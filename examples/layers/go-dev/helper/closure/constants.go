// SignatureRecord is one row of the reviewed availability inventory of VCS
// release objects. It records that the object exists and what it signs; it does
// not verify it and makes no absence claim about the modules it omits.
type SignatureRecord struct {
	Path       string
	Version    string
	Repository string
	Ref        string
	TagObject  string
	Commit     string
	Signed     SignedObject
	Format     string
}

