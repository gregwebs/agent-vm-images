// The reviewed constants of the gopls closure. They are copied from
// examples/layers/go-dev/gopls_closure.py (the Python oracle, live until #254)
// and are the reviewed record of what this closure means: the module the layer
// installs, the wrapper that selects it, the checksum-database key that
// authenticates module content and the policy strings a pin may name.

// Filename is one of the five committed inputs.
type Filename string

