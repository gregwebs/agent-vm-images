#!/usr/bin/env python3
"""Maintenance-only stager for the go-dev example's committed gopls closure.

Ordinary image builds only verify committed bytes. Selecting a new gopls release,
regenerating the module graph and adopting new checksums is a reviewed proposal on
a maintainer host: this stager resolves and verifies the whole closure with the
layer's pinned Go, cross-builds both Linux targets from the staged files with the
proxy off, and writes a candidate data directory under ``--out``.
``script/dev/upgrade-gopls.sh`` publishes it as one transaction.

It never writes to the checkout and never executes a foreign binary: a Linux
cross-build on a Darwin host is *inspected* (``go version -m -json``), not run.

    stage --gopls vX.Y.Z --go X.Y.Z --current DIR --out NEW_DIR
          [--review-determination YYYY-MM-DD --reviewer NAME]
    check DIR
    current DIR
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Mapping, Sequence

# A documented check must not write generated bytecode into the checkout.
sys.dont_write_bytecode = True
REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPOSITORY_ROOT / 'examples' / 'layers' / 'go-dev'))

import gopls_closure as model  # noqa: E402
from gopls_closure import ClosureError, refuse  # noqa: E402

DOCKERFILE = REPOSITORY_ROOT / 'examples' / 'layers' / 'go-dev' / 'Dockerfile'
# The wrapper's go directive is replaced from the root module's own directive
# before tidying, so this is only a starting value.
PLACEHOLDER_GO = '1.26.0'
# The maintenance phase resolves modules on the host, so the target variables are
# deliberately absent; the compile phase below uses the reviewed Linux target env.
MAINTENANCE_KEYS = tuple(key for key in model.CHILD_ENV_KEYS if key not in ('GOOS', 'GOARCH'))
RENEWAL = 'module-channel determination requires renewed review'
# The retained two-pass artifact: not a readable pin (its review fields are null).
PROPOSAL_FILE = 'pin.proposal.json'
GO_COMMAND_TIMEOUT_SECONDS = 1800


@dataclass(frozen=True)
class StageRequest:
    gopls: model.ReleaseVersion
    go: model.GoVersion
    current: Path
    out: Path
    reviewed_on: model.IsoDate | None
    reviewer: str | None


@dataclass(frozen=True)
class MaintenanceEnvironment:
    """Everything the stager may contact or execute, injected once.

    Production resolves the ambient host and the reviewed origins; the hermetic
    suite injects a loopback proxy, ``sumdb='off'`` for synthetic modules and
    ``in_github_actions=False``. No fixture-only flag reaches the production CLI.
    """

    proxy: str
    sumdb: str
    toolchain: str
    host_go: Path
    transport: Mapping[str, str]
    in_github_actions: bool

    @staticmethod
    def production(go: model.GoVersion) -> 'MaintenanceEnvironment':
        host_go = shutil.which('go')
        if host_go is None:
            refuse('missing prerequisite: go')
        return MaintenanceEnvironment(
            proxy=model.PROXY, sumdb=model.SUMDB, toolchain=f'go{go.value}',
            host_go=Path(os.path.realpath(host_go)),
            transport=model.production_transport(),
            in_github_actions=os.environ.get('GITHUB_ACTIONS') == 'true')

    def resolution_env(self, paths: model.BuildPaths) -> dict[str, str]:
        env = {
            'PATH': f'{os.path.dirname(self.host_go)}:{model.IMAGE_PATH}',
            'HOME': str(paths.home),
            'GOPATH': str(paths.gopath),
            'GOMODCACHE': str(paths.module_cache),
            'GOCACHE': str(paths.go_cache),
            'TMPDIR': str(paths.tmp),
            'GOENV': 'off',
            'GOWORK': 'off',
            # Resolution is exactly where a new module may be selected, so this is
            # the one place -mod=mod is correct; ordinary builds never see it.
            'GOFLAGS': '-mod=mod',
            'GOTOOLCHAIN': self.toolchain,
            'GOPROXY': self.proxy,
            'GOSUMDB': self.sumdb,
            'GONOSUMDB': '',
            'GONOPROXY': '',
            'GOPRIVATE': '',
            'GOINSECURE': '',
            'GOAUTH': 'off',
            'GOVCS': '*:off',
            'CGO_ENABLED': '0',
        }
        for key in model.TRANSPORT_KEYS:
            if key in self.transport:
                env[key] = self.transport[key]
        assert set(env) - set(model.TRANSPORT_KEYS) == set(MAINTENANCE_KEYS)
        return env

    def compile_environment(self) -> model.GoEnvironment:
        # The staged files plus the authenticated cache are proved complete with
        # the proxy off: a staging step may not hide a missing sum behind a fetch.
        return model.GoEnvironment.offline()


@dataclass(frozen=True)
class Proposal:
    out: Path
    gopls: model.ReleaseVersion
    go: model.GoVersion
    modules: tuple[tuple[str, str], ...]
    previous: tuple[tuple[str, str], ...]
    review_carried: bool
    summary: str


def hash_bytes(raw: bytes) -> model.Sha256:
    return model.Sha256(hashlib.sha256(raw).hexdigest())


def run_host_go(argv: Sequence[str], env: Mapping[str, str], cwd: Path,
                timeout: int = GO_COMMAND_TIMEOUT_SECONDS) -> subprocess.CompletedProcess:
    go = os.path.join(env['PATH'].split(os.pathsep)[0], 'go')
    return subprocess.run([go, *argv], cwd=str(cwd), env=dict(env), capture_output=True,
                          text=True, timeout=timeout)


def require(proc: subprocess.CompletedProcess, what: str) -> subprocess.CompletedProcess:
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or '').strip()
        refuse(f'{what} failed (status {proc.returncode}): {detail}')
    return proc


def review_evidence(gopls: model.ReleaseVersion) -> tuple[str, ...]:
    """The reviewed evidence set for a root version, in a fixed order."""
    return (f'{model.PROXY}/{model.ROOT}/@v/{gopls.value}.info',
            'https://go.dev/ref/mod#checksum-database',
            f'https://sum.golang.org/lookup/{model.ROOT}@{gopls.value}',
            f'https://go.googlesource.com/tools/+/refs/tags/gopls/{gopls.value}',
            model.AMENDMENT_URL,
            *model.SIGNATURE_EVIDENCE_URLS,
            model.AUTH_FOLLOW_UP_URL)


def write_bytes(path: Path, raw: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'xb') as handle:
        handle.write(raw)


def rewrite_dockerfile(raw: str, gopls: model.ReleaseVersion) -> str:
    lines = raw.split('\n')
    matches = [index for index, line in enumerate(lines) if line.startswith('ARG GOPLS_VERSION=')]
    if len(matches) != 1:
        refuse('Dockerfile: expected exactly one ARG GOPLS_VERSION line')
    lines[matches[0]] = f'ARG GOPLS_VERSION={gopls.value}'
    return '\n'.join(lines)


def selection_of(wrapper: model.WrapperGoMod,
                 sums: model.GoSum) -> model.ModuleSelection:
    modules = []
    for path, version in wrapper.requires.items():
        module = model.ModuleId(model.ModulePath(path), version)
        if module not in sums.zip:
            refuse(f'go.sum lacks h1 for {module}')
        modules.append(model.ModuleIdentity(module, sums.zip[module]))
    modules.sort(key=lambda identity: identity.id.path.value)
    return model.ModuleSelection(tuple(modules))


def license_sections(selection: model.ModuleSelection,
                     module_cache: Path) -> tuple[model.LicenseSection, ...]:
    """Collect the reviewed notice evidence from the module cache.

    Evidence transport, not a legal audit: every matching file is preserved with
    its exact bytes, and a layout this record has not reviewed is refused rather
    than blessed.
    """
    sections: list[model.LicenseSection] = []
    for identity in selection.modules:
        directory = (module_cache
                     / f'{model.escape_module(identity.id.path.value)}'
                       f'@{model.escape_module(identity.id.version.value)}')
        notices = model.collect_notices(directory, identity.id)
        roots = [relative for relative, _raw in notices if '/' not in relative]
        nested = [relative for relative, _raw in notices if '/' in relative]
        for relative, raw in notices:
            sections.append(model.LicenseSection(
                id=identity.id, name=model.RelativeNoticePath(relative),
                sha256=hash_bytes(raw), raw=raw))
        if not roots:
            refuse(f'{identity.id}: unsupported license layout; review notices and update the '
                   'ADR/layout policy before staging')
        if sorted(nested) != sorted(model.reviewed_nested_notices(identity.id)):
            refuse(f'{identity.id}: unsupported license layout; review notices and update the '
                   'ADR/layout policy before staging')
    sections.sort(key=lambda section: (section.id.path.value, section.name.value))
    return tuple(sections)


def pinned_modules(selection: model.ModuleSelection, sums: model.GoSum,
                   sections: Sequence[model.LicenseSection]) -> tuple[model.PinnedModule, ...]:
    """The selection as pin domain values, so a review can compare whole records."""
    modules = []
    for identity in selection.modules:
        licenses = tuple(
            model.LicenseFile(name=section.name, sha256=section.sha256)
            for section in sections if section.id == identity.id)
        modules.append(model.PinnedModule(
            id=identity.id, h1=identity.h1,
            # Exactly the committed go.sum /go.mod entry, which the checker
            # re-derives from the root evidence file for the root module.
            go_mod_h1=sums.mod[identity.id], licenses=licenses))
    return tuple(modules)


def pin_document(request: StageRequest, files: Mapping[str, model.Sha256],
                 modules: Sequence[model.PinnedModule],
                 signatures: Sequence[model.VcsSignatureEvidence],
                 provenance: model.Provenance, review: model.Review | None) -> dict:
    return {
        'schema': 1,
        'gopls': request.gopls.value,
        'go': request.go.value,
        'module': model.WRAPPER,
        'files': {name: files[name].value for name in model.FILE_KEYS},
        'modules': [
            {'path': module.id.path.value,
             'version': module.id.version.value,
             'h1': module.h1.value,
             'go_mod_h1': module.go_mod_h1.value,
             'licenses': [{'name': license.name.value, 'sha256': license.sha256.value}
                          for license in module.licenses]}
            for module in modules],
        'provenance': {
            'authenticated': False, 'source': provenance.source, 'vcs': provenance.vcs,
            'url': provenance.url, 'subdir': provenance.subdir, 'ref': provenance.ref,
            'hash': provenance.hash},
        'authentication': {
            'method': 'go-checksum-database',
            # The emitted record always names the reviewed production origins,
            # even from a fixture run that resolved through a loopback proxy: a
            # fabricated test record must not look like an authentication claim.
            'sumdb': model.SUMDB,
            'proxy': model.PROXY,
            'determination': model.DETERMINATION,
            # A proposal (``review is None``) has no human review yet; the writer
            # never publishes one, and the fields stay null rather than being
            # filled with a guessed date or reviewer.
            'reviewed_on': review.reviewed_on.value if review else None,
            'reviewer': review.reviewer if review else None,
            'scope': {'root': f'{model.ROOT}@{request.gopls.value}',
                      'go.mod': files[model.GO_MOD_FILE].value,
                      'go.sum': files[model.GO_SUM_FILE].value},
            'reason': model.DETERMINATION_REASON,
            'vcs_signature_policy': model.VCS_SIGNATURE_POLICY,
            'known_vcs_signatures': [
                {'path': signature.id.path.value, 'version': signature.id.version.value,
                 'repository': signature.repository, 'ref': signature.ref,
                 'tag_object': signature.tag_object, 'commit': signature.commit,
                 'signed_object': signature.signed_object.value,
                 'format': signature.format, 'verified': signature.verified}
                for signature in signatures],
            'notice_policy': model.NOTICE_POLICY,
            'follow_up': model.AUTH_FOLLOW_UP_URL,
            'evidence': list(review_evidence(request.gopls)),
            'reassess_when': model.DETERMINATION_REASSESS,
        },
    }


def stage(request: StageRequest, environment: MaintenanceEnvironment,
          dockerfile: Path = DOCKERFILE) -> Proposal:
    if environment.in_github_actions:
        refuse('stage is refused in GitHub Actions; pin maintenance is maintainer-host '
               'work and CI only runs the offline check')
    if os.path.lexists(request.out):
        refuse(f'--out must be a new invocation-owned path: {request.out}')
    previous: model.Closure | None = None
    if request.current.exists():
        if not request.current.is_dir():
            refuse(f'--current is not a directory: {request.current}')
        previous = model.load_closure(request.current)

    work = Path(tempfile.mkdtemp(prefix='gopls-stage-'))
    try:
        return _stage_into(request, environment, dockerfile, previous, work)
    finally:
        _remove(work)


def _remove(path: Path) -> None:
    """Remove the invocation's scratch tree, reporting what it could not remove."""
    failures: list[str] = []
    for directory, _names, _files in os.walk(path):
        try:
            os.chmod(directory, 0o700)
        except OSError as error:
            failures.append(f'{directory}: {error}')
    try:
        shutil.rmtree(path)
    except OSError as error:
        failures.append(f'{path}: {error}')
    if path.exists() or failures:
        print(f'gopls-closure-update: could not remove the invocation scratch tree {path}: '
              f'{"; ".join(failures) or "still present"}', file=sys.stderr)


def _stage_into(request: StageRequest, environment: MaintenanceEnvironment, dockerfile: Path,
                previous: model.Closure | None, work: Path) -> Proposal:
    paths = model.BuildPaths(work / 'build')
    paths.prepare()
    module = work / 'module'
    module.mkdir()
    (module / 'go.mod').write_text(f'module {model.WRAPPER}\n\ngo {PLACEHOLDER_GO}\n')
    env = environment.resolution_env(paths)
    version = require(run_host_go(['env', 'GOVERSION'], env, module),
                      'go env GOVERSION').stdout.strip()
    if version != request.go.toolchain():
        refuse(f'maintenance compiler is {version}, want {request.go.toolchain()}')
    for key, expected in (('GOSUMDB', environment.sumdb), ('GOPROXY', environment.proxy),
                          ('GOFLAGS', '-mod=mod')):
        actual = require(run_host_go(['env', key], env, module), f'go env {key}').stdout.strip()
        if actual != expected:
            refuse(f'maintenance environment: {key} is {actual!r}, want {expected!r}')

    require(run_host_go(['get', '-tool', f'{model.ROOT}@{request.gopls.value}'], env, module),
            'go get -tool')
    downloaded = require(run_host_go(['mod', 'download', '-json',
                                      f'{model.ROOT}@{request.gopls.value}'], env, module),
                         'go mod download')
    evidence = json.loads(downloaded.stdout)
    root_go_mod_raw = Path(evidence['GoMod']).read_bytes()
    origin = json.loads(Path(evidence['Info']).read_text()).get('Origin', {})
    root = model.parse_root_go_mod(root_go_mod_raw)
    if not model.go_language_at_most(root.go, request.go):
        refuse(f'gopls {request.gopls.value} requires go >= {root.go.value}; the layer '
               f'pins {request.go.value}')

    require(run_host_go(['mod', 'edit', f'-go={root.go.value}', '-toolchain=none'], env, module),
            'go mod edit')
    require(run_host_go(['mod', 'tidy'], env, module), 'go mod tidy')
    require(run_host_go(['mod', 'verify'], env, module), 'go mod verify')
    require(run_host_go(['mod', 'tidy', '-diff'], env, module), 'go mod tidy -diff')

    go_mod_raw = (module / 'go.mod').read_bytes()
    go_sum_raw = (module / 'go.sum').read_bytes()
    wrapper = model.parse_wrapper_go_mod(go_mod_raw)
    if model.render_go_mod(wrapper.go, wrapper.requires) != go_mod_raw:
        refuse('go mod tidy formatted go.mod differently; update render_go_mod')
    sums = model.parse_go_sum(go_sum_raw)
    for path, version_value in sorted(wrapper.requires.items()):
        if path == model.ROOT:
            continue
        model.check_adoption_restriction(model.ModulePath(path), version_value,
                                        root.requires)
    selection = selection_of(wrapper, sums)
    for identity in selection.modules:
        if identity.id not in sums.mod:
            refuse(f'go.sum lacks go.mod hash for {identity.id}')

    go_root = Path(require(run_host_go(['env', 'GOROOT'], env, module),
                           'go env GOROOT').stdout.strip())
    staged = work / 'staged'
    staged.mkdir()
    (staged / model.GO_MOD_FILE).write_bytes(go_mod_raw)
    (staged / model.GO_SUM_FILE).write_bytes(go_sum_raw)
    for arch in model.Architecture:
        target = model.Target(go_root=go_root, bin_dir=work / 'bin', share_dir=work / 'share',
                              arch=arch)
        compile_env = environment.compile_environment().child_env(target, paths, {})
        model.compile_module(staged, selection, request.go, target, compile_env, model.run_go,
                             work / f'gopls-{arch.value}')

    sections = license_sections(selection, paths.module_cache)
    licenses_raw = model.render_licenses(sections, request.gopls)
    files = {
        model.GO_MOD_FILE: hash_bytes(go_mod_raw),
        model.GO_SUM_FILE: hash_bytes(go_sum_raw),
        model.ROOT_GO_MOD_FILE: hash_bytes(root_go_mod_raw),
        model.LICENSE_FILE: hash_bytes(licenses_raw),
    }
    provenance = model.Provenance(
        authenticated=False,
        source=f'{model.PROXY}/{model.ROOT}/@v/{request.gopls.value}.info',
        vcs=origin.get('VCS', ''), url=origin.get('URL', ''), subdir=origin.get('Subdir', ''),
        ref=origin.get('Ref', ''), hash=origin.get('Hash', ''))
    signatures = model.known_signatures_for(selection)
    root_id = model.ModuleId(model.ModulePath(model.ROOT),
                             model.ModuleVersion(request.gopls.value))
    modules = pinned_modules(selection, sums, sections)
    candidate = Candidate(files=files, modules=modules, signatures=tuple(signatures),
                          go_mod=go_mod_raw, go_sum=go_sum_raw,
                          root_go_mod=root_go_mod_raw, licenses=licenses_raw)
    carried = _carried(previous, request, files, modules, signatures)
    if carried:
        assert previous is not None
        review = previous.pin.review
    else:
        if request.reviewed_on is None or request.reviewer is None:
            summary = _describe(request, previous, modules, sums, files,
                                go_directive=wrapper.go.value)
            # The proposal is the exact byte set an approved run would publish, so a
            # human reviews bytes rather than a digest summary. It is written under
            # ``--out`` (never the checkout) and ``pin.proposal.json`` is not a
            # readable pin: it has no review.
            write_candidate(request, candidate, provenance, None, dockerfile, proposal=True)
            refuse(f'{summary}\n{RENEWAL}: {_identity(previous, request)}')
        review = model.Review(
            reviewed_on=request.reviewed_on, reviewer=request.reviewer, root=root_id,
            go_mod=files[model.GO_MOD_FILE], go_sum=files[model.GO_SUM_FILE],
            determination=model.DETERMINATION, reason=model.DETERMINATION_REASON,
            evidence=review_evidence(request.gopls),
            reassess_when=model.DETERMINATION_REASSESS,
            vcs_signature_policy=model.VCS_SIGNATURE_POLICY,
            known_vcs_signatures=signatures, notice_policy=model.NOTICE_POLICY,
            follow_up=model.AUTH_FOLLOW_UP_URL)

    write_candidate(request, candidate, provenance, review, dockerfile)
    data = request.out / 'gopls-closure'
    model.load_closure(data, request.gopls, request.go)
    summary = _describe(request, previous, modules, sums, files,
                        go_directive=wrapper.go.value, carried=carried, review=review)
    write_bytes(request.out / 'summary.txt', (summary + '\n').encode())
    selected = tuple((module.id.path.value, module.id.version.value) for module in modules)
    previous_modules = tuple((module.id.path.value, module.id.version.value)
                             for module in previous.pin.modules) if previous else ()
    return Proposal(out=request.out, gopls=request.gopls, go=request.go, modules=selected,
                    previous=previous_modules, review_carried=carried, summary=summary)


@dataclass(frozen=True)
class Candidate:
    """The exact bytes an approved run publishes -- the two-pass review artifact."""

    files: Mapping[str, model.Sha256]
    modules: tuple[model.PinnedModule, ...]
    signatures: tuple[model.VcsSignatureEvidence, ...]
    go_mod: bytes
    go_sum: bytes
    root_go_mod: bytes
    licenses: bytes


def write_candidate(request: StageRequest, candidate: Candidate,
                    provenance: model.Provenance, review: model.Review | None,
                    dockerfile: Path, *, proposal: bool = False) -> None:
    # A renewed record records the inventory it reviewed; a carried one already
    # equals the candidate projection (that is why it carried).
    signatures = review.known_vcs_signatures if review else candidate.signatures
    document = pin_document(request, candidate.files, candidate.modules, signatures,
                            provenance, review)
    data = request.out / 'gopls-closure'
    write_bytes(data / model.GO_MOD_FILE, candidate.go_mod)
    write_bytes(data / model.GO_SUM_FILE, candidate.go_sum)
    write_bytes(data / model.ROOT_GO_MOD_FILE, candidate.root_go_mod)
    write_bytes(data / model.LICENSE_FILE, candidate.licenses)
    name = PROPOSAL_FILE if proposal else model.PIN_FILE
    write_bytes(data / name, (json.dumps(document, indent=2) + '\n').encode())
    write_bytes(request.out / 'Dockerfile',
                rewrite_dockerfile(dockerfile.read_text(), request.gopls).encode())


def _carried(previous: model.Closure | None, request: StageRequest,
             files: Mapping[str, model.Sha256],
             modules: Sequence[model.PinnedModule],
             signatures: Sequence[model.VcsSignatureEvidence]) -> bool:
    """Carry a review only when the *whole* reviewed scope is unchanged.

    That means the selected modules with their content and go.mod identities, the
    notice identity of every module (and therefore the transported notice bytes),
    the VCS signature inventory, and every determination/policy constant. A
    graph-only comparison would silently extend an old review over new evidence.
    """
    if previous is None:
        return False
    review = previous.pin.review
    return (previous.pin.gopls == request.gopls
            and previous.pin.modules == tuple(modules)
            and previous.pin.files[model.GO_MOD_FILE] == files[model.GO_MOD_FILE]
            and previous.pin.files[model.GO_SUM_FILE] == files[model.GO_SUM_FILE]
            and previous.pin.files[model.LICENSE_FILE] == files[model.LICENSE_FILE]
            and review.determination == model.DETERMINATION
            and review.reason == model.DETERMINATION_REASON
            and review.reassess_when == model.DETERMINATION_REASSESS
            and review.evidence == review_evidence(request.gopls)
            and review.vcs_signature_policy == model.VCS_SIGNATURE_POLICY
            and review.notice_policy == model.NOTICE_POLICY
            and review.follow_up == model.AUTH_FOLLOW_UP_URL
            and review.known_vcs_signatures == tuple(signatures))


def compare_directories(proposal_root: Path, staged_root: Path) -> None:
    """Bind an approved run to the proposal a human actually reviewed.

    All six destinations are compared -- the five closure files *and* the example
    Dockerfile, which the writer publishes in the same transaction: a proposal whose
    ARG line changed is a different proposal. The review date and reviewer are the
    only fields that may differ.
    """
    if not proposal_root.is_dir():
        refuse(f'--proposal is not a directory: {proposal_root}')
    proposal = proposal_root / 'gopls-closure'
    staged = staged_root / 'gopls-closure'
    for name in (PROPOSAL_FILE,):
        if not (proposal / name).is_file():
            refuse(f'--proposal does not look like a retained proposal: missing {name}')
    for name in (model.GO_MOD_FILE, model.GO_SUM_FILE, model.ROOT_GO_MOD_FILE,
                 model.LICENSE_FILE):
        if (proposal / name).read_bytes() != (staged / name).read_bytes():
            refuse(f'the reviewed proposal changed since it was retained: {name}')
    proposal_dockerfile = proposal_root / 'Dockerfile'
    if not proposal_dockerfile.is_file():
        refuse('--proposal does not look like a retained proposal: missing Dockerfile')
    if proposal_dockerfile.read_bytes() != (staged_root / 'Dockerfile').read_bytes():
        refuse('the reviewed proposal changed since it was retained: Dockerfile')
    proposal_document = json.loads((proposal / PROPOSAL_FILE).read_text())
    staged_document = json.loads((staged / model.PIN_FILE).read_text())
    for document in (proposal_document, staged_document):
        document['authentication']['reviewed_on'] = None
        document['authentication']['reviewer'] = None
    if proposal_document != staged_document:
        differing = sorted(key for key in set(proposal_document) | set(staged_document)
                           if proposal_document.get(key) != staged_document.get(key))
        refuse('the reviewed proposal changed since it was retained: '
               + ', '.join(differing))


def _identity(previous: model.Closure | None, request: StageRequest) -> str:
    if previous is None:
        return f'{model.ROOT}@{request.gopls.value}: no previous reviewed determination'
    return (f'{previous.pin.review.root} reviewed by {previous.pin.review.reviewer} on '
            f'{previous.pin.review.reviewed_on.value} -> {model.ROOT}@{request.gopls.value}')


def _describe(request: StageRequest, previous: model.Closure | None,
              modules: Sequence[model.PinnedModule], sums: model.GoSum,
              files: Mapping[str, model.Sha256], *,
              go_directive: str = '', carried: bool = False,
              review: model.Review | None = None) -> str:
    lines = []
    old_gopls = previous.pin.gopls.value if previous else '(none)'
    old_go = f'go{previous.pin.go.value}' if previous else '(none)'
    lines.append(f'gopls: {old_gopls} -> {request.gopls.value}')
    lines.append(f'go:    {old_go} -> go{request.go.value}')
    if go_directive:
        old_directive = previous.go_mod.go.value if previous else '(none)'
        lines.append(f'go directive: {old_directive} -> {go_directive}')

    previous_modules = ({module.id.path.value: module.id.version.value
                         for module in previous.pin.modules} if previous else {})
    current_modules = {module.id.path.value: module.id.version.value for module in modules}
    for path in sorted(set(previous_modules) | set(current_modules)):
        old = previous_modules.get(path, '(absent)')
        new = current_modules.get(path, '(absent)')
        if old != new:
            lines.append(f'module {path}: {old} -> {new}')
    unchanged = sum(1 for path in current_modules
                    if previous_modules.get(path) == current_modules[path])
    lines.append(f'modules: {len(current_modules)} selected, {unchanged} unchanged')

    previous_sum_lines = ({f'{module.path.value} {module.version.value}{suffix} {digest.value}'
                           for suffix, mapping in (('', previous.go_sum.zip),
                                                   ('/go.mod', previous.go_sum.mod))
                           for module, digest in mapping.items()} if previous else set())
    current_sum_lines = ({f'{module.path.value} {module.version.value}{suffix} {digest.value}'
                          for suffix, mapping in (('', sums.zip), ('/go.mod', sums.mod))
                          for module, digest in mapping.items()})
    added = sorted(current_sum_lines - previous_sum_lines)
    removed = sorted(previous_sum_lines - current_sum_lines)
    lines.append(f'go.sum: {len(previous_sum_lines)} -> {len(current_sum_lines)} lines, '
                 f'{len(added)} added, {len(removed)} removed')
    for entry in added:
        lines.append(f'  + {entry}')
    for entry in removed:
        lines.append(f'  - {entry}')
    for name in (model.GO_MOD_FILE, model.GO_SUM_FILE, model.ROOT_GO_MOD_FILE,
                 model.LICENSE_FILE):
        old = previous.pin.files[name].value if previous else '(absent)'
        lines.append(f'files[{name}]: {old} -> {files[name].value}')

    previous_sections = ({(module.id.path.value, license.name.value): license.sha256.value
                          for module in previous.pin.modules
                          for license in module.licenses} if previous else {})
    current_sections = {(module.id.path.value, license.name.value): license.sha256.value
                        for module in modules for license in module.licenses}
    for key in sorted(set(previous_sections) | set(current_sections)):
        old = previous_sections.get(key, '(absent)')
        new = current_sections.get(key, '(absent)')
        if old != new:
            lines.append(f'notice {key[0]} {key[1]}: {old} -> {new}')
    lines.append(f'notice files: {len(current_sections)} transported')

    signatures = model.known_signatures_for(
        model.ModuleSelection(tuple(model.ModuleIdentity(module.id, module.h1)
                                    for module in modules)))
    previous_signatures = ({signature.id: signature
                            for signature in previous.pin.review.known_vcs_signatures}
                           if previous else {})
    current_signatures = {signature.id: signature for signature in signatures}
    lines.append(f'signature inventory: {len(current_signatures)} record(s)')
    for identity in sorted(set(previous_signatures) | set(current_signatures),
                           key=lambda module_id: module_id.path.value):
        old = previous_signatures.get(identity)
        new = current_signatures.get(identity)
        if old is None:
            lines.append(f'  + {identity} {new.signed_object.value} '
                         f'{new.tag_object} -> {new.commit} ({new.ref})')
        elif new is None:
            lines.append(f'  - {identity} {old.signed_object.value} '
                         f'{old.tag_object} -> {old.commit} ({old.ref})')
        elif old != new:
            lines.append(f'  ~ {identity} {old.signed_object.value}/{old.tag_object}/'
                         f'{old.commit} -> {new.signed_object.value}/{new.tag_object}/'
                         f'{new.commit}')
    if previous is not None:
        for label, old_value, new_value in (
                ('determination', previous.pin.review.determination, model.DETERMINATION),
                ('vcs signature policy', previous.pin.review.vcs_signature_policy,
                 model.VCS_SIGNATURE_POLICY),
                ('notice policy', previous.pin.review.notice_policy, model.NOTICE_POLICY),
                ('reason', previous.pin.review.reason, model.DETERMINATION_REASON),
                ('reassess_when', previous.pin.review.reassess_when,
                 model.DETERMINATION_REASSESS)):
            if old_value != new_value:
                lines.append(f'policy {label}: changed')
                lines.append(f'  - {old_value}')
                lines.append(f'  + {new_value}')
    if review is not None:
        lines.append(f'determination: carried={carried} reviewer={review.reviewer} '
                     f'reviewed_on={review.reviewed_on.value}')
    else:
        lines.append(f'determination: proposed (carried={carried})')
    lines.append(f'scope digests: go.mod={files[model.GO_MOD_FILE].value} '
                 f'go.sum={files[model.GO_SUM_FILE].value}')
    lines.append('git diff -- examples/layers/go-dev')
    return '\n'.join(lines)


def main(argv: Sequence[str] | None = None,
         environment: MaintenanceEnvironment | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    subparsers = parser.add_subparsers(dest='command', required=True)
    stage_parser = subparsers.add_parser('stage')
    stage_parser.add_argument('--gopls', required=True)
    stage_parser.add_argument('--go', required=True)
    stage_parser.add_argument('--current', required=True)
    stage_parser.add_argument('--out', required=True)
    stage_parser.add_argument('--review-determination')
    stage_parser.add_argument('--reviewer')
    for name in ('check', 'current'):
        command = subparsers.add_parser(name)
        command.add_argument('data_dir')
    compare_parser = subparsers.add_parser('compare')
    compare_parser.add_argument('proposal_dir')
    compare_parser.add_argument('staged_dir')
    arguments = parser.parse_args(argv)
    try:
        if arguments.command == 'check':
            closure = model.load_closure(Path(arguments.data_dir))
            print(closure.pin.gopls.value)
            return 0
        if arguments.command == 'compare':
            compare_directories(Path(arguments.proposal_dir), Path(arguments.staged_dir))
            print('proposal bound: the staged bytes equal the retained proposal')
            return 0
        if arguments.command == 'current':
            closure = model.load_closure(Path(arguments.data_dir))
            print(f'gopls={closure.pin.gopls.value}')
            print(f'go={closure.pin.go.value}')
            return 0
        gopls = model.parse_release_version(arguments.gopls, '--gopls')
        go = model.parse_go_version(arguments.go, '--go')
        if arguments.review_determination is not None or arguments.reviewer is not None:
            if arguments.review_determination is None or arguments.reviewer is None:
                print('gopls-closure-update: --review-determination and --reviewer go together',
                      file=sys.stderr)
                return 2
        reviewed_on = (model.parse_date(arguments.review_determination,
                                        '--review-determination')
                       if arguments.review_determination else None)
        environment = environment or MaintenanceEnvironment.production(go)
        if environment.in_github_actions:
            print('gopls-closure-update: refusing stage in GitHub Actions; pin maintenance is '
                  'maintainer-host work', file=sys.stderr)
            return 2
        if environment.toolchain != f'go{go.value}':
            # The reviewed origins are fixed by ``production``; an injected
            # environment (the hermetic suite) may only select a different
            # transport. A toolchain disagreeing with --go is always a bug.
            print('gopls-closure-update: the maintenance toolchain does not match --go',
                  file=sys.stderr)
            return 2
        request = StageRequest(gopls=gopls, go=go, current=Path(arguments.current),
                               out=Path(arguments.out), reviewed_on=reviewed_on,
                               reviewer=arguments.reviewer)
        proposal = stage(request, environment)
    except ClosureError as error:
        print(f'gopls-closure-update: {error}', file=sys.stderr)
        return 1
    print(proposal.summary)
    return 0


if __name__ == '__main__':
    sys.exit(main())
