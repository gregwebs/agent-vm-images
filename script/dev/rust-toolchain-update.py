#!/usr/bin/env python3
"""Maintenance-only stager for the Rust example's committed toolchain closure.

Why maintenance is separate from building: an ordinary image build only verifies
committed bytes. Resolving a channel, fetching a manifest and adopting new hashes
must be a reviewed proposal on a maintainer host, and a failure anywhere in the
two-architecture closure must leave the committed sources untouched. This module
downloads and authenticates the *whole* closure into an invocation-owned scratch
directory and writes a candidate data directory there;
``script/dev/upgrade-rust-toolchain.sh`` publishes it as one transaction.

It never executes a foreign-architecture bootstrap and never writes to the
source tree.

    stage --channel EXACT --rustup EXACT --key PATH --current DIR --out NEW_DIR
          [--verify-bootstrap-exception YYYY-MM-DD --reviewer NAME]
    check INPUT_DIR
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

# A documented check must not write generated bytecode into the checkout, so
# this stands in for a caller that did not set the environment variable.
sys.dont_write_bytecode = True
REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPOSITORY_ROOT / 'examples' / 'layers' / 'rust-dev'))

import rust_toolchain as model  # noqa: E402
from rust_toolchain import Architecture, ToolchainError, refuse  # noqa: E402

DOCKERFILE = REPOSITORY_ROOT / 'examples' / 'layers' / 'rust-dev' / 'Dockerfile'
# Reviewed hash-only exception text. Both the reason and the reassessment
# condition are source, like the fingerprint policy: a bootstrap identity change
# requires a human to renew the review, and this writer refuses to invent it.
BOOTSTRAP_EXCEPTION_REASON = (
    'rustup publishes versioned per-target rustup-init binaries with a .sha256 '
    'sidecar but no detached OpenPGP signature, attestation or release object for '
    '1.28.2 (the .asc endpoints return 404 and the GitHub tag has no release). The '
    'reviewed exception binds each architecture to the exact versioned URL and '
    'SHA-256 in this record, cross-checked against the upstream .sha256 sidecar. It '
    'is hash-only: it does not authenticate the bootstrap publisher, and pinning '
    'does not establish that the release is safe.')
BOOTSTRAP_EXCEPTION_REASSESS = (
    'On each rustup-init content or identity change, or on publication of a '
    'supported upstream signing, attestation or release-provenance scheme; renew '
    'the review explicitly rather than extending this record.')
BOOTSTRAP_INSTALLATION_DOC = 'https://rust-lang.github.io/rustup/installation/other.html'


@dataclass(frozen=True)
class Proposal:
    out: Path
    channel: model.Channel
    rustup: model.Semver
    manifest_sha: str
    archives: dict[str, list[tuple[str, str, str]]]
    exception: model.BootstrapException


def bootstrap_evidence_urls(arch: Architecture, rustup: model.Semver) -> list[str]:
    url = model.expected_bootstrap_url(rustup, arch)
    return [url, url + '.sha256']


def build_exception(rustup: model.Semver, reviewed_on: model.IsoDate, reviewer: str,
                    digests: dict[Architecture, str]) -> model.BootstrapException:
    scope = {arch.platform: model.Content(
        model.parse_url(model.expected_bootstrap_url(rustup, arch), 'bootstrap'),
        model.parse_sha256(digests[arch], 'bootstrap digest')) for arch in Architecture}
    evidence = [BOOTSTRAP_INSTALLATION_DOC]
    for arch in Architecture:
        evidence.extend(bootstrap_evidence_urls(arch, rustup))
    evidence = list(dict.fromkeys(evidence))
    return model.BootstrapException(
        reviewed_on=reviewed_on, reviewer=reviewer,
        reason=BOOTSTRAP_EXCEPTION_REASON, evidence=tuple(evidence),
        reassess_when=BOOTSTRAP_EXCEPTION_REASSESS, scope=scope)


def exception_pin_node(exception: model.BootstrapException) -> dict:
    return {
        'method': 'reviewed-hash-only',
        'reviewed_on': exception.reviewed_on.value,
        'reviewer': exception.reviewer,
        'scope': {platform: {'url': content.url.value, 'sha256': content.digest.value}
                  for platform, content in exception.scope.items()},
        'reason': exception.reason,
        'evidence': list(exception.evidence),
        'reassess_when': exception.reassess_when,
    }


def exception_unchanged(previous: model.BootstrapException | None,
                        digests: dict[Architecture, str],
                        rustup: model.Semver) -> bool:
    if previous is None:
        return False
    for arch in Architecture:
        content = previous.scope[arch.platform]
        if content.url.value != model.expected_bootstrap_url(rustup, arch):
            return False
        if content.digest.value != digests[arch]:
            return False
    return True


def write_bytes(path: Path, raw: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'xb') as handle:
        handle.write(raw)


def pin_document(channel: model.Channel, release_date: model.IsoDate,
                 rustup: model.Semver, key_sha: str, trust: model.TrustPolicy,
                 manifest_url: str, manifest_sha: str, checksum_sha: str,
                 signature_sha: str, closures: dict[Architecture, dict],
                 exception: model.BootstrapException) -> dict:
    return {
        'schema': 1,
        'channel': channel.value,
        'release_date': release_date.value,
        'profile': model.PROFILE,
        'rustup_version': rustup.value,
        'trust': {
            'key': {'path': model.KEY_PATH, 'sha256': key_sha},
            'primary_fingerprint': trust.primary.value,
            'signing_fingerprints': [signer.value for signer in trust.signers],
        },
        'manifest': {
            'url': manifest_url,
            'path': model.MANIFEST_PATH,
            'sha256': manifest_sha,
            'checksum': {'url': manifest_url + '.sha256',
                         'path': model.MANIFEST_CHECKSUM_PATH, 'sha256': checksum_sha},
            'signature': {'url': manifest_url + '.asc',
                          'path': model.MANIFEST_SIGNATURE_PATH, 'sha256': signature_sha},
        },
        'platforms': {arch.platform: closures[arch] for arch in Architecture},
        'bootstrap_exception': exception_pin_node(exception),
    }


def rewrite_dockerfile(raw: str, channel: model.Channel) -> str:
    pattern = f'ARG RUST_TOOLCHAIN={channel.value}'
    lines = raw.split('\n')
    matches = [index for index, line in enumerate(lines) if line.startswith('ARG RUST_TOOLCHAIN=')]
    if len(matches) != 1:
        refuse('Dockerfile: expected exactly one ARG RUST_TOOLCHAIN line')
    lines[matches[0]] = pattern
    return '\n'.join(lines)


@dataclass(frozen=True)
class StageRequest:
    channel: model.Channel
    rustup: model.Semver
    key: Path | None
    current: Path
    out: Path
    reviewed_on: model.IsoDate | None
    reviewer: str | None


def require_maintainer_host(dependencies: model.Dependencies) -> None:
    """Stage mode resolves and adopts upstream bytes, so it is never CI work.

    Checked here as well as in the shell writer: this module is a public entrypoint
    (and an importable one), and a caller that skips the shell must still be
    refused before any network or scratch activity.
    """
    if model.in_github_actions(dependencies):
        refuse('stage mode is refused in GitHub Actions; pin maintenance is maintainer-host '
               'work and ordinary CI only runs the offline check')


def stage(request: StageRequest, dependencies: model.Dependencies,
          dockerfile: Path = DOCKERFILE) -> Proposal:
    require_maintainer_host(dependencies)
    if request.rustup.value not in model.SUPPORTED_RUSTUP_VERSIONS:
        # The exception text, format preference and installation behaviour are
        # bound to the audited installer; a different version cannot inherit them.
        refuse(f'rustup {request.rustup.value} is not an audited installer; only '
               f'{", ".join(model.SUPPORTED_RUSTUP_VERSIONS)} has a reviewed format/trust '
               'policy, so a new version needs code and policy review')
    if os.path.lexists(request.out):
        refuse(f'--out must be a new invocation-owned path: {request.out}')
    if request.out.is_symlink():
        refuse(f'--out must not be a symlink: {request.out}')
    previous = None
    if request.current.exists():
        if not request.current.is_dir():
            refuse(f'--current is not a directory: {request.current}')
        previous = model.load_pin(request.current, dependencies.trust)
        if previous.channel == request.channel and previous.rustup_version == request.rustup:
            # Not a refusal: an identical upstream proposal is how a repeated
            # maintenance run proves it is idempotent.
            pass
    key = request.key
    if key is None:
        if previous is None:
            refuse('first adoption needs --key with the reviewed Rust release key')
        key = request.current / model.KEY_PATH
    if not key.is_file() or key.is_symlink():
        refuse(f'--key must be a regular file: {key}')
    key_raw = key.read_bytes()
    key_sha = model.hash_file(key)

    # All transport, keyring and scratch state lives outside --out: the output
    # directory holds only the files the publisher will copy.
    work = Path(tempfile.mkdtemp(prefix='rust-stage-'))
    os.chmod(work, 0o700)
    try:
        return _stage_into(request, dependencies, dockerfile, previous, key, key_raw, key_sha, work)
    finally:
        shutil.rmtree(work, ignore_errors=True)


def _stage_into(request: StageRequest, dependencies: model.Dependencies, dockerfile: Path,
                previous: model.RustPin | None, key: Path, key_raw: bytes, key_sha: str,
                work: Path) -> Proposal:
    verifier = model.SignatureVerifier(dependencies.gpg, key, work, dependencies.runner,
                                       dependencies.trust)
    events = model.Events()
    download = work / 'downloads'
    download.mkdir(mode=0o700)

    manifest_url = model.parse_url(f'{model.DIST_SERVER}/dist/channel-rust-'
                                   f'{request.channel.value}.toml', 'manifest')
    for suffix in ('', '.sha256', '.asc'):
        url = model.parse_url(manifest_url.value + suffix, 'manifest evidence')
        dependencies.transport.fetch(url, download / model.MANIFEST_PATH.replace(
            'channel.toml', 'channel.toml' + suffix), 2 << 20)
    manifest_raw = (download / model.MANIFEST_PATH).read_bytes()
    checksum_raw = (download / (model.MANIFEST_PATH + '.sha256')).read_bytes()
    manifest_sha = model.hash_file(download / model.MANIFEST_PATH)
    checksum_line = model._one_checksum_line(checksum_raw, 'manifest checksum')
    if not checksum_line.startswith(manifest_sha + ' '):
        refuse('upstream manifest does not match its published .sha256 line')
    verifier.verify(download / model.MANIFEST_PATH, download / (model.MANIFEST_PATH + '.asc'),
                    'manifest signature')
    manifest = model.decode_toml(manifest_raw, 'upstream manifest')
    release_date = model.parse_date(manifest.get('date'), 'manifest.date')
    version = manifest.get('pkg', {}).get('rust', {}).get('version')
    if type(version) is not str or not version.split(' ')[0] == request.channel.value:
        refuse(f'upstream manifest describes {version!r}, not {request.channel.value}')
    if manifest.get('manifest-version') != '2':
        refuse('upstream manifest is not manifest-version 2; verifier/policy review required')

    digests: dict[Architecture, str] = {}
    bootstrap_checksum_bytes: dict[Architecture, bytes] = {}
    for arch in Architecture:
        url = model.parse_url(model.expected_bootstrap_url(request.rustup, arch), 'bootstrap')
        target = download / f'rustup-init-{arch.value}'
        dependencies.transport.fetch(url, target, model.MAX_BOOTSTRAP_BYTES)
        digests[arch] = model.hash_file(target)
        if model.elf_machine(target) != arch.elf_machine:
            refuse(f'bootstrap {arch.value}: ELF machine is not {arch.bootstrap_target}')
        checksum_target = download / f'rustup-init-{arch.value}.sha256'
        dependencies.transport.fetch(
            model.parse_url(url.value + '.sha256', 'bootstrap checksum'), checksum_target,
            model.MAX_EVIDENCE_BYTES)
        bootstrap_checksum_bytes[arch] = checksum_target.read_bytes()
        model.verify_bootstrap_checksum_line(bootstrap_checksum_bytes[arch], arch,
                                             model.parse_sha256(digests[arch], 'bootstrap'))

    if previous is not None and exception_unchanged(previous.bootstrap_exception, digests,
                                                    request.rustup):
        exception = previous.bootstrap_exception
    else:
        old = None
        if previous is not None:
            old = {arch.platform: (previous.bootstrap_exception.scope[arch.platform].digest.value,
                                   previous.bootstrap_exception.scope[arch.platform].url.value)
                   for arch in Architecture}
        if request.reviewed_on is None or request.reviewer is None:
            lines = ['hash-only bootstrap exception requires renewed review']
            for arch in Architecture:
                new = f'{model.expected_bootstrap_url(request.rustup, arch)} {digests[arch]}'
                if old is not None:
                    lines.append(f'  {arch.platform}: old {old[arch.platform][1]} '
                                 f'{old[arch.platform][0]} -> new {new}')
                else:
                    lines.append(f'  {arch.platform}: new {new}')
            refuse('\n'.join(lines))
        exception = build_exception(request.rustup, request.reviewed_on, request.reviewer,
                                    digests)

    archive_digests: dict[Architecture, list[tuple[str, str, str]]] = {}
    closures: dict[Architecture, dict] = {}
    signature_bytes: dict[str, bytes] = {}
    for arch in Architecture:
        selection = model.derive_selection(manifest, arch)
        archives = []
        archive_digests[arch] = []
        for package, target in selection:
            entry = model.manifest_entry(manifest, package, target)
            url_text = model.expected_archive_url(request.channel, release_date, package, target)
            if entry['xz_url'] != url_text:
                refuse(f'manifest: {package} {target.value} xz_url {entry["xz_url"]} != {url_text}')
            url = model.parse_url(url_text, 'archive')
            target_path = download / url.filename
            dependencies.transport.fetch(url, target_path, model.MAX_ARCHIVE_BYTES)
            digest = model.hash_file(target_path)
            if digest != entry['xz_hash']:
                refuse(f'{url.filename}: downloaded bytes do not match the manifest hash')
            signature_path = download / (url.filename + '.asc')
            dependencies.transport.fetch(model.parse_url(url.value + '.asc', 'signature'),
                                         signature_path, model.MAX_EVIDENCE_BYTES)
            verifier.verify(target_path, signature_path, f'{url.filename} signature')
            evidence_path = model.expected_signature_path(arch, package, target)
            signature_bytes[evidence_path] = signature_path.read_bytes()
            payload = model.ComponentArchive(
                package=package, target=target,
                content=model.Content(url, model.Sha256(digest)),
                member_prefix=model.MemberPrefix(
                    model.archive_filename(request.channel, package, target)[:-len('.tar.xz')]
                    + '/'),
                signature=model.Evidence(
                    model.EvidencePath(evidence_path),
                    model.Sha256(model.sha_of_bytes(signature_bytes[evidence_path]))))
            model.preflight_archive(target_path, payload, events)
            archives.append({
                'package': package,
                'target': target.value,
                'url': url.value,
                'sha256': digest,
                'member_prefix': payload.member_prefix.value,
                'signature': {'path': evidence_path,
                              'sha256': payload.signature.digest.value},
            })
            archive_digests[arch].append((package, target.value, digest))
        closures[arch] = {
            'host': arch.host.value,
            'musl': arch.musl.value,
            'bootstrap': {
                'url': model.expected_bootstrap_url(request.rustup, arch),
                'sha256': digests[arch],
                'checksum': {
                    'path': model.expected_bootstrap_checksum_path(arch),
                    'sha256': model.sha_of_bytes(bootstrap_checksum_bytes[arch]),
                },
            },
            'archives': archives,
        }

    document = pin_document(request.channel, release_date, request.rustup, key_sha,
                            dependencies.trust,
                            manifest_url.value, manifest_sha,
                            model.sha_of_bytes(checksum_raw),
                            model.sha_of_bytes((download / (model.MANIFEST_PATH + '.asc')).read_bytes()),
                            closures, exception)
    data = request.out / 'rust-toolchain'
    write_bytes(data / model.MANIFEST_PATH, manifest_raw)
    write_bytes(data / model.MANIFEST_CHECKSUM_PATH, checksum_raw)
    write_bytes(data / model.MANIFEST_SIGNATURE_PATH,
                (download / (model.MANIFEST_PATH + '.asc')).read_bytes())
    write_bytes(data / model.KEY_PATH, key_raw)
    for arch in Architecture:
        write_bytes(data / model.expected_bootstrap_checksum_path(arch),
                    bootstrap_checksum_bytes[arch])
    for evidence_path, raw in sorted(signature_bytes.items()):
        write_bytes(data / evidence_path, raw)
    write_bytes(data / model.PIN_FILE,
                (json.dumps(document, indent=2) + '\n').encode())
    write_bytes(request.out / 'Dockerfile',
                rewrite_dockerfile(dockerfile.read_text(), request.channel).encode())

    candidate = model.load_pin(data, dependencies.trust)
    model.verify_inputs(data, candidate, verifier)
    for arch in Architecture:
        if candidate.closure(arch).arch is not arch:
            refuse(f'candidate pin is missing {arch.platform}')
    return Proposal(out=request.out, channel=request.channel, rustup=request.rustup,
                    manifest_sha=manifest_sha, archives=archive_digests, exception=exception)


def describe(proposal: Proposal, previous: model.RustPin | None) -> str:
    lines = []
    old_channel = previous.channel.value if previous else '(none)'
    old_rustup = previous.rustup_version.value if previous else '(none)'
    lines.append(f'channel: {old_channel} -> {proposal.channel.value}')
    lines.append(f'rustup:  {old_rustup} -> {proposal.rustup.value}')
    lines.append(f'manifest sha256: {proposal.manifest_sha}')
    for arch in Architecture:
        for package, target, digest in proposal.archives[arch]:
            lines.append(f'{arch.platform} {package} {target}: {digest}')
    lines.append(f'bootstrap exception: {proposal.exception.reviewer} '
                 f'{proposal.exception.reviewed_on.value}')
    for arch in Architecture:
        content = proposal.exception.scope[arch.platform]
        lines.append(f'{arch.platform} bootstrap: {content.url.value} {content.digest.value}')
    return '\n'.join(lines)


def main(argv: Sequence[str] | None = None,
         dependencies: model.Dependencies | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    subparsers = parser.add_subparsers(dest='command', required=True)
    stage_parser = subparsers.add_parser('stage')
    stage_parser.add_argument('--channel', required=True)
    stage_parser.add_argument('--rustup')
    stage_parser.add_argument('--key')
    stage_parser.add_argument('--current', required=True)
    stage_parser.add_argument('--out', required=True)
    stage_parser.add_argument('--verify-bootstrap-exception')
    stage_parser.add_argument('--reviewer')
    check_parser = subparsers.add_parser('check')
    check_parser.add_argument('input_dir')
    current_parser = subparsers.add_parser('current')
    current_parser.add_argument('input_dir')
    arguments = parser.parse_args(argv)
    dependencies = dependencies or model.Dependencies.production()
    if arguments.command == 'check':
        return model.main(['check', arguments.input_dir], dependencies)
    if arguments.command == 'current':
        pin = model.load_pin(Path(arguments.input_dir), dependencies.trust)
        print(f'channel={pin.channel.value}')
        print(f'rustup={pin.rustup_version.value}')
        print(f'reviewed_on={pin.bootstrap_exception.reviewed_on.value}')
        print(f'reviewer={pin.bootstrap_exception.reviewer}')
        return 0
    if model.in_github_actions(dependencies):
        print('rust-toolchain-update: refusing stage in GitHub Actions; pin maintenance is '
              'maintainer-host work and ordinary CI only runs the offline check',
              file=sys.stderr)
        return 2
    previous = None
    current = Path(arguments.current)
    if current.is_dir():
        try:
            previous = model.load_pin(current, dependencies.trust)
        except ToolchainError:
            previous = None
    rustup = arguments.rustup
    if rustup is None:
        if previous is None:
            print('rust-toolchain-update: first adoption needs --rustup VERSION', file=sys.stderr)
            return 2
        rustup = previous.rustup_version.value
    request = StageRequest(
        channel=model.parse_channel(arguments.channel, '--channel'),
        rustup=model.parse_semver(rustup, '--rustup'),
        key=Path(arguments.key) if arguments.key else None,
        current=current,
        out=Path(arguments.out),
        reviewed_on=(model.parse_date(arguments.verify_bootstrap_exception,
                                      '--verify-bootstrap-exception')
                     if arguments.verify_bootstrap_exception else None),
        reviewer=arguments.reviewer)
    try:
        proposal = stage(request, dependencies)
    except ToolchainError as error:
        print(f'rust-toolchain-update: {error}', file=sys.stderr)
        return 1
    print(describe(proposal, previous))
    return 0


if __name__ == '__main__':
    sys.exit(main())
