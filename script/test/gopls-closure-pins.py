def mutant_module(name: str, replacements: Sequence[tuple[str, str]], directory: Path):
    """A scratch copy of the shipped helper with the named edits applied.

    Same seam the #102 suites use: mutating the *production* source is how a failure
    branch that needs a real filesystem error is reached without changing the shipped
    code or weakening a check.
    """
    import importlib.util

    source = (MODEL_DIRECTORY / 'gopls_closure.py').read_text()
    for old, new in replacements:
        if old not in source:
            raise AssertionError(f'mutant {name}: pattern not found: {old[:60]!r}')
        source = source.replace(old, new, 1)
    # The checkout is read-only inside the boundary (by design), so the mutant lives
    # in the invocation's own writable scratch.
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f'{name}.py'
    path.write_text(source)
    spec = importlib.util.spec_from_file_location(f'gopls_closure_{name}', path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    previous = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = previous
    return module


