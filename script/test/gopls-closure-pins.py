    import fixture as fixture_module

    updater = fixture_module.updater
    request = updater.StageRequest(
        gopls=model.ReleaseVersion('v0.0.1'), go=model.GoVersion('1.27.3'),
        current=fixture.workspace / 'no-current', out=fixture.workspace / 'carry-out',
        reviewed_on=model.IsoDate('2026-01-02'), reviewer='fixture-reviewer')
    files = dict(closure.pin.files)
    modules = closure.pin.modules
    signatures = closure.pin.review.known_vcs_signatures

    check('an identical scope carries the review',
          updater._carried(closure, request, files, modules, signatures))
    check('a Go-only bump carries the review',
          updater._carried(closure, dataclasses.replace(request, go=model.GoVersion('1.26.5')),
                           files, modules, signatures))
    changed_notice = dict(files)
    changed_notice[model.LICENSE_FILE] = model.Sha256('0' * 64)
    check('a notice-bytes change does not carry',
          not updater._carried(closure, request, changed_notice, modules, signatures))
    mutated_modules = list(modules)
    drifted = mutated_modules[0]
    mutated_modules[0] = dataclasses.replace(
        drifted, licenses=tuple(dataclasses.replace(license, sha256=model.Sha256('1' * 64))
                                for license in drifted.licenses))
    check('a notice-identity change does not carry',
          not updater._carried(closure, request, files, tuple(mutated_modules), signatures))
    # The synthetic closure selects no inventoried module, so a signature change
    # is expressed with a hand-built record rather than a slice of an empty list.
    synthetic = model.VcsSignatureEvidence(
        id=model.ModuleId(model.ModulePath('example.test/dep'),
                          model.ModuleVersion('v1.0.0')),
        repository='https://example.test/dep', ref='refs/tags/v1.0.0',
        tag_object='0' * 40, commit='1' * 40, signed_object=model.SignedObject.TAG,
        format='ssh', verified=False)
    check('an added signature record does not carry',
          not updater._carried(closure, request, files, modules, signatures + (synthetic,)))
    with_signature = dataclasses.replace(
        closure, pin=dataclasses.replace(
            closure.pin, review=dataclasses.replace(
                closure.pin.review, known_vcs_signatures=(synthetic,))))
    check('a dropped signature record does not carry',
          not updater._carried(with_signature, request, files, modules, signatures))
    changed_graph = list(modules)
    changed_graph[0] = dataclasses.replace(
        changed_graph[0], h1=model.H1('h1:' + 'A' * 43 + '='))
    check('a module-content change does not carry',
          not updater._carried(closure, request, files, tuple(changed_graph), signatures))
    original_reason = model.DETERMINATION_REASON
    original_policy = model.VCS_SIGNATURE_POLICY
    model.DETERMINATION_REASON = original_reason + ' (revised)'
    try:
        check('a rationale/policy change does not carry',
              not updater._carried(closure, request, files, modules, signatures))
    finally:
        model.DETERMINATION_REASON = original_reason
    model.VCS_SIGNATURE_POLICY = 'inventoried-not-used-v2'
    try:
        check('a VCS signature policy change does not carry',
              not updater._carried(closure, request, files, modules, signatures))
    finally:
        model.VCS_SIGNATURE_POLICY = original_policy
    check('the constants were restored',
          model.DETERMINATION_REASON == original_reason
          and model.VCS_SIGNATURE_POLICY == original_policy)


