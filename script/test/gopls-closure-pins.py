def test_environment() -> None:
    import gopls_closure as model

    print('environment: constructed from scratch, never inherited')
    target = model.Target(go_root=Path('/opt/go'), bin_dir=Path('/opt/go-tools/bin'),
                          share_dir=Path('/opt/go-tools/share/gopls'),
                          arch=model.Architecture.ARM64)
    paths = model.BuildPaths(Path('/tmp/gopls-closure-env'))
    env = model.GoEnvironment.production().child_env(target, paths, {})
    check('the key set is exactly the reviewed allowlist',
          set(env) == set(model.CHILD_ENV_KEYS), f'({sorted(set(env) ^ set(model.CHILD_ENV_KEYS))})')
    check('the pinned go root is the only tool directory',
          env['PATH'].startswith('/opt/go/bin:'))
    check('GOENV/GOWORK/GOTOOLCHAIN are closed',
          (env['GOENV'], env['GOWORK'], env['GOTOOLCHAIN']) == ('off', 'off', 'local'))
    check('GOFLAGS is empty so nothing ambient can add -mod=mod', env['GOFLAGS'] == '')
    check('no checksum or proxy exemption survives',
          not any(env[key] for key in ('GONOSUMDB', 'GONOPROXY', 'GOPRIVATE', 'GOINSECURE')))
    check('the target is explicit and is Linux', (env['GOOS'], env['GOARCH']) == ('linux', 'arm64'))
    check('cgo stays off for gopls', env['CGO_ENABLED'] == '0')

    transport_keys = {'HTTP_PROXY', 'https_proxy', 'SSL_CERT_FILE', 'SSL_CERT_DIR'}
    wide = model.GoEnvironment.production().child_env(
        target, paths, {key: 'value' for key in model.TRANSPORT_KEYS} | {'GOOS': 'darwin'})
    check('only transport keys may be added, and they cannot override the target',
          set(wide) - set(model.CHILD_ENV_KEYS) == set(model.TRANSPORT_KEYS)
          and wide['GOOS'] == 'linux' and wide['GOARCH'] == 'arm64')
    check('the production adapter selects only the documented transport keys',
          set(model.production_transport()) <= set(model.TRANSPORT_KEYS))
    # The production adapter reads the ambient environment; a hostile ambient set
    # must still contribute nothing outside the transport subset. This asserts the
    # shipped function's behaviour, not a local literal.
    previous = {key: os.environ.get(key) for key in
                ('GOPROXY', 'GOFLAGS', 'GOTOOLCHAIN', 'GOOS', 'GOARCH')
                + model.TRANSPORT_KEYS}
    for key in model.TRANSPORT_KEYS:
        os.environ.pop(key, None)
    os.environ.update({'GOPROXY': 'direct', 'GOFLAGS': '-mod=mod', 'GOTOOLCHAIN': 'auto',
                       'GOOS': 'darwin', 'GOARCH': '386', 'HTTPS_PROXY': 'http://h:1',
                       'SSL_CERT_DIR': '/nonexistent'})
    try:
        produced = model.production_transport()
        env = model.GoEnvironment.production().child_env(target, paths, produced)
        check('the production adapter contributes only transport keys and they must be '
              'carried, not dropped',
              set(produced) == {'HTTPS_PROXY', 'SSL_CERT_DIR'}
              and env['HTTPS_PROXY'] == 'http://h:1' and env['SSL_CERT_DIR'] == '/nonexistent',
              f'({sorted(produced)})')
        check('hostile ambient Go settings never reach the child through that adapter',
              (env['GOPROXY'], env['GOFLAGS'], env['GOTOOLCHAIN'])
              == (model.PROXY, '', 'local'))
        check('the validated target wins over the ambient GOOS/GOARCH',
              (env['GOOS'], env['GOARCH']) == ('linux', 'arm64'))
    finally:
        for key, value in previous.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def test_build_info() -> None:
    import gopls_closure as model

    print('build info: strict parse and the reviewed Linux target settings')
    selection = sample_selection()
    for arch in (model.Architecture.ARM64, model.Architecture.AMD64):
        info = model.parse_build_info(json.dumps(build_info_document(arch.value)))
        model.verify_module_build_info(selection, info, arch, model.GoVersion('1.27.3'))
        check(f'{arch.value}: a correct Linux build info passes', True)

    def refuses_info(name: str, document: dict, expected: str,
                     arch: model.Architecture = model.Architecture.ARM64) -> None:
        refuses(name, lambda: model.verify_module_build_info(
            selection, model.parse_build_info(json.dumps(document)), arch,
            model.GoVersion('1.27.3')), expected)

    mutated = build_info_document()
    mutated['Settings'].append({'Key': 'GOEXPERIMENT', 'Value': 'none'})
    info = model.parse_build_info(json.dumps(mutated))
    refuses('an unknown build setting is a compatibility tripwire',
            lambda: model.verify_module_build_info(selection, info,
                                                   model.Architecture.ARM64,
                                                   model.GoVersion('1.27.3')),
            'build settings differ')

    changed = build_info_document()
    for item in changed['Settings']:
        if item['Key'] == 'DefaultGODEBUG':
            item['Value'] = 'tracebacklabels=1'
    refuses_info('a changed DefaultGODEBUG is refused', changed, 'build settings differ')
    refuses_info('a Darwin build is refused', build_info_document(settings=[
        {'Key': '-buildmode', 'Value': 'exe'}, {'Key': '-compiler', 'Value': 'gc'},
        {'Key': '-trimpath', 'Value': 'true'},
        {'Key': 'DefaultGODEBUG', 'Value': 'tracebacklabels=0,x509sslcertoverrideplatform=0'},
        {'Key': 'CGO_ENABLED', 'Value': '0'}, {'Key': 'GOARCH', 'Value': 'arm64'},
        {'Key': 'GOOS', 'Value': 'darwin'}, {'Key': 'GOARM64', 'Value': 'v8.0'}]),
        'build settings differ')
    refuses_info('a different feature level is refused', build_info_document(settings=[
        {'Key': '-buildmode', 'Value': 'exe'}, {'Key': '-compiler', 'Value': 'gc'},
        {'Key': '-trimpath', 'Value': 'true'},
        {'Key': 'DefaultGODEBUG', 'Value': 'tracebacklabels=0,x509sslcertoverrideplatform=0'},
        {'Key': 'CGO_ENABLED', 'Value': '0'}, {'Key': 'GOARCH', 'Value': 'arm64'},
        {'Key': 'GOOS', 'Value': 'linux'}, {'Key': 'GOARM64', 'Value': 'v9.0'}]),
        'build settings differ')
    replacement = build_info_document()
    replacement['Deps'][0]['Replace'] = {'Path': 'example.test/evil', 'Version': 'v9.9.9',
                                         'Sum': h1_of('evil')}
    refuses('a module replacement is refused', 
            lambda: model.parse_build_info(json.dumps(replacement)), 'module replacement')
    duplicate = build_info_document()
    duplicate['Deps'].append(dict(duplicate['Deps'][0]))
    refuses('a duplicate dependency is refused',
            lambda: model.parse_build_info(json.dumps(duplicate)), 'duplicate dependency')
    duplicate_setting = build_info_document()
    duplicate_setting['Settings'].append(dict(duplicate_setting['Settings'][0]))
    refuses('a duplicate setting is refused',
            lambda: model.parse_build_info(json.dumps(duplicate_setting)),
            'duplicate setting')
    extra = build_info_document()
    extra['Deps'].append({'Path': 'example.test/extra', 'Version': 'v1.0.0',
                          'Sum': h1_of('extra')})
    refuses_info('an unreviewed extra dependency is refused', extra, 'not in the reviewed closure')
    refuses_info('a missing dependency is refused', build_info_document(deps=[]),
                 'from the reviewed closure')
    wrong_sum = build_info_document()
    wrong_sum['Deps'][0]['Sum'] = h1_of('different content')
    refuses_info('a different module content hash is refused', wrong_sum,
                 'not the reviewed content')
    wrong_version = build_info_document(deps=[{'Path': 'example.test/dep', 'Version': 'v1.1.0',
                                               'Sum': h1_of('zip example.test/dep v1.0.0')}])
    refuses_info('a different selected version is refused', wrong_version,
                 'not in the reviewed closure')
    wrong_root = build_info_document(main={'Path': 'golang.org/x/tools/gopls',
                                          'Version': 'v0.0.1', 'Sum': h1_of('other root')})
    refuses_info('a different root content hash is refused', wrong_root,
                 'not the reviewed root')
    refuses('a wrong compiler is refused', lambda: model.verify_module_build_info(
        selection, model.parse_build_info(json.dumps(build_info_document())),
        model.Architecture.ARM64, model.GoVersion('1.26.5')), 'compiler is go1.27.3, want go1.26.5')


# --- P1: the offline checker --------------------------------------------------
def test_check_positive(root: Path) -> None:
    import gopls_closure as model

    print('check: a coherent minimal record loads')
    directory = fresh_records(root, 'positive')
    closure = model.load_closure(directory, model.ReleaseVersion('v0.0.1'),
                                 model.GoVersion('1.27.3'))
    check('the root go.mod evidence is bound by go.sum',
          model.h1_go_mod((directory / 'gopls.go.mod').read_bytes())
          == closure.go_sum.mod[model.ModuleId(model.ModulePath(model.ROOT),
                                               model.ModuleVersion('v0.0.1'))])
    check('the reviewed set equals the wrapper requirements',
          {module.id.path.value for module in closure.pin.modules}
          == set(closure.go_mod.requires))
    check('the emitted synthetic record carries the production constants',
          closure.pin.review.determination == model.DETERMINATION
          and closure.pin.review.follow_up == model.AUTH_FOLLOW_UP_URL)
    check('an unlisted synthetic selection projects an empty signature inventory',
          closure.pin.review.known_vcs_signatures == ())

    def mutated(name: str, change, expected: str, **keywords) -> None:
        directory = fresh_records(root, name, **keywords)
        change(directory)
        refuses(name.replace('-', ' '), lambda: model.load_closure(directory), expected)

    def edit_json(directory: Path, edit) -> None:
        document = json.loads((directory / 'pin.json').read_text())
        edit(document)
        (directory / 'pin.json').write_text(json.dumps(document, indent=2) + '\n')

    mutated('missing-pin', lambda directory: (directory / 'pin.json').unlink(),
            'missing input: pin.json')
    mutated('extra-file', lambda directory: (directory / '.extra').write_text('x'),
            'unreviewed input: .extra')
    def symlink_sum(directory: Path) -> None:
        outside = directory.parent / f'{directory.name}-outside-sum'
        outside.write_bytes((directory / 'go.sum').read_bytes())
        (directory / 'go.sum').unlink()
        (directory / 'go.sum').symlink_to(outside)

    mutated('symlink-sum', symlink_sum, 'symlink go.sum')
    mutated('digest', lambda directory: (directory / 'go.sum').write_bytes(
        (directory / 'go.sum').read_bytes() + b'\n'), 'bytes differ from the committed digest')

    def append_bogus_sum(directory: Path) -> None:
        (directory / 'go.sum').write_bytes(
            (directory / 'go.sum').read_bytes() + b'bogus line\n')
        repin(directory)

    mutated('sum-malformed', append_bogus_sum, 'go.sum: malformed')

    def unsorted_sum(directory: Path) -> None:
        lines = (directory / 'go.sum').read_text().splitlines(keepends=True)
        (directory / 'go.sum').write_text(''.join(reversed(lines)))
        repin(directory)

    mutated('sum-unsorted', unsorted_sum, 'unsorted or duplicated')

    def conflicting_sum(directory: Path) -> None:
        text = (directory / 'go.sum').read_text()
        (directory / 'go.sum').write_text(
            text + 'example.test/dep v1.0.0 h1:BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB=\n')
        repin(directory)

    mutated('sum-conflicting', conflicting_sum, 'conflicting h1')

    def drop_zip_h1(directory: Path) -> None:
        lines = (directory / 'go.sum').read_text().splitlines(keepends=True)
        (directory / 'go.sum').write_text(''.join(
            line for line in lines if 'example.test/dep v1.0.0 h1:' not in line))
        repin(directory)

    mutated('absent-h1', drop_zip_h1, 'go.sum lacks h1 for example.test/dep@v1.0.0')

    def drop_mod_h1(directory: Path) -> None:
        lines = (directory / 'go.sum').read_text().splitlines(keepends=True)
        (directory / 'go.sum').write_text(''.join(
            line for line in lines
            if 'example.test/dep v1.0.0/go.mod h1:' not in line))
        repin(directory)

    mutated('absent-go-mod-h1', drop_mod_h1, 'go.sum lacks go.mod hash for example.test/dep@v1.0.0')

    def wrong_h1(directory: Path) -> None:
        document = json.loads((directory / 'pin.json').read_text())
        document['modules'][0]['h1'] = h1_of('unreviewed content')
        (directory / 'pin.json').write_text(json.dumps(document, indent=2) + '\n')

    mutated('pin-h1-mismatch', wrong_h1, 'h1 differs from go.sum')

    def add_replace(directory: Path) -> None:
        (directory / 'go.mod').write_bytes(
            (directory / 'go.mod').read_bytes() + b'\nreplace example.test/dep => example.test/evil v1.0.0\n')
        repin(directory)

    mutated('replace', add_replace, 'directive not allowed: replace')

    def add_toolchain(directory: Path) -> None:
        (directory / 'go.mod').write_bytes(
            (directory / 'go.mod').read_bytes() + b'\ntoolchain go1.99.0\n')
        repin(directory)

    mutated('toolchain', add_toolchain, 'directive not allowed: toolchain')

    def newer_go(directory: Path) -> None:
        (directory / 'go.mod').write_bytes(
            (directory / 'go.mod').read_bytes().replace(b'go 1.26.0', b'go 1.99.0'))
        repin(directory)

    mutated('newer-go', newer_go, 'go directive')

