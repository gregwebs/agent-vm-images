Failures: list[str] = []
Passed = 0
NotRun: list[str] = []


def check(name: str, condition: bool, detail: str = '') -> None:
    global Passed
    if condition:
        Passed += 1
        print(f'  ok   {name}')
        return
    Failures.append(name)
    print(f'  FAIL {name} {detail}')


def not_run(name: str, reason: str) -> None:
    NotRun.append(name)
    print(f'  SKIP {name} ({reason})')


def refuses(name: str, action, expected: str) -> None:
    import gopls_closure as model

    try:
        action()
    except model.ClosureError as error:
        message = str(error)
        check(name, expected in message, f'(refused with "{message}")')
        return
    except Exception:  # noqa: BLE001 - an unexpected exception is a failing case
        check(name, False, traceback.format_exc().splitlines()[-1])
        return
    check(name, False, '(no refusal)')


def h1_of(text: str) -> str:
    return 'h1:' + base64.b64encode(hashlib.sha256(text.encode()).digest()).decode()


