def test_scratch_removal() -> None:
    """The suite's own cleanup must remove what a real Go build leaves behind.

    Go writes its module and build caches with read-only directories and files, so
    the cleanup this suite used to run (``shutil.rmtree(..., ignore_errors=True)``)
    reported success and left the whole tree on disk. The fixture helper is the
    replacement; the plain call is kept here as the control that it is needed.
    """
    print('scratch: a read-only tree is removed, not leaked')
    tree = Path(tempfile.mkdtemp(prefix='gopls-closure-scratch-control-'))
    module = tree / 'pkg' / 'mod' / 'example.test' / 'dep@v1.0.0'
    module.mkdir(parents=True)
    source = module / 'dep.go'
    source.write_bytes(b'package dep\n')
    os.chmod(source, 0o444)
    os.chmod(module, 0o555)
    os.chmod(module.parent, 0o555)
    if os.geteuid() != 0:
        # Root ignores the permission bits, so the defect is a non-root property.
        plain = 0
        try:
            shutil.rmtree(tree)
        except OSError:
            plain = 1
        check('a plain rmtree cannot remove the read-only tree',
              plain == 1 and os.path.lexists(tree), f'(still present: {os.path.lexists(tree)})')
    check('remove_tree leaves nothing behind',
          remove_tree(tree) == [] and not os.path.lexists(tree))


