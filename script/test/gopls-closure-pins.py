# Deliberately independent of the maintenance stager: the offline checker is
# proved against records this suite serialized itself, so a stager bug cannot
# make the checker look correct.
def synthetic_records(dep_version: str = 'v1.0.0', gopls: str = 'v0.0.1',
                      requires: dict[str, str] | None = None,
                      root_requires: dict[str, str] | None = None) -> dict:
    import gopls_closure as model

    requires = requires or {'example.test/dep': dep_version, model.ROOT: gopls}
    root_requires = root_requires or {'example.test/dep': dep_version}
    go_mod = model.render_go_mod(
        model.GoLanguage('1.26.0'),
        {path: model.ModuleVersion(version) for path, version in requires.items()})
    root_go_mod = (f'module {model.ROOT}\n\ngo 1.26.0\n\nrequire (\n'
                   + ''.join(f'\t{path} {version}\n'
                             for path, version in root_requires.items())
                   + ')\n')
    root_go_mod_raw = root_go_mod.encode()
    selected = {'example.test/dep': dep_version, model.ROOT: gopls}
    zip_sums = {path: h1_of(f'zip {path} {version}') for path, version in selected.items()}
    mod_sums = {path: (model.h1_go_mod(root_go_mod_raw).value if path == model.ROOT
                       else h1_of(f'mod {path} {version}'))
                for path, version in selected.items()}
    lines = []
    for path, version in selected.items():
        lines.append((path, version, False, zip_sums[path]))
        lines.append((path, version, True, mod_sums[path]))
    lines.sort(key=lambda line: (line[0], model.semver_sort_key(line[1]), 1 if line[2] else 0))
    go_sum = ''.join(f'{path} {version}{"/go.mod" if is_mod else ""} {digest}\n'
                     for path, version, is_mod, digest in lines)
    sections = []
    for path in sorted(selected):
        body = f'{path} {selected[path]} license text\n'.encode()
        sections.append(model.LicenseSection(
            id=model.ModuleId(model.ModulePath(path), model.ModuleVersion(selected[path])),
            name=model.RelativeNoticePath('LICENSE'),
            sha256=model.Sha256(hashlib.sha256(body).hexdigest()), raw=body))
    licenses = model.render_licenses(sections, model.ReleaseVersion(gopls))
    files = {'go.mod': go_mod, 'go.sum': go_sum.encode(), 'gopls.go.mod': root_go_mod_raw,
             'THIRD_PARTY_LICENSES': licenses}
    digests = {name: hashlib.sha256(raw).hexdigest() for name, raw in files.items()}
    modules = [{'path': path, 'version': selected[path], 'h1': zip_sums[path],
                'go_mod_h1': mod_sums[path],
                'licenses': [{'name': 'LICENSE',
                              'sha256': hashlib.sha256(
                                  f'{path} {selected[path]} license text\n'.encode()).hexdigest()}]}
               for path in sorted(selected)]
    pin = {
        'schema': 1,
        'gopls': gopls,
        'go': '1.27.3',
        'module': model.WRAPPER,
        'files': digests,
        'modules': modules,
        'provenance': {
            'authenticated': False,
            'source': f'{model.PROXY}/{model.ROOT}/@v/{gopls}.info',
            'vcs': 'git', 'url': 'https://go.googlesource.com/tools', 'subdir': 'gopls',
            'ref': 'refs/tags/gopls/v0.0.1',
            'hash': '014f87ff5c01915bc90f4f11a6bb8aea3e0edbd7'},
        'authentication': {
            'method': 'go-checksum-database',
            'sumdb': model.SUMDB,
            'proxy': model.PROXY,
            'determination': model.DETERMINATION,
            'reviewed_on': '2026-01-02',
            'reviewer': 'fixture-reviewer',
            'scope': {'root': f'{model.ROOT}@{gopls}',
                      'go.mod': digests['go.mod'], 'go.sum': digests['go.sum']},
            'reason': model.DETERMINATION_REASON,
            'vcs_signature_policy': model.VCS_SIGNATURE_POLICY,
            'known_vcs_signatures': [],
            'notice_policy': model.NOTICE_POLICY,
            'follow_up': model.AUTH_FOLLOW_UP_URL,
            'evidence': [f'{model.PROXY}/{model.ROOT}/@v/{gopls}.info'],
            'reassess_when': model.DETERMINATION_REASSESS},
    }
    return {'files': files, 'pin': pin}


def write_records(directory: Path, records: dict) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    for name, raw in records['files'].items():
        (directory / name).write_bytes(raw)
    (directory / 'pin.json').write_text(json.dumps(records['pin'], indent=2) + '\n')
    return directory


def fresh_records(root: Path, name: str, **keywords) -> Path:
    return write_records(root / name, synthetic_records(**keywords))


def repin(directory: Path) -> None:
    """Recompute only the file digests and the review scope of a test tree.

    A semantic mutation has to reach its intended rule instead of stopping at a
    stale digest; the module ``h1`` values are deliberately left alone so the
    checksum cases still test what they name.
    """
    import gopls_closure as model

    document = json.loads((directory / 'pin.json').read_text())
    for name in model.FILE_KEYS:
        document['files'][name] = hashlib.sha256((directory / name).read_bytes()).hexdigest()
    document['authentication']['scope']['go.mod'] = document['files']['go.mod']
    document['authentication']['scope']['go.sum'] = document['files']['go.sum']
    (directory / 'pin.json').write_text(json.dumps(document, indent=2) + '\n')


# --- build info samples (shape captured from the real Go 1.27.3) --------------
def build_info_document(arch: str = 'arm64', go_version: str = 'go1.27.3',
                        settings: list[dict] | None = None,
                        main: dict | None = None, deps: list[dict] | None = None) -> dict:
    if settings is None:
        settings = [
            {'Key': '-buildmode', 'Value': 'exe'},
            {'Key': '-compiler', 'Value': 'gc'},
            {'Key': '-trimpath', 'Value': 'true'},
            {'Key': 'DefaultGODEBUG',
             'Value': 'tracebacklabels=0,x509sslcertoverrideplatform=0'},
            {'Key': 'CGO_ENABLED', 'Value': '0'},
            {'Key': 'GOARCH', 'Value': arch},
            {'Key': 'GOOS', 'Value': 'linux'},
            {'Key': 'GOARM64' if arch == 'arm64' else 'GOAMD64',
             'Value': 'v8.0' if arch == 'arm64' else 'v1'},
        ]
    return {
        'GoVersion': go_version,
        'Path': 'golang.org/x/tools/gopls',
        'Main': main if main is not None else {
            'Path': 'golang.org/x/tools/gopls', 'Version': 'v0.0.1',
            'Sum': h1_of('zip golang.org/x/tools/gopls v0.0.1')},
        'Deps': deps if deps is not None else [
            {'Path': 'example.test/dep', 'Version': 'v1.0.0',
             'Sum': h1_of('zip example.test/dep v1.0.0')}],
        'Settings': settings,
    }


def sample_selection(dep_version: str = 'v1.0.0', gopls: str = 'v0.0.1'):
    import gopls_closure as model

    return model.ModuleSelection((
        model.ModuleIdentity(
            model.ModuleId(model.ModulePath('example.test/dep'),
                           model.ModuleVersion(dep_version)),
            model.H1(h1_of(f'zip example.test/dep {dep_version}'))),
        model.ModuleIdentity(
            model.ModuleId(model.ModulePath(model.ROOT), model.ModuleVersion(gopls)),
            model.H1(h1_of(f'zip golang.org/x/tools/gopls {gopls}'))),
    ))


