def test_install(fixture_root: driver.Fixture) -> None:
    print('install: fetch, verify, layout, install order')
    for arch in model.Architecture:
        transport = driver.FixtureTransport(fixture_root.dist.files)
        work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
        work.mkdir()
        # The scratch layout is removed when the command returns, so the original
        # manifest bytes are captured when the layout exists.
        layouts: list[bytes] = []
        original_prepare = model.prepare

        def capture(*arguments, **keywords):
            layout = original_prepare(*arguments, **keywords)
            layouts.append(
                (layout.root / 'dist' / f'channel-rust-{fixture.CHANNEL}.toml').read_bytes())
            return layout

        model.prepare = capture
        try:
            runner = driver.RecordingRunner(arch, fixture.CHANNEL, fixture.RUSTUP_VERSION)
            dependencies = model.Dependencies(
                transport=transport, runner=runner,
                gpg=model.GpgProgram(driver._gpg_path()), trust=fixture_root.trust)
            code = model.main(['install', str(fixture_root.pinned), '--arch', arch.value,
                               '--expect-channel', fixture.CHANNEL,
                               '--rustup-home', str(work / 'rustup'),
                               '--cargo-home', str(work / 'cargo'),
                               '--work-dir', str(work)], dependencies)
        finally:
            model.prepare = original_prepare
        check(f'{arch.value}: install exit 0', code == 0)
        expected = {model.expected_bootstrap_url(model.Semver(fixture.RUSTUP_VERSION), arch)}
        expected |= {archive_url(package, target.value)
                     for package, target in model.selected_pairs(arch)}
        check(f'{arch.value}: fetched exactly the selected closure',
              set(transport.fetches) == expected,
              f'({sorted(set(transport.fetches) ^ expected)})')
        check(f'{arch.value}: layout keeps the original manifest bytes',
              len(layouts) == 1 and
              layouts[0] == fixture_root.dist.files[
                  f'https://static.rust-lang.org/dist/channel-rust-{fixture.CHANNEL}.toml'])
        argv = runner.executed()
        bootstrap_index = next(index for index, line in enumerate(argv)
                               if line.endswith('rustup-init -y --no-modify-path'
                                                f' --default-host {arch.host.value}'
                                                ' --default-toolchain none --profile minimal'))
        install_index = next(index for index, line in enumerate(argv)
                             if 'toolchain install' in line)
        check(f'{arch.value}: bootstrap before toolchain install',
              bootstrap_index < install_index)
        check(f'{arch.value}: exact rustup argv',
              any(line.endswith(f'rustup toolchain install {fixture.CHANNEL} --profile minimal'
                                ' --component clippy,rustfmt'
                                f' --target {arch.musl.value} --no-self-update')
                  for line in argv), argv)
        check(f'{arch.value}: auto-install and self-update disabled',
              any(line.endswith('rustup set auto-install disable') for line in argv) and
              any(line.endswith('rustup set auto-self-update disable') for line in argv))
        bootstrap_env = runner.calls[bootstrap_index][1]
        check(f'{arch.value}: dist server is the private file:// layout',
              bootstrap_env['RUSTUP_DIST_SERVER'].startswith('file://'))
        check(f'{arch.value}: no ambient toolchain selection in the child environment',
              'RUSTUP_TOOLCHAIN' not in bootstrap_env and
              bootstrap_env['RUSTUP_AUTO_INSTALL'] == '0')


def expected_process_transcript(arch: model.Architecture) -> list[str]:
    """The complete ordered non-gpg process trace of a clean install.

    Spelled out here, independently of the module under test: a positive case
    that only looks for the commands it expects cannot notice an extra one.
    """
    host = arch.host.value
    cargo = 'cargo/bin'
    return [
        f'cargo/bin/rustup set auto-self-update disable',
        f'{cargo}/rustup set auto-install disable',
        f'{cargo}/rustup toolchain install {fixture.CHANNEL} --profile minimal '
        f'--component clippy,rustfmt --target {arch.musl.value} --no-self-update',
        f'{cargo}/rustup default {fixture.CHANNEL}',
        f'{cargo}/rustup --version',
        f'{cargo}/rustup toolchain list',
        f'{cargo}/rustup component list --installed',
        f'{cargo}/rustup target list --installed',
        f'{cargo}/rustc -vV',
        f'{cargo}/cargo --version',
        f'{cargo}/cargo clippy --version',
        f'{cargo}/rustfmt --version',
    ]


def normalize_argv(line: str) -> str:
    """Drop the invocation's scratch prefix so the trace is comparable."""
    return re.sub(r'^\S*?(?=(cargo/bin|rustup-init))', '', line)


def clean_transcript_problems(runner: driver.RecordingRunner,
                              transport: driver.FixtureTransport,
                              arch: model.Architecture,
                              events: model.Events) -> list[str]:
    """Reasons a positive install did more than the reviewed closure."""
    problems = []
    lines = [normalize_argv(line) for line in runner.executed()]
    gpg_lines = [line for line in lines
                 if os.path.basename(line.split(' ', 1)[0]) in ('gpg', 'gpg2')]
    rest = [line for line in lines if line not in gpg_lines]
    bootstrap = [line for line in rest if line.startswith('rustup-init')]
    if len(bootstrap) != 1:
        problems.append(f'expected exactly one bootstrap execution, saw {bootstrap}')
    others = [line for line in rest if not line.startswith('rustup-init')]
    expected = expected_process_transcript(arch)
    if others != expected:
        problems.append(f'process transcript differs: {others} != {expected}')
    if runner.foreign_calls():
        problems.append(f'forbidden calls: {runner.foreign_calls()}')
    verifications = [line for line in lines if '--verify' in line]
    if len(verifications) != 1 + len(model.selected_pairs(arch)):
        problems.append(f'expected {1 + len(model.selected_pairs(arch))} signature checks, '
                        f'saw {len(verifications)}')
    fetches = transport.fetches
    if len(fetches) != len(set(fetches)):
        problems.append('a payload or manifest URL was fetched more than once (retry)')
    expected_fetches = {model.expected_bootstrap_url(
        model.Semver(fixture.RUSTUP_VERSION), arch)}
    expected_fetches |= {archive_url(package, target.value)
                         for package, target in model.selected_pairs(arch)}
    if set(fetches) != expected_fetches:
        problems.append(f'unexpected or missing fetches: {sorted(set(fetches) ^ expected_fetches)}')
    last_verification = max((index for index, line in enumerate(events.lines)
                             if line.startswith(('hash-ok', 'signature-ok', 'preflight-ok'))),
                            default=-1)
    execute = [index for index, line in enumerate(events.lines)
               if line.startswith('execute')]
    if execute and execute[0] < last_verification:
        problems.append('something executed before the last selected byte was verified')
    if not any(line.startswith('install-ok') for line in events.lines):
        problems.append('no install-ok event')
    return problems


def test_transcript(fixture_root: driver.Fixture) -> None:
    print('install: complete independent process and fetch transcript')
    for arch in model.Architecture:
        work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
        work.mkdir()
        transport = driver.FixtureTransport(fixture_root.dist.files)
        runner = driver.RecordingRunner(arch, fixture.CHANNEL, fixture.RUSTUP_VERSION)
        events_path = work / 'events.log'
        pin = model.load_pin(fixture_root.pinned, fixture_root.trust)
        # The verifier uses the recording runner, so the real gpg invocations are
        # part of the same transcribed trace (delegated, not emulated).
        verifier = model.SignatureVerifier(model.GpgProgram(driver._gpg_path()),
                                           fixture_root.dist.key, work / 'verify', runner,
                                           fixture_root.trust)
        # One timeline for prepare and install: a fresh Events for install would
        # discard every hash/preflight event before the execution comparison.
        events = model.Events(events_path)
        layout = model.prepare(fixture_root.pinned, pin, arch, work / 'scratch', transport,
                               verifier, events)
        model.install(layout, model.InstallHomes(work / 'rustup', work / 'cargo'), arch, pin,
                      runner, events)
        problems = clean_transcript_problems(runner, transport, arch, events)
        check(f'{arch.value}: the clean install transcript is exactly the reviewed closure',
              problems == [], f'({problems})')


@contextlib.contextmanager
def captured_transcript(fixture_root: driver.Fixture, arch: model.Architecture):
    """Everything one install attempt observed, for mutant oracles."""
    work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    work.mkdir()
    transport = driver.FixtureTransport(fixture_root.dist.files)
    runner = driver.RecordingRunner(arch, fixture.CHANNEL, fixture.RUSTUP_VERSION)
    events = model.Events()
    yield work, transport, runner, events


def test_installer_mutants(fixture_root: driver.Fixture) -> None:
    print('mutants: the installer oracles kill live fetches, early execution and retries')
    arch = model.Architecture.AMD64
    pin = model.load_pin(fixture_root.pinned, fixture_root.trust)

    # 1. The reviewer's added live downloader: one extra fetch before bootstrap.
    class LiveDownloader(driver.RecordingRunner):
        def __init__(self, *arguments, **keywords):
            super().__init__(*arguments, **keywords)
            self.injected = False

        def run(self, argv, env, cwd=None):
            if str(argv[0]).endswith('rustup-init') and not self.injected:
                self.injected = True
                super().run(['/usr/bin/curl', 'https://sh.rustup.rs'], env)
            return super().run(argv, env, cwd)

    work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    work.mkdir()
    transport = driver.FixtureTransport(fixture_root.dist.files)
    layout = model.prepare(fixture_root.pinned, pin, arch, work / 'scratch', transport,
                           fixture_root.verifier(work / 'verify'), model.Events())
    runner = LiveDownloader(model.Architecture.AMD64, fixture.CHANNEL, fixture.RUSTUP_VERSION)
    events = model.Events()
    refused = False
    try:
        model.install(layout, model.InstallHomes(work / 'rustup', work / 'cargo'), arch, pin,
                      runner, events)
    except model.ToolchainError:
        refused = True
    check('the runner fails closed on an added live downloader', refused)
    check('the added downloader is visible in the transcript',
          any('curl' in line for line in runner.executed()), f'({runner.executed()})')
    check('the added downloader is caught by the transcript oracle',
          clean_transcript_problems(runner, transport, arch, events) != [])
    check('the added downloader did not become installed state',
          not (work / 'cargo').exists() and not any(
              line.startswith('install-ok') for line in events.lines))

    # 2. A late (sixth) archive corruption through the real prepare, with a
    #    runner that records *actual process calls* as well as events: nothing may
    #    execute and no origin may be fetched twice. The clean run must produce no
    #    problems at all; the two mutants below must produce exactly theirs, so a
    #    green result is evidence rather than an artefact of an unchecked oracle.
    def late_corruption_problems(module, label: str) -> list[str]:
        mutant_trust = module.TrustPolicy(
            primary=module.Fingerprint(fixture_root.dist.fingerprint),
            signers=(module.Fingerprint(fixture_root.dist.fingerprint),))
        mutant_pin = module.load_pin(fixture_root.pinned, mutant_trust)
        mutant_arch = module.Architecture.AMD64
        corrupt_transport = driver.FixtureTransport(fixture_root.dist.files)
        last = module.selected_pairs(mutant_arch)[-1]
        corrupt_transport.fault(archive_url(last[0], last[1].value),
                                lambda raw: b'\x00' + raw[1:])
        # A short path: a gpg-agent unix socket inside a deeper directory exceeds
        # the platform's socket-path limit and the signature check would fail for
        # an unrelated reason.
        corner = Path(tempfile.mkdtemp(dir=fixture_root.root))
        # The runner records the real process calls, including any bootstrap a
        # mutant starts before the sixth archive is verified.
        runner = driver.RecordingRunner(mutant_arch, fixture.CHANNEL,
                                        fixture.RUSTUP_VERSION)
        trust = module.TrustPolicy(
            primary=module.Fingerprint(fixture_root.dist.fingerprint),
            signers=(module.Fingerprint(fixture_root.dist.fingerprint),))
        verifier = module.SignatureVerifier(module.GpgProgram(driver._gpg_path()),
                                            fixture_root.dist.key, corner / 'v',
                                            runner, trust)
        events = module.Events()
        problems: list[str] = []
        try:
            module.prepare(fixture_root.pinned, mutant_pin, mutant_arch, corner / 'p',
                           corrupt_transport, verifier, events)
        except (module.ToolchainError, driver.UnrecognizedCommand):
            # A bootstrap started before the closure was verified is refused by the
            # runner *and* recorded as a call; the oracle below is what fails the
            # mutant, so the refusal must not hide the recorded call.
            pass
        else:
            problems.append('the corrupt late archive was accepted')
        bootstraps = [argv for argv, _, _ in runner.calls if argv[0].endswith('rustup-init')]
        if bootstraps:
            problems.append(f'executed the bootstrap before the closure was verified: '
                            f'{bootstraps}')
        fetches = corrupt_transport.fetches
        if len(fetches) != len(set(fetches)):
            problems.append('retried a fetch instead of refusing the mismatch')
        known = {module.expected_bootstrap_url(module.Semver(fixture.RUSTUP_VERSION),
                                               mutant_arch)}
        known |= {archive_url(package, target.value) for package, target in
                  module.selected_pairs(mutant_arch)}
        if set(fetches) - known:
            problems.append('fetched an origin outside the committed closure')
        executions = [line for line in events.lines if line.startswith('execute')]
        if executions:
            problems.append(f'executed before the closure was verified: {executions}')
        return problems

    clean = late_corruption_problems(model, 'late-sixth-clean')
    check('a corrupt sixth archive is refused with no bootstrap call and no retried fetch',
          clean == [], f'({clean})')

    mutants = {
        'early-bootstrap-process-call': [(
            '    bootstrap.chmod(0o755)\n',
            '    bootstrap.chmod(0o755)\n'
            "    verifier._runner.run([str(bootstrap), '-y', '--no-modify-path',\n"
            "                          '--default-host', arch.host.value,\n"
            "                          '--default-toolchain', 'none', '--profile', PROFILE],\n"
            "                         {'RUSTUP_HOME': str(work / 'early-rustup'),\n"
            "                          'CARGO_HOME': str(work / 'early-cargo')})\n")],
        'retry-after-mismatch': [(
            "            refuse(f'{name}: downloaded bytes at {archive.content.url.value} '\n"
            "                   'do not match the signed manifest hash')",
            "            transport.fetch(archive.content.url, target_path, MAX_ARCHIVE_BYTES)\n"
            "            refuse(f'{name}: downloaded bytes at {archive.content.url.value} '\n"
            "                   'do not match the signed manifest hash')")],
    }
    expected_reason = {
        'early-bootstrap-process-call': 'executed the bootstrap',
        'retry-after-mismatch': 'retried a fetch',
    }
    for name, replacements in mutants.items():
        module = driver.load_mutant(name, replacements, fixture_root.root / 'mutants')
        problems = late_corruption_problems(module, name)
        check(f'mutant {name} is killed by the actual-call/fetch oracle',
              any(expected_reason[name] in problem for problem in problems),
              f'({problems})')


def test_runner_dispatch(fixture_root: driver.Fixture) -> None:
    print('runner: executable-plus-complete-argv dispatch fails closed')
    root = Path(tempfile.mkdtemp(dir=fixture_root.root))
    homes = root / 'homes'
    bins = homes / 'cargo' / 'bin'
    bins.mkdir(parents=True)
    env = {'RUSTUP_HOME': str(homes / 'rustup'), 'CARGO_HOME': str(homes / 'cargo')}
    runner = driver.RecordingRunner(model.Architecture.ARM64, fixture.CHANNEL,
                                    fixture.RUSTUP_VERSION)

    def accepted(argv) -> bool:
        try:
            runner.run(argv, env)
        except driver.UnrecognizedCommand:
            return False
        return True

    cases = [
        (['/unregistered/program', 'clippy', '--version'], False,
         'an unregistered executable with an allowlisted argv tail'),
        ([str(bins / 'cargo'), 'clippy', '--version'], True, 'the real cargo clippy call'),
        ([str(bins / 'cargo'), 'clippy', '--version', '--extra'], False,
         'a recognized executable with an extra argument'),
        ([str(bins / 'rustup'), 'toolchain', 'list', '--installed'], False,
         'a recognized executable with an unlisted argv'),
        (['/usr/bin/rustup', '--version'], False,
         'a rustup that is not the one in the install homes'),
        ([str(bins / 'rustup'), '--version'], True, 'the real rustup --version call'),
    ]
    for argv, expected, label in cases:
        check(f'runner {"accepts" if expected else "refuses"} {label}',
              accepted(argv) is expected, f'({argv})')

    # The bootstrap is authorized by the verified layout path, not by its name: a
    # foreign program with the same basename and the documented argv is a
    # different file, so it must be refused even after a real layout registered.
    bootstrap_argv = ['-y', '--no-modify-path', '--default-host',
                      model.Architecture.ARM64.host.value, '--default-toolchain', 'none',
                      '--profile', 'minimal']
    work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    layout = model.prepare(fixture_root.pinned, model.load_pin(fixture_root.pinned,
                                                               fixture_root.trust),
                           model.Architecture.ARM64, work,
                           driver.FixtureTransport(fixture_root.dist.files),
                           fixture_root.verifier(work), model.Events())
    check('a prepared layout registered its own bootstrap',
          os.path.realpath(str(layout.bootstrap)) in driver.REGISTERED_BOOTSTRAPS)
    foreign = root / 'unregistered'
    foreign.mkdir()
    planted = foreign / 'rustup-init'
    planted.write_bytes(Path(layout.bootstrap).read_bytes())
    planted.chmod(0o755)
    check('runner accepts the registered verified bootstrap',
          accepted([str(layout.bootstrap), *bootstrap_argv]), str(layout.bootstrap))
    check('runner refuses a same-basename foreign path with the documented argv',
          not accepted([str(planted), *bootstrap_argv]), str(planted))
    check('runner refuses a same-basename foreign path by basename alone',
          not accepted(['/unregistered/rustup-init', *bootstrap_argv]), '/unregistered')
    check('runner refuses the verified bootstrap with a different argv',
          not accepted([str(layout.bootstrap), *bootstrap_argv, '--extra']))
    check('runner delegates real gpg by resolved identity',
          accepted([driver._gpg_path(), '--version']))
    fake_gpg = foreign / 'gpg'
    fake_gpg.write_text('#!/bin/sh\nexit 0\n')
    fake_gpg.chmod(0o755)
    check('runner refuses a foreign program named gpg', not accepted([str(fake_gpg), '--version']))


def test_events(fixture_root: driver.Fixture) -> None:
    print('install: event ordering and late-component verification')
    subset = driver.FixtureTransport(fixture_root.dist.files)
    events_path = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'events.log'
    work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    pin = model.load_pin(fixture_root.pinned, fixture_root.trust)
    verifier = fixture_root.verifier(work)
    events = model.Events(events_path)
    layout = model.prepare(fixture_root.pinned, pin, model.Architecture.AMD64, work, subset,
                           verifier, events)
    lines = events_path.read_text().splitlines()
    last_hash = max(index for index, line in enumerate(lines) if line.startswith(('hash-ok',
                                                                                 'signature-ok')))
    check('all hashes and signatures precede the layout',
          last_hash < next(index for index, line in enumerate(lines)
                           if line.startswith('layout-ready')))
    check('events record each selected archive',
          sum(1 for line in lines if line.startswith('signature-ok')) == 6)

    # A corrupt *sixth* archive must not reach bootstrap: without this case a
    # test that only mutates the first file could pass while later bytes are
    # trusted unverified.
    for position, (package, target) in enumerate(model.selected_pairs(model.Architecture.AMD64)):
        corrupted = driver.FixtureTransport(fixture_root.dist.files)
        url = archive_url(package, target.value)
        corrupted.fault(url, lambda raw: b'\x00' + raw[1:])
        events_file = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'events.log'
        corner = Path(tempfile.mkdtemp(dir=fixture_root.root))
        # The refusal has to name the origin: an operator reading a withdrawn-pin
        # failure needs the URL that stopped working, not only the file name.
        refuses(f'changed {package} {target.value} bytes are refused',
                lambda: model.prepare(fixture_root.pinned, pin, model.Architecture.AMD64,
                                      corner, corrupted, fixture_root.verifier(corner),
                                      model.Events(events_file)),
                'do not match the signed manifest hash', url)
        check(f'{package} {target.value}: no execution event',
              'execute' not in events_file.read_text(),
              f'({events_file.read_text() if events_file.exists() else "absent"})')

    # The bootstrap is the first input a build fetches, so its digest refusal
    # names the URL too: a withdrawn rustup-init must be visible in the log.
    bootstrap_url = model.expected_bootstrap_url(model.Semver(fixture.RUSTUP_VERSION),
                                                 model.Architecture.AMD64)
    corrupted = driver.FixtureTransport(fixture_root.dist.files)
    corrupted.fault(bootstrap_url, lambda raw: b'\x00' + raw[1:])
    corner = Path(tempfile.mkdtemp(dir=fixture_root.root))
    refuses('changed bootstrap bytes are refused',
            lambda: model.prepare(fixture_root.pinned, pin, model.Architecture.AMD64, corner,
                                  corrupted, fixture_root.verifier(corner),
                                  model.Events(corner / 'events.log')),
            'do not match the committed digest', bootstrap_url)
    del layout


def custom_archive(entries) -> bytes:
    items = entries if isinstance(entries, list) else list(entries.items())
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode='w:xz') as archive:
        for name, data in items:
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o644
            archive.addfile(info, io.BytesIO(data))
    return buffer.getvalue()


def cargo_archive(package: str, target: model.TargetTriple, arch: str) -> model.ComponentArchive:
    name = fixture.archive_name(arch, package, target.value)
    return model.ComponentArchive(
        package=package, target=target,
        content=model.Content(
            model.CanonicalUrl(f'https://static.rust-lang.org/dist/{fixture.DATE}/{name}'),
            model.Sha256('0' * 64)),
        member_prefix=model.MemberPrefix(name[:-len('.tar.xz')] + '/'),
        signature=model.Evidence(model.EvidencePath('evidence/x.asc'), model.Sha256('0' * 64)))


def test_arch_confusion(fixture_root: driver.Fixture) -> None:
    print('prepare/preflight: wrong architecture and hostile payloads')
    pin = model.load_pin(fixture_root.pinned, fixture_root.trust)
    work = Path(tempfile.mkdtemp(dir=fixture_root.root))
    amd64_host = model.Architecture.AMD64.host
    arm64_host = model.Architecture.ARM64.host

    swapped = driver.FixtureTransport(fixture_root.dist.files)
    swapped.replace(archive_url('cargo', amd64_host.value),
                    fixture_root.dist.files[archive_url('cargo', arm64_host.value)])
    events_file = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'events.log'
    refuses('arm64 bytes under the amd64 URL are refused before preflight',
            lambda: model.prepare(fixture_root.pinned, pin, model.Architecture.AMD64,
                                  Path(tempfile.mkdtemp(dir=fixture_root.root)), swapped,
                                  fixture_root.verifier(work), model.Events(events_file)),
            'do not match the signed manifest hash',
            archive_url('cargo', amd64_host.value))
    check('no execution event after a payload refusal',
          'execute' not in events_file.read_text())

    # With hashes and signatures made to agree, only the ELF/target preflight can
    # refuse a consistently rehashed wrong-architecture payload.
    arm64_cargo = model.ComponentArchive(**{
        **cargo_archive('cargo', arm64_host, 'arm64').__dict__,
        'package': 'cargo',
        'target': amd64_host})
    archives = Path(tempfile.mkdtemp(dir=fixture_root.root))
    arm64_path = archives / 'cargo-arm64.tar.xz'
    arm64_path.write_bytes(fixture.build_archive('arm64', 'cargo', arm64_host.value))
    refuses('arm64 ELF under an amd64 selection is refused',
            lambda: model.preflight_archive(arm64_path, arm64_cargo, model.Events()),
            'targets ELF machine')

    musl_target = model.Architecture.AMD64.musl
    prefix = fixture.archive_name('amd64', 'rust-std', musl_target.value)[:-len('.tar.xz')]
    component = f'rust-std-{musl_target.value}'
    wrong_std = archives / 'std-wrong-target.tar.xz'
    wrong_std.write_bytes(custom_archive({
        f'{prefix}/rust-installer-version': b'3\n',
        f'{prefix}/components': (component + '\n').encode(),
        f'{prefix}/{component}/manifest.in': (
            f'file:lib/rustlib/{amd64_host.value}/lib/libstd-00000000.rlib\n').encode(),
        f'{prefix}/{component}/lib/rustlib/{amd64_host.value}/lib/libstd-00000000.rlib': b'rlib',
    }))
    refuses('a rust-std archive without the selected target is refused',
            lambda: model.preflight_archive(wrong_std, cargo_archive('rust-std', musl_target,
                                                                    'amd64'), model.Events()),
            'standard library')

    traversal = archives / 'traversal.tar.xz'
    traversal.write_bytes(hostile_archive('../escape', amd64_host.value))
    refuses('traversal member is refused',
            lambda: model.preflight_archive(
                traversal, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
            'non-canonical archive member')

    duplicate = archives / 'duplicate.tar.xz'
    prefix = fixture.archive_name('amd64', 'cargo', amd64_host.value)[:-len('.tar.xz')]
    duplicate.write_bytes(custom_archive([
        (f'{prefix}/rust-installer-version', b'3\n'),
        (f'{prefix}/rust-installer-version', b'3\n'),
    ]))
    refuses('duplicate members are refused',
            lambda: model.preflight_archive(
                duplicate, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
            'duplicate archive member')

    def metadata_case(name: str, entries: dict[str, bytes], expected: str) -> None:
        prefix = fixture.archive_name('amd64', 'cargo', amd64_host.value)[:-len('.tar.xz')]
        complete = {f'{prefix}/rust-installer-version': b'3\n',
                    f'{prefix}/components': b'cargo\n',
                    f'{prefix}/cargo/manifest.in': b'file:bin/cargo\n',
                    f'{prefix}/cargo/bin/cargo': fixture.elf_header(62)}
        complete.update({f'{prefix}/{key}' if not key.startswith(prefix) else key: value
                         for key, value in entries.items()})
        path = archives / f'{name}.tar.xz'
        path.write_bytes(custom_archive(complete))
        refuses(f'metadata {name} is refused',
                lambda: model.preflight_archive(
                    path, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
                expected)

    metadata_case('version', {'rust-installer-version': b'2\n'}, 'rust-installer-version must be 3')
    metadata_case('component-name', {'components': b'rustc\n'}, 'component list is')
    metadata_case('absolute-directive', {'cargo/manifest.in': b'file:/etc/passwd\n'},
                  'non-canonical directive path')
    metadata_case('unknown-directive', {'cargo/manifest.in': b'symlink:bin/cargo\n'},
                  'unknown directive')
    metadata_case('missing-payload', {'cargo/manifest.in': b'file:bin/other\n'},
                  'missing payload path')
    metadata_case('uncovered-payload', {'cargo/extra.txt': b'x'}, 'not covered by manifest.in')

    # --- decoded-stream and tree bounds --------------------------------------
    # tarfile's GNU long-name header is decoded and consumed before a member is
    # yielded, so a limit that only sums member sizes never sees it.
    prefix = fixture.archive_name('amd64', 'cargo', amd64_host.value)[:-len('.tar.xz')]
    long_name = archives / 'long-name.tar.xz'
    builder = io.BytesIO()
    with tarfile.open(fileobj=builder, mode='w:xz', format=tarfile.GNU_FORMAT) as output:
        with tarfile.open(fileobj=io.BytesIO(
                fixture_root.dist.files[archive_url('cargo', amd64_host.value)]),
                mode='r:xz') as origin:
            for member in origin:
                output.addfile(member, origin.extractfile(member) if member.isfile() else None)
        info = tarfile.TarInfo(f'{prefix}/overlay-' + 'a' * 100000)
        info.size = 0
        output.addfile(info, io.BytesIO())
    long_name.write_bytes(builder.getvalue())
    check('the compressed long-name archive is smaller than its decoded header',
          len(long_name.read_bytes()) < 5000, f'({len(long_name.read_bytes())} bytes)')
    limit = model.MAX_EXPANDED_BYTES
    header_limit = model.MAX_EXTENDED_HEADER_BYTES
    total_limit = model.MAX_EXTENDED_TOTAL_BYTES
    metadata_file_limit = model.MAX_METADATA_FILE_BYTES
    metadata_total_limit = model.MAX_METADATA_TOTAL_BYTES

    # The metadata bomb: a 100 KB GNU longname with the *metadata file* and
    # *metadata total* caps and the expansion budget all at production values. A
    # header bound independent of those is the only thing that can refuse it.
    refuses('a GNU longname larger than the metadata policy is refused',
            lambda: model.preflight_archive(
                long_name, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
            'extended header')
    check('the metadata-file caps are at their production values for that control',
          (model.MAX_METADATA_FILE_BYTES, model.MAX_METADATA_TOTAL_BYTES) ==
          (metadata_file_limit, metadata_total_limit))
    try:
        model.MAX_EXTENDED_HEADER_BYTES = 2048
        refuses('a GNU longname past the reduced header bound is refused',
                lambda: model.preflight_archive(
                    long_name, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
                'extended header')
    finally:
        model.MAX_EXTENDED_HEADER_BYTES = header_limit

    # The same shape through PAX: a PAX record set is also consumed before any
    # member is yielded.
    pax_name = archives / 'pax-long-name.tar.xz'
    builder = io.BytesIO()
    with tarfile.open(fileobj=builder, mode='w:xz', format=tarfile.PAX_FORMAT) as output:
        with tarfile.open(fileobj=io.BytesIO(
                fixture_root.dist.files[archive_url('cargo', amd64_host.value)]),
                mode='r:xz') as origin:
            for member in origin:
                output.addfile(member, origin.extractfile(member) if member.isfile() else None)
        info = tarfile.TarInfo(f'{prefix}/pax-' + 'b' * 100000)
        info.size = 0
        output.addfile(info, io.BytesIO())
    pax_name.write_bytes(builder.getvalue())
    refuses('a PAX longname larger than the metadata policy is refused',
            lambda: model.preflight_archive(
                pax_name, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
            'extended header')

    # Cumulative: several extended headers each inside the per-header bound but
    # together past the total.
    many_names = archives / 'many-long-names.tar.xz'
    builder = io.BytesIO()
    with tarfile.open(fileobj=builder, mode='w:xz', format=tarfile.GNU_FORMAT) as output:
        with tarfile.open(fileobj=io.BytesIO(
                fixture_root.dist.files[archive_url('cargo', amd64_host.value)]),
                mode='r:xz') as origin:
            for member in origin:
                output.addfile(member, origin.extractfile(member) if member.isfile() else None)
        for index in range(4):
            info = tarfile.TarInfo(f'{prefix}/many-{index}-' + 'c' * 8000)
            info.size = 0
            output.addfile(info, io.BytesIO())
    many_names.write_bytes(builder.getvalue())
    try:
        model.MAX_EXTENDED_TOTAL_BYTES = 10000
        refuses('extended headers past the cumulative bound are refused',
                lambda: model.preflight_archive(
                    many_names, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
                'extended headers total')
    finally:
        model.MAX_EXTENDED_TOTAL_BYTES = total_limit

    # Positive control: a long name inside the reviewed bound is not refused, so
    # the bound refuses the bomb rather than long names as such.
    modest_name = archives / 'modest-long-name.tar.xz'
    builder = io.BytesIO()
    with tarfile.open(fileobj=builder, mode='w:xz', format=tarfile.GNU_FORMAT) as output:
        with tarfile.open(fileobj=io.BytesIO(
                fixture_root.dist.files[archive_url('cargo', amd64_host.value)]),
                mode='r:xz') as origin:
            for member in origin:
                output.addfile(member, origin.extractfile(member) if member.isfile() else None)
        info = tarfile.TarInfo(f'{prefix}/modest-' + 'd' * 1000)
        info.size = 0
        output.addfile(info, io.BytesIO())
    modest_name.write_bytes(builder.getvalue())
    model.preflight_archive(modest_name, cargo_archive('cargo', amd64_host, 'amd64'),
                            model.Events())
    check('a long name under the reviewed header bound still passes', True)

    # --- metadata that moves the member boundary ----------------------------
    # A PAX `size` record replaces the header's size field for the following
    # member, so a walk over raw header fields and tarfile's own walk see
    # different boundaries. These are the discriminating fixtures: the hidden
    # 100 KB GNU longname sits inside what the raw field calls file data.
    def header(name: str, size: int, kind: bytes = tarfile.REGTYPE) -> bytes:
        info = tarfile.TarInfo(name)
        info.size = size
        info.type = kind
        return info.tobuf(format=tarfile.GNU_FORMAT)

    def pax(records: dict[str, str], kind: bytes = tarfile.XHDTYPE) -> bytes:
        return tarfile.TarInfo._create_pax_generic_header(records, kind, 'utf-8')

    long_bytes = (f'{prefix}/overlay-' + 'z' * 100000).encode() + b'\x00'
    hidden = (header('././@LongLink', len(long_bytes), tarfile.GNUTYPE_LONGNAME)
              + long_bytes + b'\x00' * (-len(long_bytes) % 512)
              + header('placeholder', 0))
    origin_bytes = lzma.decompress(
        fixture_root.dist.files[archive_url('cargo', amd64_host.value)])

    def preflight_case(label: str, body: bytes, expected: str) -> None:
        path = archives / f'{label}.tar.xz'
        path.write_bytes(lzma.compress(body))
        refuses(f'archive {label} is refused',
                lambda: model.preflight_archive(
                    path, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
                expected)

    preflight_case('plain-hidden-longname', hidden + origin_bytes, 'extended header')
    preflight_case('pax-size-override',
                   pax({'size': '0'}) + header(f'{prefix}/overlay-first', len(hidden))
                   + hidden + origin_bytes, 'extended header')
    # The same override reached through global state: the global record set is
    # merged into every following per-file header, so its `size` applies too.
    preflight_case('pax-global-size-override',
                   pax({'size': '0'}, tarfile.XGLTYPE)
                   + pax({'mtime': '1700000000'})
                   + header(f'{prefix}/overlay-global', len(hidden))
                   + hidden + origin_bytes, 'extended header')
    # Sparse metadata carries its data layout in the payload, which no header
    # bound describes.
    preflight_case('pax-sparse-metadata',
                   pax({'GNU.sparse.size': '0', 'GNU.sparse.name': f'{prefix}/sparse'})
                   + header(f'{prefix}/sparse-file', 0) + origin_bytes, 'sparse PAX metadata')
    preflight_case('gnu-sparse-member',
                   header(f'{prefix}/sparse-member', 512, tarfile.GNUTYPE_SPARSE)
                   + b'\x00' * 512 + origin_bytes, 'GNU sparse members')

    # tarfile's V7 normalization reads an `AREGTYPE` (`NUL`) header whose name
    # ends in `/` as a directory, so its size field is not data to skip. Walking
    # it as a regular member let a 100 KB GNU longname sit inside the skipped
    # bytes (the fourth-round counterexample). A data-carrying header of that
    # shape is refused rather than walked: whether a follow-up header after
    # `L`/`K`/`x`/`g` still gets the normalization has changed inside tarfile, so
    # one walk cannot match every supported Python there.
    v7_hidden = (header(f'{prefix}/overlay-dir/', len(hidden), tarfile.AREGTYPE)
                 + hidden + origin_bytes)
    preflight_case('v7-directory-hidden-longname', v7_hidden, 'V7 directory header')
    # The same shape through a PAX `size` record: the header's own size field is
    # zero and the data is the override, so the check has to use the effective
    # size rather than the raw field.
    preflight_case('pax-size-v7-directory',
                   pax({'size': str(len(hidden))})
                   + header(f'{prefix}/overlay-pax-dir/', 0, tarfile.AREGTYPE)
                   + hidden + origin_bytes, 'V7 directory header')
    with tarfile.open(fileobj=io.BytesIO(v7_hidden), mode='r:') as reader:
        first = next(iter(reader))
    check('tarfile reads that header as a directory and skips no data',
          first.isdir() and first.size == len(hidden),
          f'({first.name!r} type={first.type!r} size={first.size})')
    # Positive control: a V7 directory header with no data is exactly how the old
    # format spells a directory, and it still passes.
    v7_directory = archives / 'v7-directory.tar.xz'
    v7_directory.write_bytes(lzma.compress(
        header(f'{prefix}/overlay-plain-dir/', 0, tarfile.AREGTYPE) + origin_bytes))
    model.preflight_archive(v7_directory, cargo_archive('cargo', amd64_host, 'amd64'),
                            model.Events())
    check('a V7 directory header without data still passes', True)

    # Positive control: PAX metadata that does not move the boundary still passes,
    # so this is a metadata policy rather than a refusal of PAX as such.
    acceptable = archives / 'pax-modest.tar.xz'
    builder = io.BytesIO()
    with tarfile.open(fileobj=builder, mode='w:xz', format=tarfile.PAX_FORMAT) as output:
        with tarfile.open(fileobj=io.BytesIO(
                fixture_root.dist.files[archive_url('cargo', amd64_host.value)]),
                mode='r:xz') as origin:
            for member in origin:
                output.addfile(member, origin.extractfile(member) if member.isfile() else None)
        info = tarfile.TarInfo(f'{prefix}/pax-modest')
        info.size = 0
        info.pax_headers = {'mtime': '1700000000'}
        output.addfile(info, io.BytesIO())
    acceptable.write_bytes(builder.getvalue())
    check('the PAX positive control really carries a PAX header',
          acceptable.read_bytes() and b'mtime=1700000000' in lzma.decompress(
              acceptable.read_bytes()))
    model.preflight_archive(acceptable, cargo_archive('cargo', amd64_host, 'amd64'),
                            model.Events())
    check('bounded PAX metadata that does not move the boundary still passes', True)

    # Many tiny members: each member's size is one byte, but every one costs a
    # header, so the decoded stream is hundreds of times the summed member sizes
    # and the compressed archive stays small.
    squash = archives / 'squash.tar.xz'
    builder = io.BytesIO()
    with tarfile.open(fileobj=builder, mode='w:xz') as output:
        for index in range(8000):
            info = tarfile.TarInfo(f'{prefix}/cargo/many/{index:05d}')
            info.size = 1
            output.addfile(info, io.BytesIO(b'x'))
    squash.write_bytes(builder.getvalue())
    check('the compressed-small archive is far smaller than its decoded bytes',
          len(squash.read_bytes()) < (1 << 20), f'({len(squash.read_bytes())} bytes)')
    try:
        model.MAX_EXPANDED_BYTES = 1 << 20
        refuses('a compressed-small, decoded-large archive is refused',
                lambda: model.preflight_archive(
                    squash, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
                'decoded stream exceeds')
    finally:
        model.MAX_EXPANDED_BYTES = limit

    # --- archive tree types and modes ---------------------------------------
    def hostile_case(name: str, mutate, expected: str) -> None:
        builder = io.BytesIO()
        with tarfile.open(fileobj=builder, mode='w:xz') as output:
            with tarfile.open(fileobj=io.BytesIO(
                    fixture_root.dist.files[archive_url('cargo', amd64_host.value)]),
                    mode='r:xz') as origin:
                for member in origin:
                    output.addfile(member, origin.extractfile(member) if member.isfile() else None)
            mutate(output)
        path = archives / f'{name}.tar.xz'
        path.write_bytes(builder.getvalue())
        refuses(f'archive {name} is refused',
                lambda: model.preflight_archive(
                    path, cargo_archive('cargo', amd64_host, 'amd64'), model.Events()),
                expected)

    def add(output, name: str, data: bytes = b'x', kind: bytes = tarfile.REGTYPE,
            mode: int = 0o644, target: str = '') -> None:
        info = tarfile.TarInfo(prefix if name == '' else f'{prefix}/{name}')
        info.type = kind
        info.mode = mode
        info.linkname = target
        # Only a regular file carries data; tarfile does not skip a link's body,
        # so a non-zero size would desynchronize the stream.
        info.size = len(data) if kind == tarfile.REGTYPE else 0
        output.addfile(info, io.BytesIO(data[:info.size]))

    hostile_case('file-ancestor',
                 lambda output: (add(output, 'overlay'), add(output, 'overlay/child')),
                 'non-directory ancestor')
    hostile_case('linked-ancestor',
                 lambda output: (add(output, 'overlay', kind=tarfile.SYMTYPE,
                                     target='cargo/bin/cargo'),
                                 add(output, 'overlay/child')),
                 'non-directory ancestor')
    hostile_case('setgid-directory',
                 lambda output: add(output, 'overlay', kind=tarfile.DIRTYPE, mode=0o2777),
                 'setuid/setgid archive member')
    hostile_case('setgid-root',
                 lambda output: add(output, '', kind=tarfile.DIRTYPE, mode=0o2755),
                 'setuid/setgid archive member')

    def duplicate_root(output) -> None:
        info = tarfile.TarInfo(prefix)
        info.type = tarfile.DIRTYPE
        output.addfile(info, io.BytesIO())

    hostile_case('duplicate-root', duplicate_root, 'duplicate archive member')


def hostile_archive(extra_member: str, target: str) -> bytes:
    raw = fixture.build_archive('amd64', 'cargo', target)
    source = tarfile.open(fileobj=io.BytesIO(raw), mode='r:xz')
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode='w:xz') as output:
        for member in source.getmembers():
            output.addfile(member, source.extractfile(member))
        info = tarfile.TarInfo(extra_member)
        info.size = 1
        output.addfile(info, io.BytesIO(b'x'))
    return buffer.getvalue()


