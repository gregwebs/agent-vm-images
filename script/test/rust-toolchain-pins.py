def test_expired_signature(fixture_root: driver.Fixture) -> None:
    print('verify: gpg expiry is a refusal, not a verified signature')
    work = Path(tempfile.mkdtemp(dir=fixture_root.root))
    data = work / 'signed'
    data.write_bytes(b'expiring evidence')
    signature = work / 'signed.asc'
    signature.write_bytes(subprocess.run(
        [fixture.gpg_path(), '--batch', '--no-options', '--armor', '--detach-sign',
         '--default-sig-expire', '1d', '--output', '-', str(data)],
        env=fixture.sign_env(fixture_root.dist), check=True, capture_output=True).stdout)

    def verifier(runner, name: str) -> model.SignatureVerifier:
        return model.SignatureVerifier(model.GpgProgram(driver._gpg_path()),
                                       fixture_root.dist.key, work / name,
                                       runner, fixture_root.trust)

    verifier(model.ProcessRunner(), 'live').verify(data, signature, 'live signature')
    check('the same signature verifies while it is valid', True)

    class Advanced(model.ProcessRunner):
        """Real gpg, with the verifier's clock two days ahead."""

        def run(self, argv, env, cwd=None):
            argv = list(argv)
            if '--verify' in argv:
                argv = [argv[0], '--faked-system-time', str(int(time.time()) + 2 * 86400), *argv[1:]]
            return super().run(argv, env, cwd)

    refusal = ''
    try:
        verifier(Advanced(), 'expired').verify(data, signature, 'expired signature')
    except model.ToolchainError as error:
        refusal = str(error)
    check('an expired signature is refused',
          re.search(r'expired signature(: signature rejected: (EXPSIG|SIGEXPIRED)'
                    r'| check failed with status 1)', refusal) is not None,
          f'(refusal was {refusal!r})')
    check('the refusal is not a human-text match on "Good signature"',
          'Good signature' not in refusal, refusal)


def test_gpg_exit_status(fixture_root: driver.Fixture) -> None:
    print('verify: a nonzero gpg exit cannot become verified evidence')
    work = Path(tempfile.mkdtemp(dir=fixture_root.root))
    data = work / 'signed'
    data.write_bytes(b'evidence')
    signature = work / 'signed.asc'
    signature.write_bytes(fixture.armored_sign(data, fixture.sign_env(fixture_root.dist)))

    class FailingGpg(model.ProcessRunner):
        """Real gpg, plus a verifier that reports failure for a good signature."""

        def run(self, argv, env, cwd=None):
            proc = super().run(argv, env, cwd)
            if '--verify' in list(argv):
                return subprocess.CompletedProcess(list(argv), 1, proc.stdout, 'injected failure')
            return proc

    verifier = model.SignatureVerifier(model.GpgProgram(driver._gpg_path()),
                                       fixture_root.dist.key, work / 'gnupg',
                                       FailingGpg(), fixture_root.trust)
    refuses('a nonzero gpg verify exit is refused even with VALIDSIG output',
            lambda: verifier.verify(data, signature, 'signature'),
            'signature check failed with status 1')


