def check(name: str, condition: bool, detail: str = '') -> None:
    global Passed
    if condition:
        Passed += 1
        print(f'  ok   {name}')
        return
    Failures.append(name)
    print(f'  FAIL {name} {detail}')


def new_row() -> Path:
    """A short row directory: gpg-agent's socket path is a unix socket of at most
    104 bytes, so a deep temporary path fails every gpg call for the wrong reason.
    """
    row = Path(tempfile.mkdtemp(prefix='rtp-')).resolve()
    ROW_ROOTS.append(row)
    return row


def gpg_program(mode: str) -> str:
    if mode == 'real':
        return os.path.realpath(GPG)
    return str(Path(TOOLS['root']) / 'tools' / f'gpg-{mode}' / 'gpg')


def binary(name: str) -> str:
    return {'fixture': HELPER_FIXTURE, 'shipped': HELPER_SHIPPED, 'writer': WRITER}[name]


# --- the row harness ---------------------------------------------------------
# One row: a program, an argv, an expected outcome. The assertions are the ones the
# differential made on the Go side, kept one-sided.

def run_row(argv, *, gpg_mode: str = 'real', name: str = 'fixture',
            trust: str = 'fixture',
            env_extra: dict | None = None) -> tuple[list[str], int, str, str]:
    """Run one row; report the problems that do not depend on its expectation."""
    row = new_row()
    tmpdir = row / 't'
    tmpdir.mkdir()
    program = gpg_program(gpg_mode)
    env = {'PATH': os.path.dirname(program) + ':/usr/bin:/bin',
           'HOME': str(row), 'TMPDIR': str(tmpdir),
           'LANG': 'C.UTF-8', 'LC_ALL': 'C', 'TZ': 'UTC'}
    env.update(env_extra or {})
    arguments = list(argv)
    if trust == 'fixture':
        arguments = ['--fixture-trust', fixture_root.dist.fingerprint, *arguments]
    watched = Path(argv[1]) if len(argv) > 1 and Path(argv[1]).is_dir() else None
    before = driver.digest_tree(watched) if watched is not None else None
    status, out, err = driver.run_go(binary(name), arguments, env)
    problems = []
    if before is not None and driver.digest_tree(watched) != before:
        problems.append('the pin directory changed')
    left = sorted(entry.name for entry in tmpdir.iterdir())
    if left:
        problems.append(f'TMPDIR left {left}')
    return problems, status, out, err


def verdict(status: int, out: str, err: str, expected: int | None, fragments=(),
            channel: str = fixture.CHANNEL) -> list[str]:
    """The claim about one invocation: status, then the stream that status names."""
    problems = []
    if expected is None:
        return problems
    if status != expected:
        return [f'status {status}, want {expected}: {err.strip()[-300:]!r}']
    if expected == 0:
        if out != f'{channel}\n':
            problems.append(f'stdout is {out!r}, not the channel')
        if err != '':
            problems.append(f'stderr is {err!r}, not empty')
    elif expected == 1:
        if not err.startswith('rust_toolchain: '):
            problems.append(f'stderr is not one refusal line: {err!r}')
        if out != '':
            problems.append(f'stdout is {out!r}, not empty')
        missing = [fragment for fragment in fragments if fragment not in err]
        if missing:
            problems.append(f'the refusal lacks {missing}: {err.strip()[-400:]!r}')
    elif expected == 2:
        if 'usage' not in err:
            problems.append(f'stderr is not a usage line: {err!r}')
    return problems


def go_row(label: str, argv, *, fragments=(), expect: int = 0, **keywords) -> None:
    channel = keywords.pop('channel', fixture.CHANNEL)
    problems, status, out, err = run_row(argv, **keywords)
    problems.extend(verdict(status, out, err, expect, fragments, channel))
    check(label, not problems, '(' + '; '.join(problems) + ')' if problems else '')


def test_row_harness_control() -> None:
    """A wrong expectation must be reported, or a green table proves nothing."""
    print('control: the row harness reports a mismatch')
    problems = evaluate_for_control(['check', str(fixture_root.pinned)])
    check('control: a clean row has no problems', problems == [], f'({problems})')
    problems = verdict(1, '', 'rust_toolchain: asserted channel does not match', 0)
    check('control: an expected success that refused is a problem',
          any('status 1, want 0' in problem for problem in problems), f'({problems})')
    problems = verdict(0, f'{fixture.CHANNEL}\n', '', 1,
                       fragments=('asserted channel',))
    check('control: an expected refusal that succeeded is a problem',
          any('status 0, want 1' in problem for problem in problems), f'({problems})')
    problems = verdict(1, '', 'rust_toolchain: something else', 1,
                       fragments=('asserted channel',))
    check('control: a refusal missing its fragment is a problem',
          any('lacks' in problem for problem in problems), f'({problems})')


def evaluate_for_control(argv) -> list[str]:
    problems, status, out, err = run_row(argv)
    problems.extend(verdict(status, out, err, 0))
    return problems


# --- the fixture's own shape -------------------------------------------------

def test_fixture_manifest() -> None:
    """The synthetic manifest must be one a real rustup would accept.

    rustup 1.28.2 merges `extensions` into `components` and validates *every*
    reference in that vector, selected or not, so a fixture that only satisfies the
    shipped reader is not a faithful upstream shape.
    """
    print('fixture: the signed synthetic manifest satisfies upstream reference validation')
    url = f'https://static.rust-lang.org/dist/channel-rust-{fixture.CHANNEL}.toml'
    text = fixture_root.dist.files[url].decode()
    problems = fixture.unresolved_references(text)
    check('every merged component reference resolves to a package and target',
          problems == [], f'({problems})')
    for package in ('rust-docs', 'rust-src', 'rust-mingw'):
        check(f'the unselected {package} reference has a target record',
              f'[pkg.{package}.' in text, package)
    stripped = text.replace('[pkg.rust-src.target."*"]\navailable = false\n', '')
    check('the reference check catches a dropped wildcard target record',
          any('rust-src' in problem for problem in fixture.unresolved_references(stripped)),
          str(fixture.unresolved_references(stripped)))


