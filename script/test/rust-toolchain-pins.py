def test_settings_toml() -> None:
    """settings.toml: the grammar, and the rows a struct decoder would miss.

    The grammar column is the TOML 1.0 verdict, measured from `tomllib` on the
    Python the image shipped before #245. Since the oracle is gone this is a claim:
    a vendored-decoder change that moves a verdict shows up here only because the
    status is pinned, not because a second implementation disagrees.
    """
    print('verify-installed: TOML rows')
    toolchain = f'{fixture.CHANNEL}-{fixture.HOSTS["amd64"]}'
    clean = (f'profile = "minimal"\nauto_self_update = "disable"\n'
             f'auto_install = "disable"\ndefault_toolchain = "{toolchain}"\n')
    rows = [
        ('duplicate key', 'profile = "minimal"\n', 'not valid TOML'),
        ('redefined table', '[a]\nb = 1\n[a]\nc = 2\n', 'not valid TOML'),
        ('inline table extended by a dotted key', 'a = {b = 1}\na.c = 2\n',
         'not valid TOML'),
        ('inline table extended by a header', 'a = {b = 1}\n[a.c]\nd = 1\n',
         'not valid TOML'),
        ('table redefined after dotted keys', '[a]\nb.c = 1\n[a.b]\nd = 2\n',
         'not valid TOML'),
        ('trailing comma in an inline table', 'a = {b = 1,}\n', 'not valid TOML'),
        ('newline in an inline table', 'a = {b = 1,\nc = 2}\n', 'not valid TOML'),
        ('escape x', 'a = "\\x41"\n', 'not valid TOML'),
        ('local time', 'a = 07:32\n', 'not valid TOML'),
        ('crlf', None, ''),
        ('a date where a string belongs', 'profile = 2026-01-01\n',
         'installed: rustup setting profile is'),
    ]
    for label, extra, fragment in rows:
        if label == 'crlf':
            body = clean.replace('\n', '\r\n')
        elif label == 'a date where a string belongs':
            body = clean.replace('profile = "minimal"\n', extra)
        else:
            body = clean + extra
        rustup_home = settings_row(body)
        argv = ['verify-installed', str(fixture_root.pinned), '--arch', 'amd64',
                '--expect-channel', fixture.CHANNEL, '--rustup-home', str(rustup_home),
                '--cargo-home', TOOLS['cargo']]
        if fragment:
            go_row(f'TOML {label}', argv, fragments=(fragment,), expect=1)
        else:
            go_row(f'TOML {label}', argv)
    # P4: the TOML 1.1 `\e` escape. No go-toml/v2 release refuses it, so the reader
    # accepts the document. It was a declared divergence while the Python oracle
    # refused it; the oracle is gone (#245), so what remains is this acceptance row
    # and `TestTOMLGrammar/escape-e` in the layer's Go tests, which pins the value.
    # Nothing catches a go-toml release that starts refusing the escape.
    escape_row = settings_row(clean + 'a = "\\e"\n')
    go_row('P4: the TOML 1.1 \\e escape is accepted',
           ['verify-installed', str(fixture_root.pinned), '--arch', 'amd64',
            '--expect-channel', fixture.CHANNEL, '--rustup-home', str(escape_row),
            '--cargo-home', TOOLS['cargo']])


