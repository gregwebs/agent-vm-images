def test_install_command(fixture_root: driver.Fixture) -> None:
    print('install command: preconditions before fetch and scratch cleanup')
    arch = model.Architecture.ARM64
    # An existing install home must be refused before a single payload byte is
    # fetched: a full download followed by a refusal would also be a bug.
    base = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    base.mkdir()
    home = base / 'rustup'
    home.mkdir()
    dependencies = fixture_dependencies(fixture_root, arch)
    code = model.main(['install', str(fixture_root.pinned), '--arch', arch.value,
                       '--expect-channel', fixture.CHANNEL, '--rustup-home', str(home),
                       '--cargo-home', str(base / 'cargo'), '--work-dir', str(base)],
                      dependencies)
    check('an existing home refuses the install command', code == 1)
    check('no payload is fetched before the home precondition',
          dependencies.transport.fetches == [], f'({dependencies.transport.fetches})')
    check('no process runs before the home precondition',
          dependencies.runner.executed() == [])
    check('the refused home is left untouched', sorted(path.name for path in home.iterdir()) == [])

    # Success leaves no downloads, dist layout or bootstrap behind in the
    # working directory: only the installed homes are state.
    base = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    base.mkdir()
    dependencies = fixture_dependencies(fixture_root, arch)
    code = model.main(['install', str(fixture_root.pinned), '--arch', arch.value,
                       '--expect-channel', fixture.CHANNEL, '--rustup-home', str(base / 'rustup'),
                       '--cargo-home', str(base / 'cargo'), '--work-dir', str(base)],
                      dependencies)
    check('a clean install command exits 0', code == 0)
    leftovers = sorted(path.name for path in base.iterdir() if path.name not in ('rustup', 'cargo'))
    check('no scratch, downloads or bootstrap remain after success', leftovers == [],
          f'({leftovers})')

    # The same holds when the install itself fails: the verified scratch is not
    # retained as host or image state.
    base = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    base.mkdir()
    runner = driver.RecordingRunner(arch, fixture.CHANNEL, fixture.RUSTUP_VERSION,
                                    fail_when=lambda argv: 'toolchain' in argv)
    dependencies = fixture_dependencies(fixture_root, arch, runner=runner)
    code = model.main(['install', str(fixture_root.pinned), '--arch', arch.value,
                       '--expect-channel', fixture.CHANNEL, '--rustup-home', str(base / 'rustup'),
                       '--cargo-home', str(base / 'cargo'), '--work-dir', str(base)],
                      dependencies)
    check('a failed install command exits 1', code == 1)
    leftovers = sorted(path.name for path in base.iterdir() if path.name not in ('rustup', 'cargo'))
    check('no scratch remains after a failed install', leftovers == [], f'({leftovers})')


def test_transport() -> None:
    print('transport: real HTTPS transport with a controlled opener')
    transport = model.HttpsTransport(deadline_seconds=5.0)
    destination = Path(tempfile.mkdtemp()) / 'file'
    url = model.parse_url(f'https://static.rust-lang.org/dist/x-{fixture.CHANNEL}.tar.xz', 'url')

    class Response:
        def __init__(self, status=200, body=b'ok', declared=None, chunks=None):
            self.status = status
            self.body = body
            self.headers = {} if declared is None else {'Content-Length': str(declared)}
            self.chunks = chunks

        def read(self, size=-1):
            if self.chunks is not None:
                return self.chunks.pop(0) if self.chunks else b''
            data, self.body = self.body, b''
            return data

        def __enter__(self):
            return self

        def __exit__(self, *arguments):
            return False

    transport._open = lambda url_text, timeout: Response(status=302)
    refuses('redirect responses are refused', lambda: transport.fetch(url, destination, 1024),
            'unexpected HTTP status 302')
    transport._open = lambda url_text, timeout: Response(declared=10, body=b'abc')
    refuses('truncated stream is refused', lambda: transport.fetch(url, destination, 1024),
            'truncated stream')
    transport._open = lambda url_text, timeout: Response(body=b'x' * 2048)
    refuses('oversized stream is refused', lambda: transport.fetch(url, destination, 1024),
            'exceeds 1024 bytes')

    class FailingResponse(Response):
        def read(self, size=-1):
            # A socket timeout, reset or broken pipe inside the deadline must be a
            # refusal, not an uncaught exception escaping the transport.
            raise TimeoutError('simulated socket timeout')

    transport._open = lambda url_text, timeout: FailingResponse()
    refuses('a read that raises inside the deadline is refused',
            lambda: transport.fetch(url, destination, 1024), 'read failed or exceeded the deadline')
    check('a failed read leaves no verified state', not destination.exists())
    clock = [0.0]
    transport = model.HttpsTransport(deadline_seconds=10.0, clock=lambda: clock[0])

    class SlowResponse(Response):
        def read(self, size=-1):
            clock[0] += 30.0
            return b'chunk'

    transport._open = lambda url_text, timeout: SlowResponse(body=b'ignored')
    refuses('a trickling stream cannot outlive the whole-request deadline',
            lambda: transport.fetch(url, destination, 1 << 20), 'download deadline exceeded')
    check('no partial file becomes verified state', not destination.exists())

    # A read that does not return at all is what the clock checks alone cannot
    # bound: this response models a stalled peer and only unblocks when the
    # transport closes it. Without a request watchdog the refusal cannot arrive
    # before the 5-second block.
    class BlockedResponse(Response):
        def __init__(self):
            super().__init__()
            self._released = threading.Event()
            self.closed_by_watchdog = False

        def read(self, size=-1):
            self._released.wait(5.0)
            if self.closed_by_watchdog:
                raise TimeoutError('closed at the deadline')
            return b''

        def close(self):
            self.closed_by_watchdog = True
            self._released.set()

    blocked = BlockedResponse()
    transport = model.HttpsTransport(deadline_seconds=0.05)
    transport._open = lambda url_text, timeout: blocked
    started = time.monotonic()
    refuses('a read that never returns is aborted at the deadline',
            lambda: transport.fetch(url, destination, 1 << 20), 'download deadline exceeded')
    elapsed = time.monotonic() - started
    check('the blocked read is aborted at the deadline, not after the peer answers',
          elapsed < 0.5, f'({elapsed:.3f}s)')
    check('the transport closed the stalled response', blocked.closed_by_watchdog)

    # The socket's own timeout is capped by the remaining budget, so a blocking
    # read cannot wait out the full inactivity timeout when less budget is left.
    class Socket:
        def __init__(self):
            self.timeouts = []

        def settimeout(self, value):
            self.timeouts.append(value)

    class SocketResponse(Response):
        def __init__(self):
            super().__init__(body=b'ok')
            self.fp = SimpleNamespace(raw=SimpleNamespace(_sock=Socket()))
            self.socket = self.fp.raw._sock

        def read(self, size=-1):
            return super().read(size)

    socket_response = SocketResponse()
    transport = model.HttpsTransport(deadline_seconds=0.5)
    transport._open = lambda url_text, timeout: socket_response
    transport.fetch(url, destination, 1024)
    check('each read caps the socket timeout to the remaining budget',
          socket_response.socket.timeouts and max(socket_response.socket.timeouts) <= 0.5,
          f'({socket_response.socket.timeouts})')


class _LoopbackServer:
    """A real loopback HTTP server with a deliberately slow, trickling writer.

    The fake responses above prove the transport's own bookkeeping; these controls
    prove the deadline against real blocking socket I/O, where the peer keeps
    resetting urllib's inactivity timeout and only an interrupted socket can stop
    the read.
    """

    def __init__(self, writer) -> None:
        self._writer = writer
        self._server = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self._server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self._server.bind(('127.0.0.1', 0))
        self._server.listen(1)
        self.port = self._server.getsockname()[1]
        self._stop = threading.Event()
        self._thread = threading.Thread(target=self._serve, daemon=True)
        self._thread.start()

    def _serve(self) -> None:
        try:
            client, _ = self._server.accept()
        except OSError:
            return
        with client:
            client.settimeout(30)
            request = b''
            while b'\r\n\r\n' not in request and not self._stop.is_set():
                try:
                    request += client.recv(4096)
                except OSError:
                    return
            try:
                self._writer(client)
            except OSError:
                # The transport interrupts the socket at the deadline; the peer
                # then sees a broken pipe, which is the expected end of the probe.
                pass

    def close(self) -> None:
        self._stop.set()
        with contextlib.suppress(OSError):
            self._server.close()
        self._thread.join(timeout=10)

    def url(self, path: str = '/dist/probe.tar.xz') -> model.CanonicalUrl:
        # A CANONICAL ORIGIN IS NOT CONSTRUCTED HERE: the production policy lives
        # in `parse_url`, and this probe deliberately drives the transport against
        # a local socket instead of the internet.
        return model.CanonicalUrl(f'http://127.0.0.1:{self.port}{path}')


def _trickle_headers(client) -> None:
    """Send a status line, then one header character every 40 ms forever."""
    client.sendall(b'HTTP/1.1 200 OK\r\n')
    for char in b'X-Slow: ' + b'x' * 4096 + b'\r\n\r\n':
        time.sleep(0.04)
        client.sendall(bytes([char]))


def _trickle_body(client) -> None:
    """Announce 64 KiB and then send one byte every 40 ms."""
    client.sendall(b'HTTP/1.1 200 OK\r\nContent-Length: 65536\r\n\r\n')
    for _ in range(65536):
        time.sleep(0.04)
        client.sendall(b'x')


def test_transport_real_deadline() -> None:
    print('transport: real loopback peers cannot outlive the whole-request deadline')
    destination_root = Path(tempfile.mkdtemp())

    server = _LoopbackServer(_trickle_headers)
    try:
        transport = model.HttpsTransport(deadline_seconds=0.5)
        started = time.monotonic()
        refuses('trickled response headers are refused at the deadline',
                lambda: transport.fetch(server.url(), destination_root / 'headers', 1 << 20),
                'deadline exceeded')
        elapsed = time.monotonic() - started
        check('the header deadline is external to the transport clock', elapsed < 3.0,
              f'({elapsed:.3f}s against a 0.5 s budget)')
    finally:
        server.close()
    check('a refused header read leaves no verified destination',
          not (destination_root / 'headers').exists())

    server = _LoopbackServer(_trickle_body)
    try:
        transport = model.HttpsTransport(deadline_seconds=0.5)
        started = time.monotonic()
        refuses('a trickled response body is refused at the deadline',
                lambda: transport.fetch(server.url(), destination_root / 'body', 1 << 20),
                'deadline exceeded')
        elapsed = time.monotonic() - started
        check('the body deadline is external to the transport clock', elapsed < 3.0,
              f'({elapsed:.3f}s against a 0.5 s budget)')
    finally:
        server.close()
    check('a refused body read leaves no verified destination',
          not (destination_root / 'body').exists())


def _rust_host_blocks(text: str) -> list[str]:
    return re.findall(r'^\[pkg\.rust\.target\.([a-z0-9_-]+)\]$', text, re.MULTILINE)


def _pair(package: str, target: str | None, date: str) -> str:
    """A coherent archive pair for a mutation-only package row."""
    name = package if target is None else f'{package}-{target}'
    base = f'https://static.rust-lang.org/dist/{date}/{name}'
    table = f'pkg.{package}.target.{"*" if target is None else target}' if target else \
        f'pkg.{package}.target."*"'
    return '\n'.join([f'[{table}]', 'available = true',
                       f'url = "{base}.tar.gz"', f'hash = "{"0" * 64}"',
                       f'xz_url = "{base}.tar.xz"', f'xz_hash = "{"0" * 64}"']) + '\n'


def test_real_manifest_selection() -> None:
    """Selection controls against the committed manifest, offline.

    `verify_manifest_closure` is the boundary that runs after the signature: a
    legitimately signed manifest whose host tables describe a different closure
    must still be refused. The mutants below are exactly rustup shapes the
    superseded two-independent-table model got wrong in both directions.
    """
    print('real committed manifest: merged-table and wildcard selection controls')
    pin = model.load_pin(REAL_DATADIR)
    text = (REAL_DATADIR / 'channel.toml').read_text()
    date = pin.release_date.value
    check('the committed manifest derives the reviewed closure',
          model.verify_manifest_closure(text.encode(), pin) is None)
    hosts = set(_rust_host_blocks(text))
    check('the committed manifest names both pinned hosts',
          all(arch.host.value in hosts for arch in model.Architecture))

    host = model.Architecture.AMD64.host.value
    src_row = f'[[pkg.rust.target.{host}.extensions]]\npkg = "rust-src"\ntarget = "*"\n'
    check('the real manifest has a wildcard extension row to anchor mutations', src_row in text)

    # A profile row declared as a host extension: rustup's merged table still
    # selects it, so this must be *accepted* -- the six-entry closure is unchanged.
    moved = text.replace(
        f'[[pkg.rust.target.{host}.components]]\npkg = "rust-std"\ntarget = "{host}"\n',
        f'[[pkg.rust.target.{host}.extensions]]\npkg = "rust-std"\ntarget = "{host}"\n', 1)
    check('the merged-table mutation applied', moved != text)
    try:
        model.verify_manifest_closure(moved.encode(), pin)
    except model.ToolchainError as error:
        check('real manifest: a profile row declared as an extension is still selected',
              False, f'(refused with "{error}")')
    else:
        check('real manifest: a profile row declared as an extension is still selected', True)

    # A coherent wildcard exclusion: the wildcard row plus the wildcard package is
    # a seventh, target-independent component that rustup would install.
    wildcard = text.replace(
        src_row,
        f'[[pkg.rust.target.{host}.extensions]]\npkg = "rust-mingw"\ntarget = "*"\n\n'
        + src_row, 1)
    check('the wildcard mutation applied', wildcard != text)
    wildcard += '\n' + _pair('rust-mingw', None, date)
    refuses('real manifest: a wildcard merged-table component is refused',
            lambda: model.verify_manifest_closure(wildcard.encode(), pin),
            'target-independent component')

    # The same package as a host-targeted extension is a concrete seventh archive.
    added = text.replace(
        src_row,
        f'[[pkg.rust.target.{host}.extensions]]\npkg = "rust-mingw"\ntarget = "{host}"\n\n'
        + src_row, 1)
    check('the host-extension mutation applied', added != text)
    added += '\n' + _pair('rust-mingw', host, date)
    refuses('real manifest: a new host extension widens the reviewed closure',
            lambda: model.verify_manifest_closure(added.encode(), pin),
            'not the manifest-derived')

    # The invented singular flag is not a rustup field and must not be honoured.
    flagged = text.replace(
        src_row,
        f'[[pkg.rust.target.{host}.extensions]]\npkg = "rust-src"\nextension = false\n'
        'target = "*"\n', 1)
    check('the extension-flag mutation applied', flagged != text)
    refuses('real manifest: the invented extension flag is refused',
            lambda: model.verify_manifest_closure(flagged.encode(), pin),
            'not a rustup component field')


