def test_installer_mutants(fixture_root: driver.Fixture) -> None:
    print('mutants: the installer oracles kill live fetches, early execution and retries')
    arch = model.Architecture.AMD64
    pin = model.load_pin(fixture_root.pinned, fixture_root.trust)

    # 1. The reviewer's added live downloader: one extra fetch before bootstrap.
    class LiveDownloader(driver.RecordingRunner):
        def __init__(self, *arguments, **keywords):
            super().__init__(*arguments, **keywords)
            self.injected = False

        def run(self, argv, env, cwd=None):
            if str(argv[0]).endswith('rustup-init') and not self.injected:
                self.injected = True
                super().run(['/usr/bin/curl', 'https://sh.rustup.rs'], env)
            return super().run(argv, env, cwd)

    work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    work.mkdir()
    transport = driver.FixtureTransport(fixture_root.dist.files)
    layout = model.prepare(fixture_root.pinned, pin, arch, work / 'scratch', transport,
                           fixture_root.verifier(work / 'verify'), model.Events())
    runner = LiveDownloader(model.Architecture.AMD64, fixture.CHANNEL, fixture.RUSTUP_VERSION)
    events = model.Events()
    refused = False
    try:
        model.install(layout, model.InstallHomes(work / 'rustup', work / 'cargo'), arch, pin,
                      runner, events)
    except model.ToolchainError:
        refused = True
    check('the runner fails closed on an added live downloader', refused)
    check('the added downloader is visible in the transcript',
          any('curl' in line for line in runner.executed()), f'({runner.executed()})')
    check('the added downloader is caught by the transcript oracle',
          clean_transcript_problems(runner, transport, arch, events) != [])
    check('the added downloader did not become installed state',
          not (work / 'cargo').exists() and not any(
              line.startswith('install-ok') for line in events.lines))

    # 2. A late (sixth) archive corruption through the real prepare, with a
    #    runner that records *actual process calls* as well as events: nothing may
    #    execute and no origin may be fetched twice. The clean run must produce no
    #    problems at all; the two mutants below must produce exactly theirs, so a
    #    green result is evidence rather than an artefact of an unchecked oracle.
    def late_corruption_problems(module, label: str) -> list[str]:
        mutant_trust = module.TrustPolicy(
            primary=module.Fingerprint(fixture_root.dist.fingerprint),
            signers=(module.Fingerprint(fixture_root.dist.fingerprint),))
        mutant_pin = module.load_pin(fixture_root.pinned, mutant_trust)
        mutant_arch = module.Architecture.AMD64
        corrupt_transport = driver.FixtureTransport(fixture_root.dist.files)
        last = module.selected_pairs(mutant_arch)[-1]
        corrupt_transport.fault(archive_url(last[0], last[1].value),
                                lambda raw: b'\x00' + raw[1:])
        # A short path: a gpg-agent unix socket inside a deeper directory exceeds
        # the platform's socket-path limit and the signature check would fail for
        # an unrelated reason.
        corner = Path(tempfile.mkdtemp(dir=fixture_root.root))
        # The runner records the real process calls, including any bootstrap a
        # mutant starts before the sixth archive is verified.
        runner = driver.RecordingRunner(mutant_arch, fixture.CHANNEL,
                                        fixture.RUSTUP_VERSION)
        trust = module.TrustPolicy(
            primary=module.Fingerprint(fixture_root.dist.fingerprint),
            signers=(module.Fingerprint(fixture_root.dist.fingerprint),))
        verifier = module.SignatureVerifier(module.GpgProgram(driver._gpg_path()),
                                            fixture_root.dist.key, corner / 'v',
                                            runner, trust)
        events = module.Events()
        problems: list[str] = []
        try:
            module.prepare(fixture_root.pinned, mutant_pin, mutant_arch, corner / 'p',
                           corrupt_transport, verifier, events)
        except (module.ToolchainError, driver.UnrecognizedCommand):
            # A bootstrap started before the closure was verified is refused by the
            # runner *and* recorded as a call; the oracle below is what fails the
            # mutant, so the refusal must not hide the recorded call.
            pass
        else:
            problems.append('the corrupt late archive was accepted')
        bootstraps = [argv for argv, _, _ in runner.calls if argv[0].endswith('rustup-init')]
        if bootstraps:
            problems.append(f'executed the bootstrap before the closure was verified: '
                            f'{bootstraps}')
        fetches = corrupt_transport.fetches
        if len(fetches) != len(set(fetches)):
            problems.append('retried a fetch instead of refusing the mismatch')
        known = {module.expected_bootstrap_url(module.Semver(fixture.RUSTUP_VERSION),
                                               mutant_arch)}
        known |= {archive_url(package, target.value) for package, target in
                  module.selected_pairs(mutant_arch)}
        if set(fetches) - known:
            problems.append('fetched an origin outside the committed closure')
        executions = [line for line in events.lines if line.startswith('execute')]
        if executions:
            problems.append(f'executed before the closure was verified: {executions}')
        return problems

    clean = late_corruption_problems(model, 'late-sixth-clean')
    check('a corrupt sixth archive is refused with no bootstrap call and no retried fetch',
          clean == [], f'({clean})')

    mutants = {
        'early-bootstrap-process-call': [(
            '    bootstrap.chmod(0o755)\n',
            '    bootstrap.chmod(0o755)\n'
            "    verifier._runner.run([str(bootstrap), '-y', '--no-modify-path',\n"
            "                          '--default-host', arch.host.value,\n"
            "                          '--default-toolchain', 'none', '--profile', PROFILE],\n"
            "                         {'RUSTUP_HOME': str(work / 'early-rustup'),\n"
            "                          'CARGO_HOME': str(work / 'early-cargo')})\n")],
        'retry-after-mismatch': [(
            "            refuse(f'{name}: downloaded bytes do not match the signed manifest hash')",
            "            transport.fetch(archive.content.url, target_path, MAX_ARCHIVE_BYTES)\n"
            "            refuse(f'{name}: downloaded bytes do not match the signed manifest hash')")],
    }
    expected_reason = {
        'early-bootstrap-process-call': 'executed the bootstrap',
        'retry-after-mismatch': 'retried a fetch',
    }
    for name, replacements in mutants.items():
        module = driver.load_mutant(name, replacements, fixture_root.root / 'mutants')
        problems = late_corruption_problems(module, name)
        check(f'mutant {name} is killed by the actual-call/fetch oracle',
              any(expected_reason[name] in problem for problem in problems),
              f'({problems})')


def test_runner_dispatch(fixture_root: driver.Fixture) -> None:
    print('runner: executable-plus-complete-argv dispatch fails closed')
    root = Path(tempfile.mkdtemp(dir=fixture_root.root))
    homes = root / 'homes'
    bins = homes / 'cargo' / 'bin'
    bins.mkdir(parents=True)
    env = {'RUSTUP_HOME': str(homes / 'rustup'), 'CARGO_HOME': str(homes / 'cargo')}
    runner = driver.RecordingRunner(model.Architecture.ARM64, fixture.CHANNEL,
                                    fixture.RUSTUP_VERSION)

    def accepted(argv) -> bool:
        try:
            runner.run(argv, env)
        except driver.UnrecognizedCommand:
            return False
        return True

    cases = [
        (['/unregistered/program', 'clippy', '--version'], False,
         'an unregistered executable with an allowlisted argv tail'),
        ([str(bins / 'cargo'), 'clippy', '--version'], True, 'the real cargo clippy call'),
        ([str(bins / 'cargo'), 'clippy', '--version', '--extra'], False,
         'a recognized executable with an extra argument'),
        ([str(bins / 'rustup'), 'toolchain', 'list', '--installed'], False,
         'a recognized executable with an unlisted argv'),
        (['/usr/bin/rustup', '--version'], False,
         'a rustup that is not the one in the install homes'),
        ([str(bins / 'rustup'), '--version'], True, 'the real rustup --version call'),
    ]
    for argv, expected, label in cases:
        check(f'runner {"accepts" if expected else "refuses"} {label}',
              accepted(argv) is expected, f'({argv})')

    # The bootstrap is authorized by the verified layout path, not by its name: a
    # foreign program with the same basename and the documented argv is a
    # different file, so it must be refused even after a real layout registered.
    bootstrap_argv = ['-y', '--no-modify-path', '--default-host',
                      model.Architecture.ARM64.host.value, '--default-toolchain', 'none',
                      '--profile', 'minimal']
    work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    layout = model.prepare(fixture_root.pinned, model.load_pin(fixture_root.pinned,
                                                               fixture_root.trust),
                           model.Architecture.ARM64, work,
                           driver.FixtureTransport(fixture_root.dist.files),
                           fixture_root.verifier(work), model.Events())
    check('a prepared layout registered its own bootstrap',
          os.path.realpath(str(layout.bootstrap)) in driver.REGISTERED_BOOTSTRAPS)
    foreign = root / 'unregistered'
    foreign.mkdir()
    planted = foreign / 'rustup-init'
    planted.write_bytes(Path(layout.bootstrap).read_bytes())
    planted.chmod(0o755)
    check('runner accepts the registered verified bootstrap',
          accepted([str(layout.bootstrap), *bootstrap_argv]), str(layout.bootstrap))
    check('runner refuses a same-basename foreign path with the documented argv',
          not accepted([str(planted), *bootstrap_argv]), str(planted))
    check('runner refuses a same-basename foreign path by basename alone',
          not accepted(['/unregistered/rustup-init', *bootstrap_argv]), '/unregistered')
    check('runner refuses the verified bootstrap with a different argv',
          not accepted([str(layout.bootstrap), *bootstrap_argv, '--extra']))
    check('runner delegates real gpg by resolved identity',
          accepted([driver._gpg_path(), '--version']))
    fake_gpg = foreign / 'gpg'
    fake_gpg.write_text('#!/bin/sh\nexit 0\n')
    fake_gpg.chmod(0o755)
    check('runner refuses a foreign program named gpg', not accepted([str(fake_gpg), '--version']))


