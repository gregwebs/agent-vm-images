def test_fixture_manifest(fixture_root: driver.Fixture) -> None:
    """The synthetic manifest must be one a real rustup would accept.

    rustup 1.28.2 merges `extensions` into `components` and validates *every*
    reference in that vector, selected or not, so a fixture that only satisfies
    the shipped reader is not a faithful upstream shape.
    """
    print('fixture: the signed synthetic manifest satisfies upstream reference validation')
    url = f'https://static.rust-lang.org/dist/channel-rust-{fixture.CHANNEL}.toml'
    text = fixture_root.dist.files[url].decode()
    problems = fixture.unresolved_references(text)
    check('every merged component reference resolves to a package and target',
          problems == [], f'({problems})')
    for package in ('rust-docs', 'rust-src', 'rust-mingw'):
        check(f'the unselected {package} reference has a target record',
              f'[pkg.{package}.' in text, package)
    # The same check on the shape this fixture used before: it must catch the
    # missing records, or a green result would not be evidence.
    stripped = text.replace('[pkg.rust-src.target."*"]\navailable = false\n', '')
    check('the reference check catches a dropped wildcard target record',
          any('rust-src' in problem for problem in fixture.unresolved_references(stripped)),
          str(fixture.unresolved_references(stripped)))


def test_manifest_refusals(fixture_root: driver.Fixture) -> None:
    print('verify_inputs: signed manifest semantics')
    pin = model.load_pin(fixture_root.pinned, fixture_root.trust)
    work = Path(tempfile.mkdtemp(dir=fixture_root.root))
    verifier = fixture_root.verifier(work)

    def with_manifest(name: str, text: str, expected: str | None) -> None:
        """Re-sign `text` with the fixture key, then expect a refusal (or acceptance).

        `expected is None` is a positive control: the mutation must leave the
        verified selection unchanged, so only a faithful model accepts it.
        """
        target = driver.copy_pin(fixture_root.pinned, fixture_root.root / f'manifest-{name}')
        raw = text.encode()
        (target / 'channel.toml').write_bytes(raw)
        (target / 'channel.toml.sha256').write_text(
            model.sha_of_bytes(raw) + f'  channel-rust-{fixture.CHANNEL}.toml\n')
        document = json.loads((target / 'pin.json').read_text())
        document['manifest']['sha256'] = model.sha_of_bytes(raw)
        document['manifest']['checksum']['sha256'] = model.sha_of_bytes(
            (target / 'channel.toml.sha256').read_bytes())
        # Re-sign with the fixture key so only the semantic rule under test can fail.
        signed = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'resign-input'
        signed.write_bytes(raw)
        signature = fixture.armored_sign(signed, fixture.sign_env(fixture_root.dist))
        (target / 'channel.toml.asc').write_bytes(signature)
        document['manifest']['signature']['sha256'] = model.sha_of_bytes(signature)
        (target / 'pin.json').write_text(json.dumps(document, indent=2) + '\n')
        mutant = model.load_pin(target, fixture_root.trust)
        if expected is None:
            try:
                model.verify_inputs(target, mutant, verifier)
            except model.ToolchainError as error:
                check(f'manifest {name}', False, f'(refused with "{error}")')
            else:
                check(f'manifest {name} is accepted', True)
            return
        refuses(f'manifest {name}', lambda: model.verify_inputs(target, mutant, verifier),
                expected)

    original = fixture_root.dist.files[
        f'https://static.rust-lang.org/dist/channel-rust-{fixture.CHANNEL}.toml'].decode()
    with_manifest('malformed-toml', original.replace('[renames.clippy]', '[renames.clippy'),
                  'not valid TOML')
    with_manifest('profile-change', original.replace(
        'minimal = ["rustc", "cargo", "rust-std", "rust-mingw"]',
        'minimal = ["rustc", "cargo", "rust-std", "rust-mingw", "rust-docs"]'),
        'schema/policy review required')
    with_manifest('rename-change', original.replace(
        'to = "clippy-preview"', 'to = "clippy"'), 'unexpected rename')
    with_manifest('zstd-present', original.replace(
        f'xz_url = "https://static.rust-lang.org/dist/{fixture.DATE}/cargo-{fixture.CHANNEL}-'
        f'{fixture.HOSTS["amd64"]}.tar.xz"',
        f'zst_url = "https://static.rust-lang.org/dist/{fixture.DATE}/cargo-{fixture.CHANNEL}-'
        f'{fixture.HOSTS["amd64"]}.tar.zst"\nxz_url = "https://static.rust-lang.org/dist/'
        f'{fixture.DATE}/cargo-{fixture.CHANNEL}-{fixture.HOSTS["amd64"]}.tar.xz"'),
        'advertises zstd')
    with_manifest('hash-mismatch', corrupt_cargo_hash(original), 'xz_hash')
    with_manifest('unavailable', original.replace(
        f'[pkg.cargo.target.{fixture.HOSTS["amd64"]}]\navailable = true',
        f'[pkg.cargo.target.{fixture.HOSTS["amd64"]}]\navailable = false'),
        'is not available')
    with_manifest('date', original.replace(f'date = "{fixture.DATE}"', 'date = "2026-02-30"'),
                  'not a calendar date')
    with_manifest('version', original.replace(fixture.RUST_VERSION, '9.9.8 (x 2026-01-01)'),
                  'release version does not match')

    # --- rustup's own selection rule (get_profile_components/extensions) -----
    host = fixture.HOSTS['amd64']
    other = fixture.HOSTS['arm64']
    musl = fixture.MUSL['amd64']

    def rust_host_text(text: str, name: str, host_name: str = host) -> str:
        """The `[pkg.rust.target.<host>]` block body for one host."""
        start = text.index(f'[pkg.rust.target.{host_name}]')
        end = text.index('[pkg.', start + 1)
        return text[start:end]

    def component_block(package: str, target: str, host_name: str = host) -> str:
        return (f'[[pkg.rust.target.{host_name}.components]]\npkg = "{package}"\n'
                f'target = "{target}"\n\n')

    def extension_block(package: str, target: str, host_name: str = host) -> str:
        return (f'[[pkg.rust.target.{host_name}.extensions]]\npkg = "{package}"\n'
                f'target = "{target}"\n\n')

    with_manifest('components-removed',
                  original.replace(component_block('rustc', host), '', 1),
                  'absent from its components table')
    with_manifest('components-retargeted',
                  original.replace(component_block('rustc', host),
                                   component_block('rustc', other), 1),
                  'absent from its components table')
    with_manifest('components-added',
                  original.replace(component_block('rust-docs', host),
                                   component_block('rust-docs', host) +
                                   component_block('rust-std', host), 1),
                  'listed twice')
    with_manifest('components-table-missing',
                  original.replace(component_block('rustc', host), '', 1).replace(
                      component_block('rust-std', host), '', 1).replace(
                      component_block('cargo', host), '', 1).replace(
                      component_block('rust-docs', host), '', 1),
                  'missing components')
    with_manifest('extension-removed',
                  original.replace(extension_block('clippy-preview', host), '', 1),
                  'is not a single')
    with_manifest('extension-retargeted',
                  original.replace(extension_block('clippy-preview', host),
                                   extension_block('clippy-preview', other), 1),
                  'is not a single')
    # rustup's field is `is_extension`, and its merge forces every extensions row
    # to `is_extension = true`; the invented singular flag cannot disable a row,
    # so honouring it here would make the validator disagree with the installer.
    with_manifest('extension-flag',
                  original.replace(extension_block('rustfmt-preview', host),
                                   extension_block('rustfmt-preview', host).replace(
                                       'target = ', 'extension = false\ntarget = ', 1), 1),
                  'not a rustup component field')
    with_manifest('component-target-type',
                  original.replace(component_block('cargo', host),
                                   f'[[pkg.rust.target.{host}.components]]\npkg = "cargo"\n'
                                   'target = 5\n\n', 1),
                  'expected str')
    # The merged table: rustup appends `extensions` to `components` and searches
    # the result, so a profile name declared as a host-targeted extension is
    # still selected. Two independent tables would wrongly refuse this.
    with_manifest('merged-table-profile',
                  original.replace(component_block('rust-std', host),
                                   extension_block('rust-std', host), 1),
                  None)
    # A coherent target-independent component: the wildcard rust-mingw extension
    # plus a wildcard package row is what rustup would install as a seventh
    # component, so the reviewed six-entry pin must refuse it.
    with_manifest('wildcard-extension',
                  original.replace(extension_block('rust-mingw', fixture.WINDOWS['amd64']),
                                   extension_block('rust-mingw', '*'), 1) +
                  f'[pkg.rust-mingw.target."*"]\navailable = true\n'
                  f'url = "https://static.rust-lang.org/dist/{fixture.DATE}/'
                  f'rust-mingw-{fixture.CHANNEL}.tar.gz"\n'
                  f'hash = "{"0" * 64}"\n'
                  f'xz_url = "https://static.rust-lang.org/dist/{fixture.DATE}/'
                  f'rust-mingw-{fixture.CHANNEL}.tar.xz"\n'
                  f'xz_hash = "{"0" * 64}"\n',
                  'target-independent component')
    # The same package as a host-targeted extension resolves to a concrete
    # seventh archive, which the committed closure does not contain.
    with_manifest('host-extension-added',
                  original.replace(extension_block('rust-mingw', fixture.WINDOWS['amd64']),
                                   extension_block('rust-mingw', host), 1) +
                  f'[pkg.rust-mingw.target.{host}]\navailable = true\n'
                  f'url = "https://static.rust-lang.org/dist/{fixture.DATE}/'
                  f'rust-mingw-{fixture.CHANNEL}-{host}.tar.gz"\n'
                  f'hash = "{"0" * 64}"\n'
                  f'xz_url = "https://static.rust-lang.org/dist/{fixture.DATE}/'
                  f'rust-mingw-{fixture.CHANNEL}-{host}.tar.xz"\n'
                  f'xz_hash = "{"0" * 64}"\n',
                  'not the manifest-derived')
    with_manifest('musl-std-retargeted',
                  original.replace(extension_block('rust-std', musl),
                                   extension_block('rust-std', host), 1),
                  'is not a single')

    def gzip_line(name: str) -> str:
        marker = f'[pkg.{name}.target.{host}]'
        start = original.index(marker)
        end = original.index('[pkg.', start + 1)
        body = original[start:end]
        return next(line for line in body.splitlines() if line.startswith('hash = '))

    with_manifest('gzip-half-pair',
                  original.replace(gzip_line('cargo') + '\n', '', 1),
                  'half gzip format pair')
    with_manifest('gzip-renamed-half',
                  original.replace(gzip_line('cargo'),
                                   gzip_line('cargo').replace('hash = ', 'ignored_hash = '), 1),
                  'unknown keys')
    with_manifest('gzip-hash-shape',
                  original.replace(gzip_line('rustfmt-preview'), 'hash = "not-a-digest"', 1),
                  'gzip hash')


def corrupt_cargo_hash(text: str) -> str:
    marker = f'[pkg.cargo.target.{fixture.HOSTS["amd64"]}]'
    head, tail = text.split(marker, 1)
    body, rest = tail.split('\n[', 1)
    mutated = re.sub(r'xz_hash = "[0-9a-f]{64}"', 'xz_hash = "' + 'f' * 64 + '"', body)
    assert mutated != body
    return head + marker + mutated + '\n[' + rest


