def test_install_refusals(fixture_root: driver.Fixture) -> None:
    print('install: preconditions and cleanup')
    for label, setup in (
            ('existing empty home', 'empty'),
            ('existing populated home', 'populated'),
            ('dangling symlink home', 'dangling'),
    ):
        work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
        layout = prepare_layout(fixture_root, model.Architecture.ARM64, work=work)
        work.mkdir(parents=True, exist_ok=True)
        home = work / 'rustup'
        if setup == 'empty':
            home.mkdir()
        elif setup == 'populated':
            home.mkdir()
            (home / 'settings.toml').write_text('version = "12"\n')
        else:
            os.symlink('/nonexistent-target', home)
        before = {path.name: path.read_bytes() for path in home.parent.iterdir()
                  if path.is_file()}
        runner = driver.RecordingRunner(model.Architecture.ARM64, fixture.CHANNEL,
                                        fixture.RUSTUP_VERSION)
        pin = model.load_pin(fixture_root.pinned, fixture_root.trust)
        refuses(f'{label} refuses before bootstrap',
                lambda: model.install(layout, model.InstallHomes(home, work / 'cargo'),
                                      model.Architecture.ARM64, pin, runner, model.Events()),
                'refusing to install over an existing path')
        check(f'{label}: no process executed', runner.executed() == [])
        check(f'{label}: original bytes unchanged',
              {path.name: path.read_bytes() for path in home.parent.iterdir()
               if path.is_file()} == before)

    # A symlinked ancestor redirects creation, and later cleanup, outside the
    # named tree: refused before anything is fetched or created.
    work = Path(tempfile.mkdtemp(dir=fixture_root.root)) / 'work'
    layout = prepare_layout(fixture_root, model.Architecture.ARM64, work=work)
    work.mkdir(parents=True, exist_ok=True)
    outside = work / 'outside'
    outside.mkdir()
    (outside / 'keep').write_bytes(b'untouched')
    link = work / 'link'
    os.symlink(outside, link)
    pin = model.load_pin(fixture_root.pinned, fixture_root.trust)
