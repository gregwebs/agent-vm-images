def test_check_fixture() -> None:
    """The fixture pin through the reader: status, streams, and the assertion."""
    print('check: the fixture pin')
    go_row('check accepts the fixture pin', ['check', str(fixture_root.pinned)])
    go_row('check asserts the channel',
           ['check', str(fixture_root.pinned), '--expect-channel', fixture.CHANNEL])
    go_row('check refuses a wrong asserted channel',
           ['check', str(fixture_root.pinned), '--expect-channel', '0.0.0'],
           fragments=('asserted channel',), expect=1)
    go_row('check with an empty asserted channel',
           ['check', str(fixture_root.pinned), '--expect-channel', ''],
           fragments=('asserted channel ',), expect=1)


def pin_variant(label: str, change) -> Path:
    target = driver.copy_pin(fixture_root.pinned, WORKROOT / f'pin-{label}')
    document = json.loads((target / 'pin.json').read_text())
    change(document)
    (target / 'pin.json').write_text(json.dumps(document, indent=2) + '\n')
    return target


def raw_pin_variant(label: str, raw: bytes) -> Path:
    target = driver.copy_pin(fixture_root.pinned, WORKROOT / f'raw-{label}')
    (target / 'pin.json').write_bytes(raw)
    return target


