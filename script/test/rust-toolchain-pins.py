def prepare() -> None:
    global HELPER_FIXTURE, HELPER_SHIPPED, WRITER, TOOLS, fixture_root
    binaries = WORKROOT / 'bin'
    HELPER_FIXTURE = driver.build_helper(binaries, fixture_seams=True)
    HELPER_SHIPPED = driver.build_helper(binaries, fixture_seams=False)
    WRITER = str(driver.build_writer(binaries))
    fixture_root = driver.build(WORKROOT / 'fixture', Path(WRITER))
    # The tool farm's fake bootstrap holds the installed bootstrap to this
    # distribution's digests, so it is built after the fixture it describes.
    tools_root = Path(tempfile.mkdtemp(prefix='rust-toolchain-pins-tools-')).resolve()
    TOOLS = driver.install_tools(tools_root, os.path.realpath(GPG),
                                 os.path.realpath(sys.executable),
                                 fixture_root.dist.files)
    TOOLS['root'] = str(tools_root)


def main() -> int:
    print(f'frozen: these rows are claims about the Go reader, last compared with a '
          f'second implementation on {VERIFIED_ON}')
    try:
        prepare()
        check('the writer staged the fixture pin',
              (fixture_root.pinned / 'pin.json').is_file())
        check('the staged pin is read-only',
              driver.digest_tree(fixture_root.pinned) != {})
        test_fixture_manifest()
        test_row_harness_control()
        test_check_fixture()
        test_pin_refusals()
        test_evidence_refusals()
        test_manifest_refusals()
        test_real_manifest()
        test_gpg_rows()
        test_installed()
        test_settings_toml()
        test_p5_integer_range()
        test_usage()
        test_install()
        test_deleted_oracle_is_absent()
    finally:
        shutil.rmtree(WORKROOT, ignore_errors=True)
        for row in ROW_ROOTS:
            shutil.rmtree(row, ignore_errors=True)
        if TOOLS.get('root'):
            driver.remove_tools(Path(TOOLS['root']), 'rust-toolchain-pins-tools-')
    print()
    if Failures:
        print(f'FAILED {len(Failures)} case(s): {", ".join(Failures)}')
        return 1
    print(f'rust-toolchain pins suite passed ({Passed} checks)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
