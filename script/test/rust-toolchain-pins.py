def test_os_boundary() -> None:
    """This suite's real gpg tree runs inside the OS boundary, not only the hook.

    Network isolation and the filesystem view are the operating system's work on
    both platforms; the executable allowlist is macOS's. On Linux the audit hook
    in ``guards.py`` remains the authority for which programs run.
    """
    print('boundary: the pins suite and its native gpg children are OS-confined')
    check('the pins suite itself runs inside the OS sandbox',
          os.environ.get(sandbox.SANDBOXED_ENV) == '1')
    check('a direct exec of an allowed binary copied into writable scratch is denied',
          EXEC_BOUNDARY == 'denied', EXEC_BOUNDARY)


def test_deny_guard() -> None:
    # Loopback is the one allowed network path (the transport's deadline is
    # proved against a local peer); every off-host address is refused before a
    # packet exists, which is what this control attempts.
    print('guard: off-host network and unregistered process execution are refused')
    import socket
    import subprocess

    def socket_attempt() -> bool:
        try:
            socket.socket().connect(('192.0.2.1', 9))
        except RuntimeError:
            return True
        except OSError:
            return False
        return False

    def process_attempt() -> bool:
        try:
            subprocess.run(['curl', '--version'], capture_output=True)
        except RuntimeError:
            return True
        except OSError:
            return False
        return False

    check('a direct off-host socket cannot open', socket_attempt())
    check('an unregistered downloader cannot run', process_attempt())


def check(name: str, condition: bool, detail: str = '') -> None:
    global Passed
    if condition:
        Passed += 1
        print(f'  ok   {name}')
        return
    Failures.append(name)
    print(f'  FAIL {name} {detail}')


def refuses(name: str, action, expected: str) -> None:
    try:
        action()
    except model.ToolchainError as error:
        message = str(error)
        check(name, expected in message, f'(refused with "{message}")')
        return
    except Exception:  # noqa: BLE001 - an unexpected exception is a failing case
        check(name, False, traceback.format_exc().splitlines()[-1])
        return
    check(name, False, '(no refusal)')


