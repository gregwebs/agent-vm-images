def prepare() -> None:
    global HELPER_FIXTURE, HELPER_SHIPPED, WRITER, TOOLS, fixture_root
    binaries = WORKROOT / 'bin'
    HELPER_FIXTURE = driver.build_helper(binaries, fixture_seams=True)
    HELPER_SHIPPED = driver.build_helper(binaries, fixture_seams=False)
    WRITER = str(driver.build_writer(binaries))
    fixture_root = driver.build(WORKROOT / 'fixture', Path(WRITER))
    # The tool farm's fake bootstrap holds the installed bootstrap to this
    # distribution's digests, so it is built after the fixture it describes.
    tools_root = Path(tempfile.mkdtemp(prefix='rust-toolchain-pins-tools-')).resolve()
    TOOLS = driver.install_tools(tools_root, os.path.realpath(GPG),
                                 os.path.realpath(sys.executable),
                                 fixture_root.dist.files)
    TOOLS['root'] = str(tools_root)


