#!/usr/bin/env python3
"""Fault table for the Rust example's maintenance writer.

The shell writer and the real stager are driven in temporary repository trees.
Only external I/O is substituted: the transport serves the signed fixture
distribution, and a test-owned ``python3`` launcher (first on the writer's PATH)
imports the real updater/example modules and supplies those dependencies. The
publication transaction, its rollback, the refusal rules and the signal states
are the shipped code.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from pathlib import Path

# A documented check must not write generated bytecode into the checkout, so
# this stands in for a caller that did not set the environment variable.
sys.dont_write_bytecode = True
FIXTURES = Path(__file__).resolve().parent / 'fixtures' / 'rust-toolchain'
sys.path.insert(0, str(FIXTURES))

import driver  # noqa: E402
import fixture  # noqa: E402
import rust_toolchain as model  # noqa: E402

Failures: list[str] = []
Passed = 0
FAKE_PYTHON = 'python3'
STAGER = 'script/dev/rust-toolchain-update.py'


def check(name: str, condition: bool, detail: str = '') -> None:
    global Passed
    if condition:
        Passed += 1
        print(f'  ok   {name}')
        return
    Failures.append(name)
    print(f'  FAIL {name} {detail}')


def tree(root: Path, fixture_root: driver.Fixture, launcher: Path) -> Path:
    """A minimal repository tree the writer can run against."""
    for relative in ('script/build/transactional-publish.sh',
                     'script/dev/upgrade-rust-toolchain.sh',
                     'script/dev/rust-toolchain-update.py',
                     'examples/layers/rust-dev/rust_toolchain.py',
                     'examples/layers/rust-dev/Dockerfile'):
        source = driver.REPOSITORY_ROOT / relative
        destination = root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    (root / 'examples/layers/rust-dev/Dockerfile').write_text(
        f'ARG RUST_TOOLCHAIN={fixture.CHANNEL}\nFROM fixture\n')
    return root


def environment(fixture_root: driver.Fixture, tree_root: Path, launcher_dir: Path) -> dict:
    # The launcher directory comes first so the writer's ``resolve_tool python3``
    # picks the test-owned launcher; the real gpg directory follows it untouched.
    path = ':'.join([str(launcher_dir), os.path.dirname(fixture.gpg_path()),
                     '/usr/local/bin', '/usr/bin', '/bin', '/usr/sbin', '/sbin'])
    env = {'PATH': path,
           'HOME': os.environ.get('HOME', '/tmp'),
           'FIXTURE_DIST': str(fixture_root.dist.root.parent),
           'FIXTURE_FIXTURES': str(FIXTURES),
           'FIXTURE_REPOSITORY': str(driver.REPOSITORY_ROOT),
           'FIXTURE_TREE': str(tree_root),
           'PYTHONDONTWRITEBYTECODE': '1',
           'LANG': 'C'}
    return env


def writer_check(fixture_root: driver.Fixture, tree_root: Path, launcher_dir: Path) -> bool:
    """The tree holds one complete, self-consistent pinned set."""
    env = environment(fixture_root, tree_root, launcher_dir)
    return subprocess.run(['bash', str(tree_root / 'script/dev/upgrade-rust-toolchain.sh'),
                           '--check'], cwd=str(tree_root), env=env, capture_output=True,
                          text=True, timeout=300).returncode == 0


def run_writer(fixture_root: driver.Fixture, tree_root: Path, launcher_dir: Path,
               arguments: list[str], env_extra: dict | None = None,
               timeout: int = 300) -> subprocess.CompletedProcess:
    env = environment(fixture_root, tree_root, launcher_dir)
    env.update(env_extra or {})
    return subprocess.run(['bash', str(tree_root / 'script/dev/upgrade-rust-toolchain.sh'),
                           *arguments], cwd=str(tree_root), env=env, capture_output=True,
                          text=True, timeout=timeout)


def snapshot(directory: Path) -> dict[str, str]:
    if not directory.exists():
        return {}
    return driver.digest_tree(directory)


def full_snapshot(directory: Path) -> dict[str, tuple[int, str]]:
    """Bytes *and* modes, taken by the test rather than by the writer."""
    if not directory.exists():
        return {}
    return {path.relative_to(directory).as_posix():
            (path.stat().st_mode & 0o7777, hashlib.sha256(path.read_bytes()).hexdigest())
            for path in sorted(directory.rglob('*')) if path.is_file()}


def snapshot_difference(before: dict, after: dict) -> str:
    changed = sorted(key for key in set(before) | set(after) if before.get(key) != after.get(key))
    return f'{len(changed)} differ: {changed[:4]}'


def changed_files(first: dict[str, bytes], second: dict[str, bytes]) -> int:
    return sum(1 for url in set(first) | set(second) if first.get(url) != second.get(url))


def recovery_material() -> set[str]:
    """The writer's scratch directories on the host temp dir, by path.

    A set difference per case, not a global emptiness check: another process's
    leftovers are not this suite's result.
    """
    return {str(path) for path in Path(tempfile.gettempdir()).glob('upgrade-rust-toolchain.*')}


def new_recovery_material(before: set[str]) -> list[str]:
    return sorted(recovery_material() - before)


def retained_work(result: subprocess.CompletedProcess) -> Path | None:
    match = re.search(r'STOP: recover (\S+) before', result.stdout + result.stderr)
    return Path(match.group(1)) if match else None


CP_FAILURE_TARGET = 'publish-backup/.tmp3'


def fail_last_destination(source: str) -> str:
    old = 'if ! cp "${srcs[$i]}" "${dests[$i]}"; then'
    new = 'if [ $i -eq $(( ${#srcs[@]} - 1 )) ] || ! cp "${srcs[$i]}" "${dests[$i]}"; then'
    assert old in source
    return source.replace(old, new, 1)


def truncate_then_fail(source: str) -> str:
    """A copy that really writes and truncates its destination, then fails.

    The short-circuit keeps the publisher's own rollback body in place: this
    simulates a capture that died mid-write, it does not disable a repair.
    """
    old = 'if ! cp "${srcs[$i]}" "${dests[$i]}"; then'
    new = ('if [ $i -eq $(( ${#srcs[@]} - 1 )) ]; then\n'
           '            head -c 9 "${srcs[$i]}" > "${dests[$i]}"\n'
           '            printf \'partial %s\\n\' "${dests[$i]}" \\n'
           '                >> "${FIXTURE_WRITES_LOG:-/dev/null}"\n'
           '        fi\n'
           '        if [ $i -eq $(( ${#srcs[@]} - 1 )) ] || '
           '! cp "${srcs[$i]}" "${dests[$i]}"; then')
    assert old in source
    return source.replace(old, new, 1)


def write_mkdir_shim(directory: Path, mode: str) -> Path:
    """Interrupt (or fail) the writer exactly while it creates directories."""
    directory.mkdir(parents=True, exist_ok=True)
    action = ('kill -TERM $PPID\n    sleep 0.2' if mode == 'signal'
              else 'printf \'injected mkdir failure\\n\' >&2\n    exit 1')
    shim = directory / 'mkdir'
    shim.write_text('#!/bin/sh\n'
                    '# Only the owned evidence directory is affected.\n'
                    'case "$*" in\n'
                    '  */rust-toolchain/evidence)\n'
                    f'    {action}\n'
                    '    ;;\n'
                    'esac\n'
                    f'exec {shutil.which("mkdir")} "$@"\n')
    shim.chmod(0o755)
    return directory


def write_cp_shim(directory: Path) -> Path:
    """A cp that records every call and fails one backup copy."""
    directory.mkdir(parents=True, exist_ok=True)
    shim = directory / 'cp'
    shim.write_text('#!/bin/sh\n'
                    'printf \'%s\\n\' "$*" >> "${FIXTURE_COPIES_LOG:?}"\n'
                    'case "$*" in\n'
                    f'  *{CP_FAILURE_TARGET}) printf \'injected backup failure\\n\' >&2; exit 1 ;;\n'
                    'esac\n'
                    f'exec {shutil.which("cp")} "$@"\n')
    shim.chmod(0o755)
    return directory


def destination_copies(log: Path, data: Path, dockerfile: Path) -> list[str]:
    if not log.exists():
        return []
    found = []
    for line in log.read_text().splitlines():
        parts = line.split()
        if parts and (parts[-1].startswith(str(data)) or parts[-1] == str(dockerfile)):
            found.append(line)
    return found


def write_launcher(launcher_dir: Path) -> None:
    launcher_dir.mkdir(parents=True, exist_ok=True)
    (launcher_dir / 'launcher.py').write_text(
        (Path(__file__).resolve().parent / 'fixtures' / 'rust-toolchain' / 'launcher.py')
        .read_text())
    shim = launcher_dir / FAKE_PYTHON
    shim.write_text('#!/bin/sh\n'
                    f'exec "{sys.executable}" "$(dirname "$0")/launcher.py" "$@"\n')
    shim.chmod(0o755)


def main() -> int:
    root = Path(tempfile.mkdtemp(prefix='rust-toolchain-maintenance-')).resolve()
    launcher_dir = root / 'bin'
    try:
        write_launcher(launcher_dir)
        fixture_root = driver.build(root / 'fixture')
        key = str(fixture_root.dist.key)

        # --- first adoption ---------------------------------------------------
        print('first adoption')
        work = tree(root / 'repo-first', fixture_root, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        added = Path(work / 'examples/layers/rust-dev/rust-toolchain/evidence')
        result = run_writer(fixture_root, work, launcher_dir,
                            [fixture.CHANNEL, '--rustup', fixture.RUSTUP_VERSION,
                             '--key', key, '--review-bootstrap-exception', '2026-01-02',
                             '--reviewer', 'fixture-reviewer'])
        check('first adoption published (status 0)', result.returncode == 0,
              result.stdout[-1500:] + result.stderr[-500:])
        check('pin.json written', (data / 'pin.json').is_file())
        check('evidence directory written', (added / 'arm64-cargo.asc').is_file())
        check('Dockerfile assertion unchanged when the channel matches',
              (work / 'examples/layers/rust-dev/Dockerfile').read_text()
              == f'ARG RUST_TOOLCHAIN={fixture.CHANNEL}\nFROM fixture\n',
              repr((work / 'examples/layers/rust-dev/Dockerfile').read_text()))
        check('writer ran the real stager through the fixture launcher',
              'bootstrap exception: fixture-reviewer 2026-01-02' in result.stdout)

        # --- idempotent repeat ------------------------------------------------
        print('idempotent repeat')
        before = snapshot(data)
        result = run_writer(fixture_root, work, launcher_dir, [fixture.CHANNEL])
        check('repeat run reports unchanged', 'unchanged' in result.stdout, result.stdout[-300:])
        check('repeat run changed no committed bytes', snapshot(data) == before)
        check('repeat run exit 0', result.returncode == 0, result.stderr[-300:])

        # --- --check is offline and CI-safe ----------------------------------
        print('--check')
        result = run_writer(fixture_root, work, launcher_dir, ['--check'],
                            {'GITHUB_ACTIONS': 'true'})
        check('--check passes under GITHUB_ACTIONS', result.returncode == 0,
              result.stderr[-300:])
        check('--check prints the committed selection', 'channel=' + fixture.CHANNEL
              in result.stdout)

        # --- CI refusal, usage ------------------------------------------------
        print('refusals')
        result = run_writer(fixture_root, work, launcher_dir, [fixture.CHANNEL],
                            {'GITHUB_ACTIONS': 'true'})
        check('publishing under GITHUB_ACTIONS is refused with status 2',
              result.returncode == 2, result.stderr[-200:])
        result = run_writer(fixture_root, work, launcher_dir, ['latest'])
        check('a floating channel is refused with status 2', result.returncode == 2)
        result = run_writer(fixture_root, work, launcher_dir, [])
        check('missing channel is usage (status 2)', result.returncode == 2)

        # --- partial pinned state --------------------------------------------
        print('partial state')
        broken = tree(root / 'repo-partial', fixture_root, launcher_dir)
        shutil.copytree(data, broken / 'examples/layers/rust-dev/rust-toolchain')
        (broken / 'examples/layers/rust-dev/rust-toolchain/pin.json').unlink()
        result = run_writer(fixture_root, broken, launcher_dir,
                            [fixture.CHANNEL, '--rustup', fixture.RUSTUP_VERSION,
                             '--key', key, '--review-bootstrap-exception', '2026-01-02',
                             '--reviewer', 'fixture-reviewer'])
        check('partial pinned state is refused', result.returncode == 1, result.stderr[-300:])
        check('refusal names partial/unrecognized data',
              'partial or unrecognized' in result.stderr, result.stderr[-300:])

        # --- staging failures leave every destination unchanged --------------
        print('staging failures')
        for label, setup in (
                ('second architecture bootstrap', 'bootstrap-arm64'),
                ('last component signature', 'last-signature'),
                ('manifest signature', 'manifest-signature'),
                ('wrong archive digest', 'archive-digest'),
        ):
            work = tree(root / f'repo-{setup}', fixture_root, launcher_dir)
            data = work / 'examples/layers/rust-dev/rust-toolchain'
            shutil.copytree(fixture_root.pinned, data)
            before = snapshot(data)
            recovery_before = recovery_material()
            dockerfile_before = (work / 'examples/layers/rust-dev/Dockerfile').read_bytes()
            result = run_writer(fixture_root, work, launcher_dir,
                                [fixture.CHANNEL, '--rustup', fixture.RUSTUP_VERSION],
                                dict(environment(fixture_root, work, launcher_dir),
                                     FIXTURE_FAULT=setup))
            check(f'{label}: staging fails', result.returncode != 0, result.stdout[-200:])
            check(f'{label}: no destination changed', snapshot(data) == before)
            check(f'{label}: Dockerfile unchanged',
                  (work / 'examples/layers/rust-dev/Dockerfile').read_bytes()
                  == dockerfile_before)
            check(f'{label}: no recovery material left behind',
                  not any((work / '.tmp').glob('upgrade-rust-toolchain.*')),
                  '(retained work directory)')

        # --- renewed bootstrap review ----------------------------------------
        print('bootstrap exception renewal')
        work = tree(root / 'repo-renew', fixture_root, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        shutil.copytree(fixture_root.pinned, data)
        # Upstream bootstrap bytes change: the committed exception no longer
        # describes them, so the writer must demand a renewed review.
        faulted = dict(environment(fixture_root, work, launcher_dir),
                       FIXTURE_FAULT='bootstrap-bytes')
        result = subprocess.run(['bash', str(work / 'script/dev/upgrade-rust-toolchain.sh'),
                                 fixture.CHANNEL], cwd=str(work), env=faulted,
                                capture_output=True, text=True)
        check('changed bootstrap identity without review is refused',
              result.returncode == 1 and 'hash-only bootstrap exception requires renewed review'
              in result.stdout + result.stderr, result.stdout[-300:] + result.stderr[-300:])
        check('the refusal shows the old and new identity',
              '-> new' in result.stdout + result.stderr)
        check('refused renewal left the committed pin byte-identical',
              snapshot(data) == driver.digest_tree(fixture_root.pinned))
        result = subprocess.run(['bash', str(work / 'script/dev/upgrade-rust-toolchain.sh'),
                                 fixture.CHANNEL, '--review-bootstrap-exception', '2026-02-03',
                                 '--reviewer', 'second-reviewer'], cwd=str(work), env=faulted,
                                capture_output=True, text=True)
        check('an explicit reviewed renewal publishes a visible proposal',
              result.returncode == 0, result.stdout[-400:] + result.stderr[-300:])
        document = json.loads((data / 'pin.json').read_text())
        check('renewal records the new reviewer and date',
              document['bootstrap_exception']['reviewer'] == 'second-reviewer' and
              document['bootstrap_exception']['reviewed_on'] == '2026-02-03')

        # --- first adoption, failed publication, clean retry -----------------
        print('first adoption publication failure')
        args = [fixture.CHANNEL, '--rustup', fixture.RUSTUP_VERSION, '--key', key,
                '--review-bootstrap-exception', '2026-01-02', '--reviewer', 'fixture-reviewer']
        work = tree(root / 'repo-adopt-fail', fixture_root, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        dockerfile = work / 'examples/layers/rust-dev/Dockerfile'
        dockerfile_before = dockerfile.read_bytes()
        publisher = work / 'script/build/transactional-publish.sh'
        publisher_original = publisher.read_text()
        publisher.write_text(fail_last_destination(publisher_original))
        result = run_writer(fixture_root, work, launcher_dir, args)
        check('first adoption: failed publication exits 1', result.returncode == 1,
              result.stdout[-300:] + result.stderr[-300:])
        check('first adoption: no pinned file survives the rollback',
              not data.exists() or not any(path.is_file() for path in data.rglob('*')),
              f'({[p.name for p in data.rglob("*")] if data.exists() else []})')
        check('first adoption: no empty directory survives to poison a retry',
              not data.exists(), f'({[str(p.relative_to(work)) for p in data.rglob("*")]})'
              if data.exists() else '')
        check('first adoption: the Dockerfile is unchanged',
              dockerfile.read_bytes() == dockerfile_before)
        publisher.write_text(publisher_original)
        result = run_writer(fixture_root, work, launcher_dir, args)
        check('first adoption: a clean retry after the failed rollback succeeds',
              result.returncode == 0, result.stdout[-400:] + result.stderr[-300:])
        check('first adoption: the retry published the pin', (data / 'pin.json').is_file())

        # --- interruption and failure during directory creation --------------
        print('interruption during directory creation')
        for label, mode, expected in (('signal', 'signal', 143), ('failure', 'fail', 1)):
            work = tree(root / f'repo-dirs-{mode}', fixture_root, launcher_dir)
            data = work / 'examples/layers/rust-dev/rust-toolchain'
            shim_dir = write_mkdir_shim(root / f'shim-{mode}', mode)
            env = environment(fixture_root, work, launcher_dir)
            recovery_before = recovery_material()
            env['PATH'] = f'{shim_dir}:{env["PATH"]}'
            result = subprocess.run(
                ['bash', str(work / 'script/dev/upgrade-rust-toolchain.sh'), *args],
                cwd=str(work), env=env, capture_output=True, text=True, timeout=300)
            check(f'directory creation {label}: exits {expected}',
                  result.returncode == expected,
                  f'({result.returncode}) {result.stdout[-200:]}{result.stderr[-300:]}')
            check(f'directory creation {label}: no pinned file is published',
                  not data.exists() or not any(path.is_file() for path in data.rglob('*')))
            check(f'directory creation {label}: the created parent is removed again',
                  not data.exists(), f'({[str(p.relative_to(work)) for p in data.rglob("*")]})'
                  if data.exists() else '')
            check(f'directory creation {label}: no recovery material is retained',
                  not any((work / '.tmp').glob('upgrade-rust-toolchain.*')))

        # --- publication rollback over genuinely changed bytes ---------------
        print('publication rollback')
        second = root / 'fixture-second'
        fixture.save(second, fixture.respawn(fixture_root.dist, second))
        fixture_second = driver.load_fixture(second, fixture_root.pinned)
        work = tree(root / 'repo-rollback', fixture_second, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        shutil.copytree(fixture_root.pinned, data)
        dockerfile = work / 'examples/layers/rust-dev/Dockerfile'
        dockerfile_before = (dockerfile.read_bytes(), dockerfile.stat().st_mode)
        before = full_snapshot(data)
        writes = root / 'publication-writes.log'
        publisher = work / 'script/build/transactional-publish.sh'
        publisher_original = publisher.read_text()
        check('the second upstream build really changes the committed bytes',
              changed_files(fixture_root.dist.files, fixture_second.dist.files) > 20,
              f'({changed_files(fixture_root.dist.files, fixture_second.dist.files)})')
        # The failing copy truncates its destination first: that is the partial
        # write the publisher must repair, not a copy that never started.
        publisher.write_text(truncate_then_fail(publisher_original))
        result = run_writer(fixture_second, work, launcher_dir, [fixture.CHANNEL],
                            {'FIXTURE_WRITES_LOG': str(writes)})
        check('failed publication exits 1', result.returncode == 1,
              result.stdout[-400:] + result.stderr[-400:])
        check('the failing destination really was written and truncated',
              writes.is_file() and str(dockerfile) in writes.read_text(),
              writes.read_text() if writes.is_file() else '(no write log)')
        check('failed publication restored every destination byte and mode',
              full_snapshot(data) == before,
              f'({snapshot_difference(before, full_snapshot(data))})')
        check('failed publication restored the failing destination itself',
              (dockerfile.read_bytes(), dockerfile.stat().st_mode) == dockerfile_before)

        # The same fault against a publisher with rollback disabled must fail the
        # assertions above; that is what makes them a rollback oracle.
        work = tree(root / 'repo-no-rollback', fixture_second, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        shutil.copytree(fixture_root.pinned, data)
        dockerfile = work / 'examples/layers/rust-dev/Dockerfile'
        dockerfile_before = (dockerfile.read_bytes(), dockerfile.stat().st_mode)
        before = full_snapshot(data)
        publisher = work / 'script/build/transactional-publish.sh'
        publisher.write_text(
            truncate_then_fail(publisher.read_text()).replace(
                'for ((j=i; j>=0; j--)); do', 'for ((j=-1; j>=0; j--)); do'))
        result = run_writer(fixture_second, work, launcher_dir, [fixture.CHANNEL],
                            {'FIXTURE_WRITES_LOG': str(writes)})
        check('the no-rollback control still reports a failure', result.returncode != 0)
        check('the rollback oracle rejects a publisher that does not roll back',
              full_snapshot(data) != before or
              (dockerfile.read_bytes(), dockerfile.stat().st_mode) != dockerfile_before,
              'a no-rollback publisher passed every restoration assertion')

        # --- incomplete backup: zero writes, zero restoration ----------------
        print('incomplete backup')
        work = tree(root / 'repo-backup-fail', fixture_second, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        shutil.copytree(fixture_root.pinned, data)
        dockerfile = work / 'examples/layers/rust-dev/Dockerfile'
        dockerfile_before = (dockerfile.read_bytes(), dockerfile.stat().st_mode)
        before = full_snapshot(data)
        copies = root / 'backup-copies.log'
        cp_dir = write_cp_shim(root / 'shim-cp')
        env = environment(fixture_second, work, launcher_dir)
        env['PATH'] = f'{cp_dir}:{env["PATH"]}'
        env['FIXTURE_COPIES_LOG'] = str(copies)
        result = subprocess.run(
            ['bash', str(work / 'script/dev/upgrade-rust-toolchain.sh'), fixture.CHANNEL],
            cwd=str(work), env=env, capture_output=True, text=True, timeout=300)
        check('a failed backup exits 1', result.returncode == 1,
              result.stdout[-300:] + result.stderr[-300:])
        check('a failed backup copies nothing into a destination',
              not destination_copies(copies, data, dockerfile),
              destination_copies(copies, data, dockerfile))
        check('a failed backup changed no destination byte or mode',
              full_snapshot(data) == before and
              (dockerfile.read_bytes(), dockerfile.stat().st_mode) == dockerfile_before)

        # --- restoration failure: status 3 with usable recovery evidence -----
        print('restoration failure')
        work = tree(root / 'repo-restore-fail', fixture_second, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        shutil.copytree(fixture_root.pinned, data)
        blocked = data / 'evidence/rustup-amd64.sha256'
        before = full_snapshot(data)
        os.chmod(blocked, 0o400)
        retained = None
        try:
            result = run_writer(fixture_second, work, launcher_dir, [fixture.CHANNEL])
            retained = retained_work(result)
            check('a failed restoration exits 3', result.returncode == 3,
                  f'({result.returncode}) {result.stdout[-300:]}{result.stderr[-300:]}')
            check('a failed restoration still restored the earlier destinations',
                  (data / 'pin.json').read_bytes() ==
                  (fixture_root.pinned / 'pin.json').read_bytes())
            check('a failed restoration retains a recovery map and backups',
                  retained is not None and (retained / 'recovery.json').is_file() and
                  (retained / 'publish-backup').is_dir(),
                  str(retained))
            if retained is not None:
                plan = json.loads((retained / 'recovery.json').read_text())
                check('the recovery map names every destination and its ownership',
                      len(plan['destinations']) == 20 and
                      all({'path', 'existed', 'backup'} <= set(entry)
                          for entry in plan['destinations']))
                check('the recovery map records the directories this run owned',
                      plan['owned_directories'] == ['examples/layers/rust-dev/rust-toolchain',
                                                    'examples/layers/rust-dev/rust-toolchain/evidence'])
        finally:
            os.chmod(blocked, 0o600)
            if retained is not None:
                shutil.rmtree(retained, ignore_errors=True)
        check('the restored bytes after a failed restoration match the snapshot for earlier files',
              full_snapshot(data)['pin.json'] == before['pin.json'])

        # --- signal windows --------------------------------------------------
        # Only the delivery point is injected: a signal cannot be timed from
        # outside, and the state machine that decides the result is the shipped one.
        print('publication signal windows')
        windows = {
            'backup': ('backup', '  if ! : >"$backup_dir/.complete"; then',
                       '  kill -TERM $$\n  if ! : >"$backup_dir/.complete"; then', 3,
                       'interrupted while taking backups'),
        }
        for label, (where, needle, replacement, code, message) in windows.items():
            work = tree(root / f'repo-signal-{label}', fixture_second, launcher_dir)
            data = work / 'examples/layers/rust-dev/rust-toolchain'
            shutil.copytree(fixture_root.pinned, data)
            before = full_snapshot(data)
            dockerfile = work / 'examples/layers/rust-dev/Dockerfile'
            dockerfile_before = (dockerfile.read_bytes(), dockerfile.stat().st_mode)
            target = work / 'script/build/transactional-publish.sh'
            original = target.read_text()
            check(f'{where}: the {label} signal point exists', needle in original)
            target.write_text(original.replace(needle, replacement, 1))
            retained = None
            try:
                result = run_writer(fixture_second, work, launcher_dir, [fixture.CHANNEL])
                retained = retained_work(result)
                check(f'signal {label}: exits {code}', result.returncode == code,
                      f'({result.returncode}) {result.stdout[-200:]}{result.stderr[-300:]}')
                check(f'signal {label}: reports the documented outcome',
                      message in result.stdout + result.stderr,
                      result.stderr[-300:])
                check(f'signal {label}: sources are unchanged',
                      full_snapshot(data) == before and
                      (dockerfile.read_bytes(), dockerfile.stat().st_mode) == dockerfile_before)
                check(f'signal {label}: recovery material is retained',
                      retained is not None and (retained / 'recovery.json').is_file(),
                      str(retained))
            finally:
                if retained is not None:
                    shutil.rmtree(retained, ignore_errors=True)

        for label, where, needle, replacement, code, message in (
                ('complete-backup', 'publisher',
                 '    for i in "${!srcs[@]}"; do\n        if ! cp "${srcs[$i]}"',
                 '    kill -TERM $$\n    for i in "${!srcs[@]}"; do\n'
                 '        if ! cp "${srcs[$i]}"', 143,
                 'sources restored'),
                ('published-window', 'writer', 'published=1\ncase "$status" in',
                 'published=1\nkill -TERM $$\ncase "$status" in', 3, 'undecided'),
                ('decided-window', 'writer', 'decided=1\npublishing=0',
                 'decided=1\npublishing=0\nkill -TERM $$', 3, 'undecided'),
        ):
            work = tree(root / f'repo-signal-{label}', fixture_second, launcher_dir)
            data = work / 'examples/layers/rust-dev/rust-toolchain'
            shutil.copytree(fixture_root.pinned, data)
            before = full_snapshot(data)
            dockerfile = work / 'examples/layers/rust-dev/Dockerfile'
            dockerfile_before = (dockerfile.read_bytes(), dockerfile.stat().st_mode)
            target = (work / 'script/build/transactional-publish.sh' if where == 'publisher'
                      else work / 'script/dev/upgrade-rust-toolchain.sh')
            original = target.read_text()
            check(f'{label}: the signal point exists', needle in original)
            target.write_text(original.replace(needle, replacement, 1))
            retained = None
            try:
                result = run_writer(fixture_second, work, launcher_dir, [fixture.CHANNEL])
                retained = retained_work(result)
                check(f'signal {label}: exits {code}', result.returncode == code,
                      f'({result.returncode}) {result.stdout[-200:]}{result.stderr[-400:]}')
                check(f'signal {label}: reports the documented outcome',
                      message in result.stdout + result.stderr, result.stderr[-400:])
                # These two windows sit after publication completed, so the
                # state table promises a decision, not a restore: the alternatives
                # are "unchanged" and "one complete published set".
                check(f'signal {label}: sources are unchanged or a complete published set',
                      (full_snapshot(data) == before and
                       (dockerfile.read_bytes(), dockerfile.stat().st_mode) == dockerfile_before)
                      or writer_check(fixture_second, work, launcher_dir),
                      snapshot_difference(before, full_snapshot(data)))
                check(f'signal {label}: recovery material is retained',
                      retained is not None and (retained / 'recovery.json').is_file(),
                      str(retained))
            finally:
                if retained is not None:
                    shutil.rmtree(retained, ignore_errors=True)

        # --- fixture-child guards --------------------------------------------
        # A fixture child must be deny-by-default *before* it imports the modules
        # under test, or a direct urllib/subprocess fallback in the shipped stager
        # would reach the maintainer's network and never show up in a green suite.
        print('fixture child guards')
        control_env = environment(fixture_root, work, launcher_dir)
        control_env['PYTHONDONTWRITEBYTECODE'] = '1'
        shipped = subprocess.run([str(launcher_dir / FAKE_PYTHON), '--guard-self-test'],
                                 env=control_env,
                                 capture_output=True, text=True, timeout=120)
        result = shipped
        check('the shipped fixture child denies a direct socket',
              'socket=denied' in result.stdout, result.stdout + result.stderr)
        check('the shipped fixture child denies an absolute downloader',
              'downloader=denied' in result.stdout, result.stdout + result.stderr)
        check('the shipped fixture child denies nested unregistered execution',
              'nested=denied' in result.stdout, result.stdout + result.stderr)
        check('the shipped fixture child guard control exits 0', result.returncode == 0,
              f'({result.returncode}) {result.stdout}{result.stderr}')
        result = subprocess.run([sys.executable, str(FIXTURES / 'guard-self-control.py')],
                                env=control_env, capture_output=True, text=True, timeout=120)
        check('the guard control still allows the resolved gpg executable',
              'allowed-gpg=allowed' in result.stdout, result.stdout + result.stderr)
        check('the independent guard control exits 0', result.returncode == 0,
              f'({result.returncode}) {result.stdout}{result.stderr}')
        for label, output in (('the shipped fixture child', shipped.stdout),
                              ('the independent guard control', result.stdout)):
            check(f'{label} authorizes the executable, not the argv tail',
                  'identity=denied' in output, output)

        # --- OS-level isolation for fixture child trees ----------------------
        # The in-process hook cannot see a native child, so the second boundary is
        # the operating system: network isolation on both platforms, and an
        # executable allowlist only on macOS (a Linux allowed loader defeats one;
        # the audit hook is the exec authority there). This control re-execs
        # itself inside the sandbox and then attempts the same escapes as a
        # *native* grandchild that never imports the guard. Without a sandbox tool
        # it refuses with the exact prerequisite instead of claiming the
        # in-process guard is enough.
        print('fixture child OS isolation')
        result = subprocess.run([sys.executable, str(FIXTURES / 'sandbox-self-control.py')],
                                env=control_env, capture_output=True, text=True, timeout=600)
        if 'ISOLATION-UNAVAILABLE' in result.stdout + result.stderr:
            check('an OS sandbox boundary exists for fixture child trees', False,
                  (result.stdout + result.stderr).strip())
        else:
            # Each row is the denial of the *direct* attempt the control makes. On
            # Linux `nested-copy-exec` is Landlock refusing that exec, not a claim
            # that no other route to running the copy exists.
            for name in ('network', 'executable', 'nested-network', 'nested-exec',
                         'nested-copy-exec'):
                check(f'the OS sandbox denies the direct attempt {name}',
                      f'{name}=denied' in result.stdout,
                      result.stdout + result.stderr)
            check('the OS sandbox still allows the real gpg', 'gpg=allowed' in result.stdout,
                  result.stdout + result.stderr)
            check('the OS sandbox still allows the test-owned loopback peer',
                  'loopback=allowed' in result.stdout, result.stdout + result.stderr)
            check('the OS isolation control exits 0', result.returncode == 0,
                  f'({result.returncode}) {result.stdout}{result.stderr}')

        # A host without the prerequisite must fail the child *before* it imports
        # or runs anything under test. The probe above proves the boundary when it
        # exists; this proves the failure when it does not, which is the difference
        # between a refused claim and a printed diagnostic over unsandboxed work.
        unavailable = dict(control_env, FIXTURE_SANDBOX_UNAVAILABLE='1')
        result = subprocess.run([str(launcher_dir / FAKE_PYTHON), '--guard-self-test'],
                                env=unavailable, capture_output=True, text=True, timeout=120)
        check('a missing isolation prerequisite exits nonzero', result.returncode != 0,
              f'({result.returncode}) {result.stdout}{result.stderr}')
        check('a missing isolation prerequisite names itself',
              'ISOLATION-UNAVAILABLE' in result.stderr, result.stderr)
        check('a missing isolation prerequisite runs no code under test',
              result.stdout.strip() == '', result.stdout)

        # --- documented commands write no bytecode ---------------------------
        print('no bytecode in a read-only checkout')
        work = tree(root / 'repo-bytecode', fixture_root, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        shutil.copytree(fixture_root.pinned, data)
        clean_env = {name: value for name, value in
                     environment(fixture_root, work, launcher_dir).items()
                     if name not in ('PYTHONDONTWRITEBYTECODE', 'PYTHONPYCACHEPREFIX')}
        # The stager is invoked without arguments: argparse then reports usage (2),
        # but the module import that would write bytecode has already run. The
        # fixture key is not the production trust root, so a real `check` here
        # would refuse for an unrelated reason.
        for label, argv, expected in (
                ('the stager entrypoint',
                 [sys.executable, str(work / 'script/dev/rust-toolchain-update.py')], 2),
                ('the shell writer --check',
                 ['bash', str(work / 'script/dev/upgrade-rust-toolchain.sh'), '--check'], 0),
        ):
            result = subprocess.run(argv, cwd=str(work), env=clean_env, capture_output=True,
                                    text=True, timeout=300)
            check(f'{label} runs without the caller setting the variable',
                  result.returncode == expected,
                  f'({result.returncode}) {result.stderr[-300:]}')
            caches = sorted(path.relative_to(work).as_posix() for path in work.rglob('__pycache__'))
            check(f'{label} writes no bytecode into the tree', caches == [], f'({caches})')
        for relative in ('examples/layers/rust-dev', 'script/dev',
                         'script/test/fixtures/rust-toolchain'):
            caches = sorted((driver.REPOSITORY_ROOT / relative).glob('__pycache__'))
            check(f'this suite left no bytecode in {relative}', caches == [], f'({caches})')

        # --- signal during staging -------------------------------------------
        print('signal during staging')
        work = tree(root / 'repo-signal-stage', fixture_root, launcher_dir)
        data = work / 'examples/layers/rust-dev/rust-toolchain'
        shutil.copytree(fixture_root.pinned, data)
        before = snapshot(data)
        env = environment(fixture_root, work, launcher_dir)
        recovery_before = recovery_material()
        env['FIXTURE_FAULT'] = 'slow-manifest'
        process = subprocess.Popen(['bash', str(work / 'script/dev/upgrade-rust-toolchain.sh'),
                                    fixture.CHANNEL], cwd=str(work), env=env,
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        time.sleep(3.0)
        process.send_signal(signal.SIGTERM)
        stdout, stderr = process.communicate(timeout=120)
        check('signal while staging reports 128+15', process.returncode == 143,
              f'({process.returncode}) {stderr[-200:]}')
        check('sources unchanged after a staging signal', snapshot(data) == before)
        check('staging signal left no recovery material',
              not any((work / '.tmp').glob('upgrade-rust-toolchain.*')))
    finally:
        shutil.rmtree(root, ignore_errors=True)
