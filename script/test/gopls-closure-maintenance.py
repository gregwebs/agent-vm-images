def slow_publication(source: str) -> str:
    """Announce publication of the last destination, then wait before copying it."""
    old = 'for i in "${!srcs[@]}"; do\n        if ! cp "${srcs[$i]}" "${dests[$i]}"; then'
    new = ('for i in "${!srcs[@]}"; do\n'
           '        if [ $i -eq $(( ${#srcs[@]} - 1 )) ]; then\n'
           '            : > "${FIXTURE_PUBLISH_MARKER:?}"\n'
           '            sleep 6\n'
           '        fi\n'
           '        if ! cp "${srcs[$i]}" "${dests[$i]}"; then')
    assert old in source
    return source.replace(old, new, 1)


