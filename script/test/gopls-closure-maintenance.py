def second_go_root(pinned: str) -> tuple[Path, str] | None:
    """A second *real* local Go toolchain, if this host has one.

    No fake compiler is invented for the carry control: the point of the case is
    that a genuinely different compiler produces genuinely different build settings.
    """
    candidate = shutil.which('go')
    if candidate is None:
        return None
    real = Path(os.path.realpath(candidate))
    env = {'PATH': f'{real.parent}:/usr/bin:/bin', 'HOME': os.environ.get('HOME', '/tmp'),
           'GOENV': 'off', 'GOWORK': 'off'}
    try:
        proc = subprocess.run([str(real), 'env', 'GOROOT', 'GOVERSION'], capture_output=True,
                              text=True, timeout=120, env=env)
    except OSError:
        return None
    if proc.returncode != 0:
        return None
    lines = proc.stdout.split()
    if len(lines) < 2:
        return None
    root, version = Path(lines[0]), lines[1]
    if version.startswith('go'):
        version = version[2:]
    if version == pinned or not (root / 'bin' / 'go').is_file():
        return None
    return root, version


def full_inventory(go_root: Path, launcher_dir: Path,
                   alternate: Path | None) -> list[str]:
    allowed = set(writer_inventory(go_root, launcher_dir))
    if alternate is not None:
        allowed |= set(go_executables(alternate))
    return sorted(allowed)


def writer_inventory(go_root: Path, launcher_dir: Path) -> list[str]:
    """The explicit executable inventory for the writer-inclusive boundary.

    Shells are named both as the literal this suite starts and as the file it
    resolves to. On a merged-``/usr`` host (Ubuntu, and so CI) ``/bin/sh`` *is*
    ``/usr/bin/sh``, so a realpath-only inventory loses every ``/bin`` name -- and
    the boundary then has no shell to start at the path it is asked for, nor for a
    ``#!/bin/sh`` script's shebang.
    """
    allowed = set(go_executables(go_root))
    for name in WRITER_TOOLS:
        found = shutil.which(name)
        if found is not None:
            allowed.add(os.path.realpath(found))
    for path in SYSTEM_SHELLS:
        if os.access(path, os.X_OK):
            allowed.add(path)
            allowed.add(os.path.realpath(path))
    for path in sorted(launcher_dir.iterdir()):
        allowed.add(os.path.realpath(path))
    return sorted(allowed)


def check(name: str, condition: bool, detail: str = '') -> None:
    global Passed
    if condition:
        Passed += 1
        print(f'  ok   {name}')
        return
    Failures.append(name)
    print(f'  FAIL {name} {detail}')


SIGNAL_REQUEST = 'signal-request'
SIGNAL_RESULT = 'signal-result'
